"""Lethal against benign tar at L = 16: delay of the first clone (t_rep, Kaplan-Meier median as in Methods) and of the
first heritable material (first sampled step at which at least 10% of 16 random cells are heritable; median over worlds).
Post hoc, 2026-10-09, no new runs.   .venv/bin/python timing_heritable.py  ->  results/stageI/TIMING.md
"""
from __future__ import annotations

import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results")


def km_median(t: np.ndarray) -> float:
    t = np.sort(t[np.isfinite(t)])
    return float(t[int(np.ceil(len(t) / 2)) - 1])   # no censoring here: the smallest t at which S(t) <= 0.5


def first_heritable(path: str, label_prefix: str, L: int, thr: float) -> np.ndarray:
    F = pd.read_csv(path)
    F = F[F.label.str.startswith(label_prefix) & (F.tape_len == L)]
    out = []
    for _, d in F.groupby("seed"):
        d = d.sort_values("step")
        hit = d[d.frac_heritable >= thr]
        out.append(float(hit.step.iloc[0]) if len(hit) else np.nan)
    return np.array(out)


def main() -> None:
    I = pd.read_csv(os.path.join(R, "stageI", "stageI", "stage_g_runs.csv"))
    G = pd.read_csv(os.path.join(R, "stageG", "stageG", "stage_g_runs.csv"))
    tI, tG = I.t_rep.astype(float).values, G[G.L == 16].t_rep.astype(float).values
    out = ["# Lethal against benign tar at L = 16: two ways of dating life (generated by timing_heritable.py; do not edit)", ""]
    out.append(f"- first clone (t_rep), Kaplan-Meier median: lethal {km_median(tI):,.0f}, benign {km_median(tG):,.0f}, ratio {km_median(tI) / km_median(tG):.0f}")
    out.append(f"- first clone, plain median: lethal {np.median(tI):,.0f}, benign {np.median(tG):,.0f}")
    for thr in (0.1, 0.5):
        hI = first_heritable(os.path.join(R, "stageI", "c4", "functional.csv"), "lethal", 16, thr)
        hG = first_heritable(os.path.join(R, "stageG", "c4", "functional.csv"), "none@closure", 16, thr)
        out.append(f"- first step with heritable fraction >= {thr}: lethal median {np.nanmedian(hI):,.0f} ({np.isfinite(hI).sum()}/{len(hI)} worlds), "
                   f"benign median {np.nanmedian(hG):,.0f} ({np.isfinite(hG).sum()}/{len(hG)}), ratio {np.nanmedian(hI) / np.nanmedian(hG):.0f}")
    open(os.path.join(R, "stageI", "TIMING.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
