"""PE (REVISION_PREREG): parent x environment serial transfer, L = 16. Output: results/pe/PE_MATRIX.md, pe_matrix.csv
    .venv/bin/python pe_matrix.py
"""
from __future__ import annotations

import os
import sys
import time

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "manuscript", "figures"))
import serial_retention as S  # noqa: E402
import soup_stills as ss  # noqa: E402
from population_sample import STAGES  # noqa: E402

L = 16
OUT = os.path.join(HERE, "results", "pe")


def parse(t):
    return np.array([int(b, 16) for b in t.split()], np.uint8)


def parents():
    gi = pd.read_csv(os.path.join(HERE, "results", "stageI", "stageI", "stage_g_runs.csv"))
    s4009 = gi[gi.seed == 4009].final_tape.iloc[0]
    rng = np.random.default_rng(20261019)
    tT = rng.integers(0, 256, 12, dtype=np.uint8)
    tS = rng.integers(0, 256, 10, dtype=np.uint8)
    return [("pusher", "open", " ".join(["01 c5"] * 8)),
            ("return closer", "regenerator", "ad e3 21 e3 21 c0 ad c0 ad e3 21 e3 21 c0 ad c0"),
            ("block-copy R", "regenerator", " ".join(["44 5e ed b0"] * 4)),
            ("block-copy T", "transmitter", "b0 5e ed b0 " + S.hx(tT)),
            ("lethal-tar closer 4009", "transmitter", s4009),
            ("self-initialising closer", "transmitter", "2e 00 1e 10 ed b0 " + S.hx(tS))]


def soup_of(stage, seed, step=None):
    runs_dir, csv, zh, abl = STAGES[stage]
    g = pd.read_csv(csv)
    w = g[(g.L == L) & (g.seed == seed)].iloc[0]
    stem = os.path.join(runs_dir, f"{w['label']}_L{L}_st128_k4_s{seed}")
    snaps = ss.snapshot_files(stem)
    if step is None:
        f = [x for x in snaps if x[0] == "final"][0]
    else:
        f = min([x for x in snaps if x[1] is not None], key=lambda x: abs(x[1] - step))
    return ss.load(f[2], L), f[0]


def main():
    os.makedirs(OUT, exist_ok=True)
    gfin, _ = soup_of("G", 2001)
    ifin, _ = soup_of("I", 4001)
    gopen, gname = soup_of("G", 2001, 5000)
    envs = [("random partners, benign", None, False, None), ("random partners, lethal", None, True, None),
            ("closed benign world", gfin, False, None), ("lethal world", ifin, True, None),
            (f"open phase ({gname})", gopen, False, None), ("random registers", None, False, "randreg")]
    rows = []
    for env, pool, zh, variant in envs:
        if variant:
            import dial_soups
            dial_soups._patch(variant)
        for name, mode, t in parents():
            t0 = time.time()
            gt = {"key": name, "kind": mode, "tape": parse(t), "sup": (), "zh": zh}
            df, meta = S.run_genotype(gt, seed=20261019, pool=pool)
            s = S.sites(df, meta)
            d8 = df[(df.gen == 8) & df.identifiable]
            row = {"environment": env, "parent": name, "mode": mode, "tape": t, "alive_g8": meta["ctrl_alive_g8"], "alive_g1": meta["ctrl_alive_g1"],
                   "sites_g1": int(s[s.gen == 1].transmissible.sum()), "sites_g8": int(s[s.gen == 8].transmissible.sum()),
                   "lost_g8": float(d8.lost.mean()), "erased_g8": float(d8.erased.mean()), "retained_g8": float(d8.retained.mean()), "wall_s": round(time.time() - t0, 1)}
            rows.append(row)
            print(row, flush=True)
        if variant:   # restore the standard executors
            import importlib
            from algocell_exp import assay, exectrace
            importlib.reload(assay)
            importlib.reload(exectrace)
            importlib.reload(S)
    D = pd.DataFrame(rows)
    D.to_csv(os.path.join(OUT, "pe_matrix.csv"), index=False)
    lines = ["# PE — parent × environment serial transfer, L = 16 (generated by `pe_matrix.py`)", "",
             "Each cell: unmutated lineages alive after eight transfers / transmissible sites after one and eight transfers.", "",
             "| parent (mode) | " + " | ".join(e[0] for e in envs) + " |", "|---|" + "---|" * len(envs)]
    for name, mode, _ in parents():
        cells = []
        for env, *_ in envs:
            r = D[(D.parent == name) & (D.environment == env)].iloc[0]
            cells.append(f"{r.alive_g8:.2f} / {r.sites_g1}, {r.sites_g8}")
        lines.append(f"| {name} ({mode}) | " + " | ".join(cells) + " |")
    ok1 = []
    for _, r in D.iterrows():
        if r.alive_g8 >= 0.5 and r["mode"] == "regenerator":
            ok1.append(r.sites_g8 <= 2)
        if r.alive_g8 >= 0.5 and r["mode"] == "transmitter":
            ok1.append(r.sites_g8 >= 8)
    pu = D[D.parent == "pusher"]
    rr = D[D.environment == "random registers"]
    lines += ["", f"- PE1 (mode belongs to the parent where lineages survive): {'met' if all(ok1) else 'NOT met'} ({sum(ok1)} of {len(ok1)} surviving parent–environment cells as predicted)",
              f"- PE2 (pusher lost, ≤ 0.2 alive at eight, everywhere): {'met' if (pu.alive_g8 <= 0.2).all() else 'NOT met'} (alive {pu.alive_g8.min():.2f}–{pu.alive_g8.max():.2f})",
              "- PE3 (random registers): " + "; ".join(f"{r.parent} {r.alive_g8:.2f}" for r in rr.itertuples())]
    open(os.path.join(OUT, "PE_MATRIX.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
