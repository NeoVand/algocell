"""N3 (after the critic): the parts table restricted to first founders (one per world), and their families.

PARTS_v6 pooled all 32 founders; FOUNDERS2 separates the first founder in each world from later conversions. This table
reports the word shares for first founders only, the soup composition at the same snapshot (the base rate the carrier
shares must be read against), and the family of each first founder (return-closer motif `XX e3 21 e3 21 RET XX RET`).

    .venv/bin/python lod_parts_first.py      # results/lod/PARTS_FIRST.md
"""
from __future__ import annotations

import os
import re

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.environ.get("LOD_OUT", os.path.join(HERE, "results", "lod"))   # path only (N6 replication)
MOTIF = re.compile(r"^(..) e3 21 e3 21 (e0|c0) \1 (e0|c0)")


def main():
    P = pd.read_csv(os.path.join(OUT, "parts_v6.csv"))
    F = pd.read_csv(os.path.join(OUT, "founders2.csv"))
    F1 = F[F["first"] == True]  # noqa: E712
    Q = P.merge(F1[["seed", "F_step"]], on=["seed", "F_step"])
    carrier_nc = (Q.share_noncopier / Q.share.replace(0, float("nan"))).median()
    fam = F1.F_tape.map(lambda t: "return-closer motif" if MOTIF.search(t) else ("LDIR block copier" if "ed b0" in t else "other"))
    md = ["# N3: founders' parts, first founders only (generated by `lod_parts_first.py`)", "",
          f"- first founders: {Q.groupby(['seed', 'F_step']).ngroups} (one per closed world); executed words: {len(Q)}",
          f"- median share of cells carrying an executed word, last snapshot before the founder: {Q.share.median():.5f} "
          f"(random-tape baseline ≈ 0.00024; ratio ≈ {Q.share.median() / 0.00024:.1f})",
          f"- of carriers, share that are non-copiers (median over words): {carrier_nc:.2f}; non-copiers in the soup at the same "
          f"snapshot: {F1.soup_noncopier.min():.2f}–{F1.soup_noncopier.max():.2f} (open copiers {F1.soup_open.min():.2f}–{F1.soup_open.max():.2f})",
          "- families of first founders: " + ", ".join(f"{k} {v}" for k, v in fam.value_counts().items()),
          *[f"- word `{w}` (where executed): carried by a median {Q[Q.word == w].share.median():.4f} of cells (range {Q[Q.word == w].share.min():.4f}–{Q[Q.word == w].share.max():.4f}; {int((Q.word == w).sum())} founders)"
            for w in ("21 e3", "21 e0") if (Q.word == w).any()],
          f"- first founders whose soup snapshot already held confined copiers: {int((F1.soup_confined > 0).sum())} of {len(F1)} (max share {F1.soup_confined.max():.4f})", ""]
    for r, f in zip(F1.itertuples(), fam):
        md.append(f"  - world {r.seed}: `{r.F_tape}` ({f})")
    open(os.path.join(OUT, "PARTS_FIRST.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
