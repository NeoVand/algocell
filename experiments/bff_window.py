"""The open window of the wrapping literal push with lethal brackets (Model 5): ∫ n dt of the all-P class, in
tape-epochs, from the recorded samples (every 64 epochs; trapezoid rule; N = 2^17). Output: results/review_r2/BFF_WINDOW.md
"""
import json
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
N = 2 ** 17


def allp(s):
    for t in s["top"]:
        tp = t["tape"]
        if tp and set(tp[i:i + 2] for i in range(0, len(tp), 2)) == {"50"}:
            return t["share"]
    return 0.0


runs = pd.read_csv(os.path.join(HERE, "results", "bff", "runs.csv"))
rows = []
for r in runs[runs.variant.isin(["wraplit", "stdlit"])].itertuples():
    p = os.path.join(HERE, "runs", "bff_modal", "bff", r.run, "samples.jsonl")
    if not os.path.exists(p):
        continue
    S = [json.loads(l) for l in open(p)]
    e = np.array([s["epoch"] for s in S], float)
    v = np.array([allp(s) for s in S], float)
    tot = float(np.trapezoid(v * N, e))
    dec = (e <= 256)
    rows.append({"variant": r.variant, "run": r.run, "share_e64": float(v[e == 64][0]) if (e == 64).any() else np.nan, "share_e256": float(v[e == 256][0]) if (e == 256).any() else np.nan,
                 "share_end": float(v[-1]), "window_total": tot, "window_to_256": float(np.trapezoid(v[dec] * N, e[dec])), "window_after_256": tot - float(np.trapezoid(v[dec] * N, e[dec]))})
D = pd.DataFrame(rows)
D.to_csv(os.path.join(HERE, "results", "review_r2", "bff_window.csv"), index=False)
lines = ["# Open window of the BFF literal push with lethal brackets (generated by `bff_window.py`)", ""]
for v, d in D.groupby("variant"):
    lines.append(f"- {v} ({len(d)} soups): all-P share at epoch 64 {d.share_e64.min():.3f}–{d.share_e64.max():.3f}, at 256 {d.share_e256.min():.4f}–{d.share_e256.max():.4f}, at the end {d.share_end.min():.4f}–{d.share_end.max():.4f}; "
                 f"∫ n dt to epoch 256 {d.window_to_256.min():.2e}–{d.window_to_256.max():.2e}, after 256 {d.window_after_256.min():.2e}–{d.window_after_256.max():.2e}, total {d.window_total.min():.2e}–{d.window_total.max():.2e} tape-epochs")
open(os.path.join(HERE, "results", "review_r2", "BFF_WINDOW.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
