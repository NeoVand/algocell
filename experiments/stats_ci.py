"""Uncertainty across worlds for the principal quantities (round-2 review): medians with 95% bootstrap intervals
(10,000 resamples of worlds), Kaplan–Meier medians of t_rep with bootstrap intervals, Wilson intervals for counts, and
the threshold grid summary. Output: results/review_r2/STATS.md (source of Extended Data Table 3).

    .venv/bin/python stats_ci.py
"""
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results")
rng = np.random.default_rng(20261015)
B = 10000


def boot_median(x):
    x = np.asarray(pd.Series(x).dropna(), float)
    if len(x) == 0:
        return np.nan, np.nan, np.nan, 0
    idx = rng.integers(0, len(x), size=(B, len(x)))
    m = np.median(x[idx], axis=1)
    return float(np.median(x)), float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5)), len(x)


def km_median(t, horizon):
    """Kaplan–Meier median of event times t (NaN or <= 0 = censored at horizon)."""
    t = np.asarray(t, float)
    ev = np.isfinite(t) & (t > 0)
    times = np.where(ev, t, horizon)
    order = np.argsort(times, kind="stable")
    times, ev = times[order], ev[order]
    n, s = len(times), 1.0
    for i, (ti, e) in enumerate(zip(times, ev)):
        if e:
            s *= 1 - 1 / (n - i)
            if s <= 0.5:
                return ti
    return np.inf


def boot_km(t, horizon):
    t = np.asarray(t, float)
    m0 = km_median(t, horizon)
    ms = np.array([km_median(t[rng.integers(0, len(t), len(t))], horizon) for _ in range(2000)])
    return m0, float(np.percentile(ms, 2.5)), float(np.percentile(ms, 97.5)), len(t)


def wilson(k, n, z=1.96):
    if n == 0:
        return np.nan, np.nan
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


rows = []
G = pd.read_csv(os.path.join(R, "stageG", "stageG", "stage_g_runs.csv"))
E = pd.read_csv(os.path.join(R, "stageG", "exact_copy.csv"))
M = pd.read_csv(os.path.join(R, "mutscan", "mutscan_tapes.csv"))
for L in (16, 20, 50, 64):
    g = G[G.L == L]
    for col, lab in (("first_copied", "first replicator: share of 256 random partners copied"), ("first_damaged", "first replicator: share of encounters with self-damage"),
                     ("first_gen2", "first replicator: gen2")):
        m, lo, hi, n = boot_median(g[col])
        rows.append((lab, f"Z80, L = {L}", m, lo, hi, n))
    e = E[(E.L == L) & (E.which == "first")]
    m, lo, hi, n = boot_median(e.exact_frac)
    rows.append(("first replicator: share of partners holding an exact copy", f"Z80, L = {L}", m, lo, hi, n))
    m0, lo, hi, n = boot_km(g.t_rep.where(g.t_rep > 0), int(g.horizon.iloc[0]))
    rows.append(("first heritable clone t_rep, Kaplan–Meier median (steps)", f"Z80, L = {L}", m0, lo, hi, n))
    for which in ("first", "final"):
        d = M[(M.L == L) & (M.which == which)]
        m, lo, hi, n = boot_median(d.robustness_h)
        rows.append((f"{which}: share of single mutants heritable", f"Z80, L = {L}", m, lo, hi, n))
I = pd.read_csv(os.path.join(R, "stageI", "stageI", "stage_g_runs.csv"))
m0, lo, hi, n = boot_km(I.t_rep.where(I.t_rep > 0), int(I.horizon.iloc[0]))
rows.append(("first heritable clone t_rep, Kaplan–Meier median (steps)", "Z80, L = 16, lethal tar", m0, lo, hi, n))
Q = pd.read_csv(os.path.join(R, "population", "population_worlds.csv"))
for (st, L), d in Q.groupby(["stage", "L"]):
    m, lo, hi, n = boot_median(d.confined_given_heritable)
    rows.append(("last snapshot: share of heritable random cells confined", f"Stage {st}, L = {L}", m, lo, hi, n))
    m, lo, hi, n = boot_median(d.frac_heritable)
    rows.append(("last snapshot: share of random cells heritable", f"Stage {st}, L = {L}", m, lo, hi, n))

lines = ["# Uncertainty across worlds (generated by `stats_ci.py`; source of Extended Data Table 3)", "",
         "| quantity | condition | median | 95% bootstrap interval | worlds |", "|:---|:---|---:|:---|---:|"]
for lab, cond, m, lo, hi, n in rows:
    fmt = (lambda v: f"{v:,.0f}" if np.isfinite(v) else "not reached") if "steps" in lab else (lambda v: f"{v:.2f}")
    lines.append(f"| {lab} | {cond} | {fmt(m)} | {fmt(lo)}–{fmt(hi)} | {n} |")
lines += ["", "Counts with Wilson 95% intervals:", ""]
for lab, k, n in (("first replicator a load–push word, benign tar, L 16–64", 170, 170), ("worlds closed at the population level, Stage G, L = 16", 20, 20),
                  ("L = 20", 19, 20), ("L = 32 (Stage K)", 12, 20), ("L = 50", 0, 20), ("L = 64", 8, 20), ("8080 subset, L = 32", 0, 20)):
    lo, hi = wilson(k, n)
    lines.append(f"- {lab}: {k} of {n} ({lo:.2f}–{hi:.2f})")
T = pd.read_csv(os.path.join(R, "review_r2", "threshold_grid.csv"))
z = T[(T.L >= 16) & (T.L <= 64) & (T.stage != "I")]
lines += ["", "Threshold grid (first replicator re-dated under heredity threshold θ_g; informative-partner threshold 0.65–0.85 changes nothing):", ""]
for tg in sorted(z.theta_g.unique()):
    e = z[(z.theta_g == tg) & (z.theta_b == 0.75) & z.t_first.notna()]
    lo, hi = wilson(int(e.loadpush.sum()), len(e))
    lines.append(f"- θ_g = {tg}: load–push first in {int(e.loadpush.sum())} of {len(e)} worlds with a replicator ({lo:.2f}–{hi:.2f}); open first in {int(e.open.sum())}")
txt = "\n".join(lines)
open(os.path.join(R, "review_r2", "STATS.md"), "w").write(txt + "\n")
print(txt)
