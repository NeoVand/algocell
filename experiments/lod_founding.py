"""N3 (after the second figure critic): what happens at the founding event of each first founder.

For the first founder F of each closed world (results/lod/founders2.csv, first == True), on the exact line records:
- the founding encounter is replayed to find which side F was on (the executor's own half, or the partner's) and which
  tape executed;
- the executor is run against 64 random partners: how often it writes F exactly into the partner (or rewrites itself
  into F) whatever the partner holds (a "producer" of F);
- the bytes of F found in neither parent, at shift 0 and at each parent's best cyclic shift;
- every record on the chain from the newest open copier to F is tested the same way, and the earliest record that already
  produces F in at least half of the encounters is reported with the event that made it.
Classes (open copier, confined copier, non-copier) are from lod_traj.classify_tapes (64 random partners, seed 3).

    .venv/bin/python lod_founding.py      # results/lod/FOUNDING.md, founding.csv
"""
from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import exectrace as X  # noqa: E402
from lod_traj import classify_tapes  # noqa: E402

L = 16
IND = os.path.join(HERE, "runs", "lod_v6_modal", "lod_v6")
OUT = os.path.join(HERE, "results", "lod")
K = {0: "init", 1: "copy", 2: "damage", 3: "novel", 4: "mut", 5: "copyA"}
NAME = {"novel": "rewrite (neither copy nor ≥ 75% own)", "copyA": "copy of the partner", "copy": "copy", "damage": "partial overwrite", "mut": "point mutation"}
P = np.random.default_rng(7).integers(0, 256, (64, L), dtype=np.uint8)


def h(a):
    return " ".join(f"{int(x):02x}" for x in a)


def run(A, B):
    res, _ = X.execute_pairs_traced(np.concatenate([np.atleast_2d(A), np.atleast_2d(B)], 1).astype(np.uint8), L, 128)
    return res[:, :L], res[:, L:]


def produces(T, F):
    """Share of 64 random partners into which T writes F exactly (partner half), and in which T's own half becomes F."""
    a, b = run(np.tile(T, (len(P), 1)), P)
    return float((b == F).all(1).mean()), float((a == F).all(1).mean())


def enters(T):
    """Share of 64 random partners in which T's pointer fetches a partner byte (open execution)."""
    _, m = X.execute_pairs_traced(np.concatenate([np.tile(T, (len(P), 1)), P], 1).astype(np.uint8), L, 128)
    return float(X.exec_positions(m, 2 * L)[:, L:].any(1).mean())


def best_shift(F, X_):
    m = [(F == np.roll(X_, s)).sum() for s in range(L)]
    return np.roll(X_, int(np.argmax(m)))


def main():
    D = pd.read_csv(os.path.join(OUT, "founders2.csv"))
    D = D[D["first"] == True]  # noqa: E712
    rows, md = [], ["# N3: the founding event of each first founder (generated by `lod_founding.py`)", "",
                    "Producer = a tape that, run as the executor against 64 random partners, writes the founder F exactly into the partner "
                    "(or turns its own half into F) in at least half of the encounters, whatever the partner holds.", ""]
    for r in D.itertuples():
        z = np.load(os.path.join(IND, f"L16_benign_s{r.seed}", "line_records.npz"))
        tapes = [h(t) for t in z["tape"]]
        cand = [i for i in range(len(tapes)) if z["step"][i] == r.F_step and tapes[i] == r.F_tape]
        # the line holding F, and F's position on it
        off, found = 0, None
        for li, n in enumerate(z["line_lengths"]):
            ids = z["line_ids"][off:off + n]
            hit = [q for q in range(n) if ids[q] in cand]
            if hit:
                found = (ids, hit[0])
                break
            off += n
        ids, fq = found
        F = int(ids[fq])
        Fb = z["tape"][F]
        C = classify_tapes(sorted({tapes[i] for i in ids[fq:]} | {h(z["p2_tape"][F]), h(z["other"][F])}))
        cls = lambda t: C[t]["class"] if t in C else classify_tapes([t])[t]["class"]  # noqa: E731
        lo = next(q for q in range(fq + 1, len(ids)) if cls(tapes[ids[q]]) == "open copier")
        chain = [int(ids[q]) for q in range(lo, fq - 1, -1)]          # chain start ... F
        kind = K[int(z["kind"][F])]
        p1 = int(z["p1"][F])
        if kind == "novel":
            par1, par2 = z["tape"][p1], z["p2_tape"][F]
            own, oth = (par1, par2) if z["cell"][p1] == z["cell"][F] else (par2, par1)
        else:                                                         # copyA: p1 = the partner, other = own old tape
            own, oth = z["other"][F], z["tape"][p1]
        a1, _ = run(own, oth)
        _, b2 = run(oth, own)
        if (a1[0] == Fb).all():
            side, exe, partner = "executor's own half", own, oth
        elif (b2[0] == Fb).all():
            side, exe, partner = "partner half", oth, own
        else:
            side, exe, partner = "not reproduced", oth, own
        wB, wA = produces(exe, Fb)
        neither0 = int(((Fb != own) & (Fb != oth)).sum())
        neitherB = int(((Fb != best_shift(Fb, own)) & (Fb != best_shift(Fb, oth))).sum())
        # earliest record on the chain that already produces F
        prod = None
        for q, rid in enumerate(chain[:-1]):
            pb, pa = produces(z["tape"][rid], Fb)
            if max(pb, pa) >= 0.5:
                prod = (rid, pb, pa)
                break
        row = {"seed": r.seed, "F_tape": r.F_tape, "F_kind": NAME[kind], "side": side, "executor": h(exe), "executor_class": cls(h(exe)),
               "partner_class": cls(h(partner)), "executor_writes_F": wB, "executor_self_F": wA, "executor_enters": enters(exe), "bytes_in_neither_parent": neither0,
               "bytes_in_neither_best_shift": neitherB, "producer_on_chain": prod is not None}
        if prod:
            rid = prod[0]
            row.update({"producer_tape": tapes[rid], "producer_steps_before_F": int(z["step"][F] - z["step"][rid]),
                        "producer_made_by": NAME[K[int(z["kind"][rid])]], "producer_class": cls(tapes[rid]),
                        "producer_writes_F": prod[1], "producer_self_F": prod[2], "producer_enters": enters(z["tape"][rid])})
        rows.append(row)
        md.append(f"- world {r.seed}: F `{r.F_tape}`; completed by {row['F_kind']} on the {side}; executor `{h(exe)}` "
                  f"({row['executor_class']}) writes F into {wB:.2f} of random partners (own half becomes F in {wA:.2f}); partner "
                  f"{row['partner_class']}; bytes of F in neither parent: {neither0} (at best shifts {neitherB})"
                  + (f"; first producer on the chain {row['producer_steps_before_F']} steps before F, made by {row['producer_made_by']}, "
                     f"a {row['producer_class']} (writes F into {prod[1]:.2f}, becomes F in {prod[2]:.2f})" if prod else "; no producer on the chain"))
    T = pd.DataFrame(rows)
    T.to_csv(os.path.join(OUT, "founding.csv"), index=False)
    n = len(T)
    ex = T.executor_writes_F.combine(T.executor_self_F, max)
    md += ["", "## Summary", "",
           f"- first founders: {n}; side: " + ", ".join(f"{k} {v}" for k, v in T.side.value_counts().items()),
           f"- executor class at the founding encounter: " + ", ".join(f"{k} {v}" for k, v in T.executor_class.value_counts().items()),
           f"- partner class: " + ", ".join(f"{k} {v}" for k, v in T.partner_class.value_counts().items()),
           f"- the founding executor produces F in ≥ half of random encounters: {int((ex >= 0.5).sum())} of {n} (in all 64: {int((ex == 1).sum())})",
           f"- the founding executor's pointer enters random partners in ≥ half of encounters (open execution): {int((T.executor_enters >= 0.5).sum())} of {n}; "
           f"among the {int((ex >= 0.5).sum())} producers: {int(((T.executor_enters >= 0.5) & (ex >= 0.5)).sum())}",
           f"- bytes of F in neither parent: median {T.bytes_in_neither_parent.median():.0f} (range {T.bytes_in_neither_parent.min()}–{T.bytes_in_neither_parent.max()}); "
           f"at best shifts median {T.bytes_in_neither_best_shift.median():.0f} ({T.bytes_in_neither_best_shift.min()}–{T.bytes_in_neither_best_shift.max()})",
           f"- an earlier record on the chain already produces F: {int(T.producer_on_chain.sum())} of {n}"]
    if T.producer_on_chain.any():
        Pp = T[T.producer_on_chain]
        md += [f"  - producer made by: " + ", ".join(f"{k} {v}" for k, v in Pp.producer_made_by.value_counts().items()),
               f"  - producer class: " + ", ".join(f"{k} {v}" for k, v in Pp.producer_class.value_counts().items()),
               f"  - steps before F: median {Pp.producer_steps_before_F.median():.0f} (range {Pp.producer_steps_before_F.min()}–{Pp.producer_steps_before_F.max()})"]
    open(os.path.join(OUT, "FOUNDING.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
