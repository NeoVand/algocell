"""E-census follow-up (exploratory): are regenerators damaged by intruding executors because their body is copies of
their own copying code? Partners: R = `04 5e ed b0` x 8; T = `a0 5e ed b0` + 28 random bytes (fresh per encounter);
T_tiled = `a0 5e ed b0` x 8 (a transmitter whose body is tiled core). Executors: cells without a core drawn from the
final L = 32 mix50 soups of each tar, traced to see whether their pointer entered the partner. Rule benign or lethal.
Output: results/offset/INTRUDER.md"""
import glob
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import assay as A  # noqa: E402
from algocell_exp import exectrace as X  # noqa: E402
from offset_switch import classify  # noqa: E402

L, N = 32, 16384
rng = np.random.default_rng(7)
rows = []
for comp in ("benign", "lethal"):
    soup = np.concatenate([np.load(f) for f in sorted(glob.glob(os.path.join(HERE, "runs", "offset", "offset", f"L32_{comp}_muton_mix50_s*_final.npy")))])
    core, _, _ = classify(soup, L)
    ex = soup[~core]
    E = ex[rng.integers(0, len(ex), N)]
    for name in ("R", "T", "T_tiled"):
        if name == "R":
            P = np.tile(np.array([0x04, 0x5e, 0xed, 0xb0] * 8, np.uint8), (N, 1))
        elif name == "T_tiled":
            P = np.tile(np.array([0xa0, 0x5e, 0xed, 0xb0] * 8, np.uint8), (N, 1))
        else:
            P = np.concatenate([np.tile(np.array([0xa0, 0x5e, 0xed, 0xb0], np.uint8), (N, 1)), rng.integers(0, 256, (N, 28), dtype=np.uint8)], 1)
        cls0 = classify(P, L)
        for rule in ("benign", "lethal"):
            res, m = X.execute_pairs_traced(np.concatenate([E, P], 1), L, 128, zero_halts=(rule == "lethal"))
            entered = X.exec_positions(m, 2 * L)[:, L:].any(axis=1)
            B = res[:, L:]
            c1 = classify(B, L)
            keep = (c1[1] == cls0[1]) & (c1[2] == cls0[2]) & c1[0]
            exact = (B == P).all(1)
            rows.append({"composition": comp, "partner": name, "rule": rule, "entered": entered.mean(),
                         "keeps_class": keep.mean(), "keeps_class_if_entered": keep[entered].mean() if entered.any() else np.nan,
                         "keeps_class_if_not_entered": keep[~entered].mean() if (~entered).any() else np.nan, "exact": exact.mean()})
D = pd.DataFrame(rows)
lines = ["# Intruding executors and the partner's body (generated by `offset_intruder.py`; exploratory)", "",
         f"{N} encounters per row; executors are core-free cells of the L = 32 mix50 final soups of each tar; partner class kept = core intact and the offset byte in the same class.", "",
         "| executors from | partner | rule | executor entered the partner | partner keeps its class | ... if entered | ... if not entered | partner exact |", "|---|---|---|---|---|---|---|---|"]
for r in D.itertuples():
    lines.append(f"| {r.composition} | {r.partner} | {r.rule} | {r.entered:.3f} | {r.keeps_class:.3f} | {r.keeps_class_if_entered:.3f} | {r.keeps_class_if_not_entered:.3f} | {r.exact:.3f} |")
open(os.path.join(HERE, "results", "offset", "INTRUDER.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
