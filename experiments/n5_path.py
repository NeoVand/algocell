"""N5 (REVISION_PREREG): is the four-step path from the open pusher to a confined copier an adaptive walk?

    .venv/bin/python n5_path.py --yes        # results/n5/PATH.md, path_runs.csv, path_genotypes.csv
"""
from __future__ import annotations

import argparse
import os
import sys
import time

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import assay as A  # noqa: E402
from algocell_exp import exectrace as X  # noqa: E402
from algocell_exp.soup import Soup  # noqa: E402

L = 16
OUT = os.path.join(HERE, "results", "n5")


def family(ld: int, push: int, ret: int = 0xE0):
    g = [ld, push] * 8
    path = [list(g)]
    for pos, val in ((5, ret), (15, ret), (9, 0xE3), (1, 0xE3)):
        g = list(g)
        g[pos] = val
        path.append(g)
    return [np.array(x, np.uint8) for x in path]


FAMILIES = {"21 e5": family(0x21, 0xE5), "01 c5": family(0x01, 0xC5)}


def shares(soup: np.ndarray, designs) -> np.ndarray:
    # Hamming to each design at its best cyclic shift (the paper's class convention), nearest design wins, ties to none
    d = np.stack([np.min(np.stack([(soup != np.roll(g, s)).sum(1) for s in range(L)]), 0) for g in designs], 1)
    best = d.min(1)
    nbest = (d == best[:, None]).sum(1)
    win = d.argmin(1)
    ok = (best <= 2) & (nbest == 1)
    return np.array([((win == k) & ok).mean() for k in range(len(designs))])


def genotype_stats(designs, n=4096, seed=1):
    rng = np.random.default_rng(seed)
    rows = []
    for k, g in enumerate(designs):
        P = rng.integers(0, 256, (n, L), dtype=np.uint8)
        res, m = X.execute_pairs_traced(np.concatenate([np.tile(g, (n, 1)), P], 1), L, 128)
        ent = X.exec_positions(m, 2 * L)[:, L:].any(1).mean()
        B = res[:, L:]
        sim = np.max(np.stack([(B == np.roll(g, s)).mean(1) for s in range(L)]), 0)
        r = A.assay(g.tobytes(), z80_steps=128, n=32, seed=1)
        rows.append({"k": k, "tape": " ".join(f"{x:02x}" for x in g), "enter": float(ent), "copy75": float((sim >= 0.75).mean()),
                     "exact": float((B == g).all(1).mean()), "culture": r.get("score"), "gen2": r.get("gen2_score")})
    return rows


def run(resident, invader, designs, seed, steps=20000, every=250):
    soup = Soup(160, 125, "square", L, 52000 + seed, 8192, 128, 4, [])
    N = soup.cell_count
    rng = np.random.default_rng([seed, 55])
    cells = np.tile(resident, (N, 1))
    cells[rng.choice(N, size=N // 100, replace=False)] = invader
    soup.write_soup(cells)
    traj = []
    t = 0
    while t < steps:
        soup.step(every)
        t += every
        traj.append((t, shares(soup.read_soup(), designs)))
    run.last = soup.read_soup()
    return traj


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--yes", action="store_true")
    ap.add_argument("--seeds", type=int, default=5)
    a = ap.parse_args()
    if not a.yes:
        sys.exit("pass --yes (local GPU)")
    os.makedirs(OUT, exist_ok=True)
    G, R = [], []
    t0 = time.time()
    for fam, designs in FAMILIES.items():
        for row in genotype_stats(designs):
            G.append({"family": fam, **row})
        for k in range(1, len(designs)):
            for direction, res, inv, ik in (("forward", designs[k - 1], designs[k], k), ("reverse", designs[k], designs[k - 1], k - 1)):
                for sd in range(1, a.seeds + 1):
                    traj = run(res, inv, designs, sd + 100 * k + (1000 if direction == "reverse" else 0) + (5000 if fam == "01 c5" else 0))
                    os.makedirs(os.path.join(HERE, "runs", "n5"), exist_ok=True)
                    np.save(os.path.join(HERE, "runs", "n5", f"{fam.replace(' ', '')}_k{k}_{direction}_s{sd}.npy"), run.last)
                    for t, sh in traj:
                        R.append({"family": fam, "step": k, "direction": direction, "seed": sd, "t": t, "invader_share": sh[ik],
                                  "resident_share": sh[k - 1 if direction == "forward" else k], **{f"G{j}": sh[j] for j in range(len(designs))}})
                    print(f"{fam} step {k} {direction} seed {sd}: invader {traj[-1][1][ik]:.3f}, resident {traj[-1][1][k - 1 if direction == 'forward' else k]:.3f}, all {np.round(traj[-1][1], 3).tolist()} ({time.time() - t0:.0f} s)", flush=True)
    Gd, Rd = pd.DataFrame(G), pd.DataFrame(R)
    Gd.to_csv(os.path.join(OUT, "path_genotypes.csv"), index=False)
    Rd.to_csv(os.path.join(OUT, "path_runs.csv"), index=False)
    lines = ["# N5: the four-step path from the pusher to a confined copier (generated by `n5_path.py`)", "",
             "## Genotypes (against random partners; culture test with 32 partners)", "", "| family | k | tape | enters partner | copies ≥ 0.75 | exact copy | culture score | gen2 |", "|---|---|---|---|---|---|---|---|"]
    for r in Gd.itertuples():
        lines.append(f"| {r.family} | G{r.k} | `{r.tape}` | {r.enter:.3f} | {r.copy75:.3f} | {r.exact:.3f} | {r.culture:.3f} | {r.gen2:.3f} |")
    lines += ["", "## Invasions from 1% (share of the invader's class at 20,000 steps; 5 seeds)", "", "| family | step | Gk into G(k−1): shares | N5-1 (≥ 0.5 in ≥ 4) | G(k−1) into Gk: shares | N5-2 (< 0.05 in ≥ 4) |", "|---|---|---|---|---|---|"]
    end = Rd[Rd.t == Rd.t.max()]
    for (fam, k), e in end.groupby(["family", "step"]):
        f = e[e.direction == "forward"].invader_share.values
        rv = e[e.direction == "reverse"].invader_share.values
        lines.append(f"| {fam} | {k} | {', '.join(f'{x:.2f}' for x in f)} | {'met' if (f >= 0.5).sum() >= 4 else 'not met'} | {', '.join(f'{x:.2f}' for x in rv)} | {'met' if (rv < 0.05).sum() >= 4 else 'not met'} |")
    open(os.path.join(OUT, "PATH.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()


def amended(path=os.path.join(OUT, "path_runs.csv"), t_end=2000):
    """Second amendment (REVISION_PREREG N5): invader share at 2,000 steps where invader + resident hold >= 0.5."""
    D = pd.read_csv(path)
    e = D[D.t == t_end].copy()
    e["held"] = (e.invader_share + e.resident_share) >= 0.5
    lines = ["", f"## Amended endpoint: invader share at {t_end:,} steps (runs where invader + resident hold ≥ 0.5)", "",
             "| family | step | Gk into G(k−1) | N5-1 | G(k−1) into Gk | N5-2 |", "|---|---|---|---|---|---|"]
    for (fam, k), g in e.groupby(["family", "step"]):
        f = g[g.direction == "forward"]
        r = g[g.direction == "reverse"]
        fs = ", ".join(f"{x:.2f}{'' if h else '*'}" for x, h in zip(f.invader_share, f.held))
        rs = ", ".join(f"{x:.2f}{'' if h else '*'}" for x, h in zip(r.invader_share, r.held))
        n1 = "met" if ((f.invader_share >= 0.5) & f.held).sum() >= 4 else "not met"
        n2 = "met" if ((r.invader_share < 0.05) & r.held).sum() >= 4 else "not met"
        lines.append(f"| {fam} | {k} | {fs} | {n1} | {rs} | {n2} |")
    lines.append("")
    lines.append("\\* invader + resident < 0.5 at that time (evolved away).")
    with open(os.path.join(OUT, "PATH.md"), "a") as fh:
        fh.write("\\n".join(lines) + "\\n")
    print("\\n".join(lines))
