"""T — first-closure timing from the recorded runs (registered: REVISION_PREREG.md R3/T, 2026-10-09).

    .venv/bin/python first_closure.py --yes          # -> results/review_r2/first_closure.csv, FIRST_CLOSURE.md

For every world of Stages G (L = 16, 20, 64), L, K, I and M (L = 16): the first sample at which one of the three most
common tapes holding >= 0.5% of cells is heritable (gen2 >= 0.3 over 64 partners, the run's own rule) and confined in 16
of 16 traced encounters; censored at the horizon. Kaplan–Meier medians; log-rank test of benign L = 16 (Stages G and L)
against lethal L = 16 (Stage I), and of each stage against Stage I.
"""
from __future__ import annotations

import argparse
import json
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import exectrace as X  # noqa: E402
from threshold_grid import STAGES, gen2_grid  # noqa: E402

R = os.path.join(HERE, "results")
SEL = {"G": (16, 20, 64), "L": (16, 20), "K": (32,), "I": (16,), "M": (16, 32), "H": (16,)}


def logrank(t1, e1, t2, e2):
    """Two-sample log-rank test; returns (chi2, p)."""
    from math import erfc, sqrt
    times = np.unique(np.concatenate([t1[e1], t2[e2]]))
    O1 = E1 = V = 0.0
    for t in times:
        n1, n2 = (t1 >= t).sum(), (t2 >= t).sum()
        d1, d2 = ((t1 == t) & e1).sum(), ((t2 == t) & e2).sum()
        n, d = n1 + n2, d1 + d2
        if n < 2:
            continue
        O1 += d1
        E1 += d * n1 / n
        V += d * (n1 / n) * (1 - n1 / n) * (n - d) / (n - 1)
    chi2 = (O1 - E1) ** 2 / V if V > 0 else np.nan
    p = erfc(sqrt(chi2 / 2)) if np.isfinite(chi2) else np.nan
    return chi2, p


def km_median(t, e):
    order = np.argsort(t, kind="stable")
    t, e = t[order], e[order]
    s, n = 1.0, len(t)
    for i in range(n):
        if e[i]:
            s *= 1 - 1 / (n - i)
            if s <= 0.5:
                return t[i]
    return np.inf


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--yes", action="store_true")
    a = ap.parse_args()
    if not a.yes:
        sys.exit("refusing to run: pass --yes after pausing the browser simulation (local GPU)")
    from make_conds import ABLATIONS
    rows = []
    for st, Ls in SEL.items():
        rdir, csv, zh, abl = STAGES[st]
        sup = list(ABLATIONS[abl]) if abl else []
        g = pd.read_csv(os.path.join(HERE, csv))
        g = g[g.L.isin(Ls)]
        for _, w in g.iterrows():
            L, seed, label = int(w["L"]), int(w["seed"]), str(w["label"])
            horizon = int(w["horizon"])
            path = os.path.join(HERE, rdir, f"{label}_L{L}_st128_k4_s{seed}.jsonl")
            cands, seen = [], set()
            for line in open(path):
                d = json.loads(line)
                if d.get("kind") != "sample":
                    continue
                shares = d.get("top3_shares") or []
                for rank, ex in enumerate(d.get("exemplars") or []):
                    if rank < len(shares) and shares[rank] >= 0.005 and ex["tape"] not in seen:
                        seen.add(ex["tape"])
                        cands.append((d["step"], ex["tape"]))
            first = None
            rng = np.random.default_rng([seed, L, 77])
            for c0 in range(0, len(cands), 128):
                chunk = cands[c0:c0 + 128]
                T = np.array([[int(b, 16) for b in t.split()] for _, t in chunk], np.uint8)
                g2 = gen2_grid(T, sup, zh, seed=20261017 + seed)[:, 1]
                P = rng.integers(0, 256, size=(len(T) * 16, L), dtype=np.uint8)
                _, masks = X.execute_pairs_traced(np.concatenate([np.repeat(T, 16, 0), P], 1), L, 128, suppress=sup, zero_halts=zh)
                conf = ~X.exec_positions(masks, 2 * L)[:, L:].any(axis=1).reshape(len(T), 16).any(axis=1)
                hit = np.flatnonzero(np.isfinite(g2) & (g2 >= 0.3) & conf)
                if len(hit):
                    first = chunk[hit[0]]
                    break
            rows.append({"stage": st, "L": L, "seed": seed, "horizon": horizon, "t_rep": w["t_rep"], "t_closed": first[0] if first else np.nan,
                         "closed_tape": first[1] if first else ""})
            print(st, L, seed, rows[-1]["t_rep"], rows[-1]["t_closed"], rows[-1]["closed_tape"][:23], flush=True)
    D = pd.DataFrame(rows)
    D.to_csv(os.path.join(R, "review_r2", "first_closure.csv"), index=False)
    report(D)


def report(D=None):
    if D is None:
        D = pd.read_csv(os.path.join(R, "review_r2", "first_closure.csv"))
    lines = ["# T — first closed replicator (generated by `first_closure.py`)", "",
             "First sample at which a top-3 tape (≥ 0.5% of cells) is heritable and confined in 16 of 16 encounters; Kaplan–Meier medians, censored at the horizon.", "",
             "| stage | L | worlds | closed by the horizon | KM median of first closure (steps) | median first heritable clone t_rep |", "|---|---|---|---|---|---|"]
    for (st, L), d in D.groupby(["stage", "L"]):
        e = d.t_closed.notna().values
        t = np.where(e, d.t_closed.fillna(0), d.horizon).astype(float)
        lines.append(f"| {st} | {L} | {len(d)} | {int(e.sum())} | {km_median(t, e):,.0f} | {d.t_rep.median():,.0f} |")
    def grp(mask):
        d = D[mask]
        e = d.t_closed.notna().values
        return np.where(e, d.t_closed.fillna(0), d.horizon).astype(float), e
    tb, eb = grp(((D.stage == "G") | (D.stage == "L")) & (D.L == 16))
    tl, el = grp((D.stage == "I"))
    chi, p = logrank(tb, eb, tl, el)
    lines += ["", f"- benign L = 16 (Stages G and L, {len(tb)} worlds): KM median {km_median(tb, eb):,.0f}; lethal L = 16 (Stage I, {len(tl)}): KM median {km_median(tl, el):,.0f}; log-rank χ² = {chi:.2f}, P = {p:.3g}",
              f"- registered decision rule: benign closure significantly earlier (P < 0.05 and benign median lower): {'yes' if (p < 0.05 and km_median(tb, eb) < km_median(tl, el)) else 'no'}"]
    txt = "\n".join(lines)
    open(os.path.join(R, "review_r2", "FIRST_CLOSURE.md"), "w").write(txt + "\n")
    print(txt)


if __name__ == "__main__":
    main()
