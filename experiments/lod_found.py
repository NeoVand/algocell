"""N3 (addition): the exact founding event of self-confined copying on each line of descent (uses lod_v5's full line
record tables).

Every distinct tape on the 64 sampled lines is classified by itself (64 random partners; lod_traj.classify_tapes):
open copier, confined copier or non-copier. On each line (newest first) the stable stretch is the oldest record such
that at least 90% of the records from it to the present are confined copiers; F is the first confined copier after the
last open copier older than that point (the founder of the confined lineage). Reported for F: the kind of the event that
made it, the class of each parent (the line's previous record, the executor of a copy, the overwritten tape, the minor
parent of a recombinant), the alignment origin of each byte, the block move it executes and whether that move's two bytes
were present, and executed as an instruction, in the line's previous record and in the other parent.

    .venv/bin/python lod_found.py --indir runs/lod_v5_modal/lod_v5      # results/lod/FOUND.md, found.csv
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lod_origin import MOVES, copy_instruction, roles  # noqa: E402
from lod_traj import classify_tapes  # noqa: E402

L = 16
KINDS = {0: "init", 1: "copy", 2: "damage", 3: "novel", 4: "mut", 5: "copyA"}


def h(a):
    return " ".join(f"{int(x):02x}" for x in a)


def carries_move(tape_hex: str, key, R) -> str:
    t = [int(x, 16) for x in tape_hex.split()]
    pos = [p for p in range(L) if (t[p], t[(p + 1) % L]) == key]
    if not pos:
        return "absent"
    st = max(R[tape_hex]["start"][p] for p in pos)
    fe = max(R[tape_hex]["fetch"][p] for p in pos)
    return "executed" if st >= 0.05 else ("operand" if fe >= 0.05 else "carried, never fetched")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--indir", default=os.path.join(HERE, "runs", "lod_v5_modal", "lod_v5"))
    ap.add_argument("--out", default=os.path.join(HERE, "results", "lod"))
    ap.add_argument("--tag", default="")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    rows = []
    md = ["# N3 addition: the founding event of self-confined copying on each line (generated by `lod_found.py`)", ""]
    for f in sorted(glob.glob(os.path.join(a.indir, "L16_benign_s*", "line_records.npz"))):
        z = np.load(f)
        res = json.load(open(os.path.join(os.path.dirname(f), "lod.json")))["result"]
        tapes = [h(t) for t in z["tape"]]
        others = [h(t) if ho else None for t, ho in zip(z["other"], z["has_other"])]
        p2s = [h(t) if hp else None for t, hp in zip(z["p2_tape"], z["has_p2"])]
        alltapes = sorted(set(tapes) | {t for t in others if t} | {t for t in p2s if t})
        C = classify_tapes(alltapes)
        R = roles(alltapes)
        cls = np.array([C[t]["class"] for t in tapes])
        off = 0
        for li, (cell, n) in enumerate(zip(z["line_cells"], z["line_lengths"])):
            ids = z["line_ids"][off:off + n]
            off += n
            conf = cls[ids] == "confined copier"
            frac = np.cumsum(conf) / np.arange(1, n + 1)
            ok = np.where(frac >= 0.9)[0]
            if not len(ok):
                rows.append({"seed": res["seed"], "line": li, "found": False})
                continue
            tr = int(ok.max())
            last_open = next((q for q in range(tr, n) if cls[ids[q]] == "open copier"), None)
            if last_open is None:
                rows.append({"seed": res["seed"], "line": li, "found": False, "note": "no open copier on the line"})
                continue
            fq = next((q for q in range(last_open - 1, -1, -1) if cls[ids[q]] == "confined copier"), None)
            F = ids[fq]
            prev = ids[fq + 1]
            kind = KINDS.get(int(z["kind"][F]), "?")
            ft = tapes[F]
            ci = copy_instruction(np.array([int(x, 16) for x in ft.split()], np.uint8), R[ft])
            r = {"seed": res["seed"], "line": li, "found": True, "t_close": res["t_close"], "F_step": int(z["step"][F]), "F_kind": kind, "F_tape": ft,
                 "F_record": int(F), "last_open_step": int(z["step"][ids[last_open]]), "last_open_tape": tapes[ids[last_open]],
                 "records_between": int(last_open - fq - 1), "classes_between": ",".join(sorted(set(cls[ids[fq + 1:last_open]]))) if last_open - fq > 1 else "",
                 "prev_tape": tapes[prev], "prev_class": cls[prev], "prev_kind": KINDS.get(int(z["kind"][prev]), "?"),
                 "copy_move": ci[1] if ci else None, "copy_pos": ci[0] if ci else None}
            other = others[F] if kind in ("copy", "damage", "copyA") else (p2s[F] if kind == "novel" else None)
            r["other_tape"] = other
            r["other_role"] = {"copy": "overwritten tape", "copyA": "overwritten tape", "damage": "writer", "novel": "minor parent"}.get(kind)
            r["other_class"] = C[other]["class"] if other else None
            if kind in ("copy", "copyA"):
                r["executor_or_source_class"] = cls[prev]       # for copy records the line's previous record is the copier
            ft_b = [int(x, 16) for x in ft.split()]
            pv_b = [int(x, 16) for x in tapes[prev].split()]
            sh = int(z["shift"][F])
            src = np.roll(pv_b, sh) if kind in ("copy", "copyA", "novel") else np.array(pv_b)
            ob = [int(x, 16) for x in other.split()] if other else None
            cat = []
            for q in range(L):
                fs = ft_b[q] == src[q]
                fo = ob is not None and ft_b[q] == ob[q]
                cat.append("b" if fs and fo else "l" if fs else "o" if fo else "n")
            r["byte_origin"] = "".join(cat)          # l = from the line's previous record, o = from the other parent, b = both, n = new
            if ci:
                key = (ft_b[ci[0]], ft_b[(ci[0] + 1) % L])
                cat_mv = cat[ci[0]] + cat[(ci[0] + 1) % L]
                r["move_bytes_origin"] = cat_mv
                r["move_in_prev"] = carries_move(tapes[prev], key, R)
                r["move_in_other"] = carries_move(other, key, R) if other else None
                r["move_in_last_open"] = carries_move(tapes[ids[last_open]], key, R)
            rows.append(r)
        D = pd.DataFrame([x for x in rows if x["seed"] == res["seed"]])
        md.append(f"## World {res['seed']} (closure {res['t_close']}, end {res['t_end']})")
        if "F_record" in D and D.found.any():
            for F, g in D[D.found].groupby("F_record"):
                e = g.iloc[0]
                md.append(f"- {len(g)} of {len(D)} lines: F at step {e.F_step} by **{e.F_kind}** `{e.F_tape}`; previous record on the line {e.prev_class} "
                          f"(`{e.prev_tape}`); {e.other_role}: {e.other_class} (`{e.other_tape}`); bytes by origin `{e.byte_origin}` (l line, o other, b both, n new); "
                          f"copy move {e.copy_move} at {e.copy_pos} (bytes `{e.get('move_bytes_origin')}`; in previous record: {e.get('move_in_prev')}; in other parent: {e.get('move_in_other')}; "
                          f"in last open copier: {e.get('move_in_last_open')}); last open copier at {e.last_open_step} `{e.last_open_tape}`, {e.records_between} records between ({e.classes_between or 'none'})")
        md.append("")
    D = pd.DataFrame(rows)
    D.to_csv(os.path.join(a.out, f"found{a.tag}.csv"), index=False)
    if len(D) and D.found.any():
        g = D[D.found].drop_duplicates(["seed", "F_record"])
        md += ["## Summary over distinct founders", "", f"- founders: {len(g)} in {g.seed.nunique()} worlds",
               "- kind of founding event: " + ", ".join(f"{k} {v}" for k, v in g.F_kind.value_counts().items()),
               "- class of the line's previous record: " + ", ".join(f"{k} {v}" for k, v in g.prev_class.value_counts().items()),
               "- role and class of the other tape: " + ", ".join(f"{k} {v}" for k, v in g.groupby(["other_role", "other_class"], dropna=False).size().items()),
               "- copy move: " + ", ".join(f"{k} {v}" for k, v in g.copy_move.value_counts(dropna=False).items()),
               "- origin of the move's two bytes (l line, o other, b both, n new): " + ", ".join(f"{k} {v}" for k, v in g.get("move_bytes_origin", pd.Series(dtype=str)).value_counts(dropna=False).items()),
               "- the move in the last open copier: " + ", ".join(f"{k} {v}" for k, v in g.get("move_in_last_open", pd.Series(dtype=str)).value_counts(dropna=False).items())]
    open(os.path.join(a.out, f"FOUND{a.tag}.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
