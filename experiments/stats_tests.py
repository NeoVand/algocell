import os
from math import comb, erfc, sqrt

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))


def fisher_two_sided(a, b, c, d):
    n, r1, c1 = a + b + c + d, a + b, a + c

    def h(x):
        return comb(r1, x) * comb(n - r1, c1 - x) / comb(n, c1)
    p0 = h(a)
    return sum(h(x) for x in range(max(0, c1 - (n - r1)), min(r1, c1) + 1) if h(x) <= p0 * (1 + 1e-9))


def cochran_armitage(succ, n, x):
    succ, n, x = (np.asarray(v, float) for v in (succ, n, x))
    N, p = n.sum(), succ.sum() / n.sum()
    T = np.sum(x * (succ - n * p))
    var = p * (1 - p) * (np.sum(n * x ** 2) - np.sum(n * x) ** 2 / N)
    z = T / sqrt(var)
    return z, erfc(abs(z) / sqrt(2))


