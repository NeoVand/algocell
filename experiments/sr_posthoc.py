"""Post hoc (not registered): the serial allele-retention procedure of serial_retention.py (S) applied to tapes found
after S was registered — the most common tape of each A1 invasion soup (the constructed 8080 closer's descendants, under
i8080) and, when present, of each A2 soup. Output: results/serial_retention/posthoc_summary.csv, POSTHOC.md.
"""
import glob
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from serial_retention import run_genotype, sites, GENS, hx  # noqa: E402
from make_conds import ABLATIONS  # noqa: E402

rows = []
for f in sorted(glob.glob(os.path.join(HERE, "runs", "invasion_closer", "A*_final.npy"))):
    name = os.path.basename(f).replace("_final.npy", "")
    if "none" in name and name.startswith("A1_pusher"):
        continue
    soup = np.load(f)
    u, n = np.unique(soup, axis=0, return_counts=True)
    t = u[int(np.argmax(n))]
    sup = tuple(ABLATIONS["i8080"]) if name.startswith("A1") else ()
    df, meta = run_genotype({"key": name, "kind": "invasion descendant", "tape": t, "sup": sup, "zh": False}, seed=20261009)
    s = sites(df, meta)
    for g in GENS:
        dg = df[(df.gen == g) & df.identifiable]
        sg = s[s.gen == g]
        meta[f"sites_g{g}"] = int(sg.transmissible.sum())
        meta[f"sites_unexec_g{g}"] = int((sg.transmissible & ~sg.executed).sum())
        meta[f"retained_g{g}"] = float(dg.retained.mean())
        meta[f"erased_g{g}"] = float(dg.erased.mean())
        meta[f"lost_g{g}"] = float(dg.lost.mean())
    meta["modal_share"] = float(n.max() / len(soup))
    rows.append(meta)
    print(f"{name}: {hx(t)} | ctrl alive g8 {meta['ctrl_alive_g8']:.2f} | sites g1/g8 {meta['sites_g1']}/{meta['sites_g8']} (unexecuted at g8 {meta['sites_unexec_g8']}) | g8 lost/erased/retained {meta['lost_g8']:.2f}/{meta['erased_g8']:.2f}/{meta['retained_g8']:.2f}", flush=True)
D = pd.DataFrame(rows)
D.to_csv(os.path.join(HERE, "results", "serial_retention", "posthoc_summary.csv"), index=False)
lines = ["# Post hoc serial retention of invasion descendants (generated by `sr_posthoc.py`; not registered)", "",
         "| soup | most common tape (share) | control lineages alive at g = 8 | sites g = 1 / 8 (unexecuted at 8) | lost / erased / retained at g = 8 |", "|---|---|---|---|---|"]
lines += [f"| {r.key} | `{r.tape}` ({r.modal_share:.3f}) | {r.ctrl_alive_g8:.2f} | {r.sites_g1} / {r.sites_g8} ({r.sites_unexec_g8}) | {r.lost_g8:.2f} / {r.erased_g8:.2f} / {r.retained_g8:.2f} |" for r in D.itertuples()]
open(os.path.join(HERE, "results", "serial_retention", "POSTHOC.md"), "w").write("\n".join(lines) + "\n")
