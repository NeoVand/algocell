"""N3, genotype-level line of descent (addition; uses the per-line tapes stored by lod_v3/lod_v4).

Every distinct ancestral tape sampled along each line is classified by itself, against 64 random partners (128
instructions, zero registers): copier if it makes copies (>= 0.75 at the best cyclic shift) in at least half of the
encounters, open if its pointer fetches a partner byte in at least half, confined otherwise. The transition is located
on each line: the newest ancestor that is an open copier, and the oldest ancestor after which every sampled ancestor is a
confined copier.

    .venv/bin/python lod_traj.py --indir runs/lod_v3_modal/lod_v3     # results/lod/TRAJ.md, traj.csv
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import exectrace as X  # noqa: E402

L = 16


def classify_tapes(tapes: list[str], n: int = 64, seed: int = 3) -> dict:
    uniq = sorted(set(tapes))
    rng = np.random.default_rng(seed)
    P = rng.integers(0, 256, (n, L), dtype=np.uint8)
    out = {}
    B = 256
    for i in range(0, len(uniq), B):
        chunk = uniq[i:i + B]
        T = np.array([[int(x, 16) for x in t.split()] for t in chunk], np.uint8)
        A = np.repeat(T, n, axis=0)
        res, m = X.execute_pairs_traced(np.concatenate([A, np.tile(P, (len(chunk), 1))], 1), L, 128)
        ent = X.exec_positions(m, 2 * L)[:, L:].any(1).reshape(len(chunk), n)
        Bo = res[:, L:].reshape(len(chunk), n, L)
        for j, t in enumerate(chunk):
            sim = np.max(np.stack([(Bo[j] == np.roll(T[j], s)).mean(1) for s in range(L)]), 0)
            cr, er = float((sim >= 0.75).mean()), float(ent[j].mean())
            cls = ("open copier" if er >= 0.5 else "confined copier") if cr >= 0.5 else "non-copier"
            out[t] = {"copy": cr, "enter": er, "exact": float((Bo[j] == T[j]).all(1).mean()), "class": cls}
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--indir", default=os.path.join(HERE, "runs", "lod_v3_modal", "lod_v3"))
    ap.add_argument("--out", default=os.path.join(HERE, "results", "lod"))
    ap.add_argument("--tag", default="")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    rows, lines_out = [], ["# N3 by genotype along the line of descent (generated by `lod_traj.py`; addition)", "",
                           "Each sampled ancestral tape is classified by itself against 64 random partners: copier if it copies (≥ 0.75 at best shift) in ≥ half of the encounters; open if its pointer enters the partner in ≥ half, confined otherwise.", ""]
    for f in sorted(glob.glob(os.path.join(a.indir, "L16_benign_s*", "lod.json"))):
        D = json.load(open(f))
        R = D["result"]
        lines = D["lines"]["lines"]
        if not lines:
            continue
        alltapes = [t for ln in lines for t in ln.get("tapes", {}).values()]
        C = classify_tapes(alltapes)
        per = []
        for ln in lines:
            idx = sorted(int(k) for k in ln["tapes"])            # 0 = newest
            steps = ln["steps"]
            seq = [(q, steps[q], ln["tapes"][str(q)], C[ln["tapes"][str(q)]]["class"]) for q in idx]
            newest_open = next((s for s in seq if s[3] == "open copier"), None)
            # oldest index q such that every sampled ancestor newer than or equal to it is a confined copier
            run = None
            for s in seq:
                if s[3] == "confined copier":
                    run = s
                else:
                    break
            between = [s for s in seq if newest_open and run and run[0] < s[0] < newest_open[0]]
            # robust transition: the oldest sampled ancestor such that >= 90% of the sampled ancestors from it to the
            # present are confined copiers; then the newest open copier older than it and the first confined copier after
            cls = np.array([s[3] == "confined copier" for s in seq])          # seq is newest first
            frac = np.cumsum(cls) / np.arange(1, len(cls) + 1)
            ok = np.where(frac >= 0.9)[0]
            tr = int(ok.max()) if len(ok) else None
            pre_open = next((s for s in seq[tr + 1:] if s[3] == "open copier"), None) if tr is not None else None
            post_conf = None
            if pre_open is not None:
                post_conf = next((s for s in reversed(seq[:seq.index(pre_open)]) if s[3] == "confined copier"), None)
            diff = ""
            if pre_open is not None and post_conf is not None:
                a_, b_ = pre_open[2].split(), post_conf[2].split()
                diff = " ".join(f"{q}:{a_[q]}>{b_[q]}" for q in range(L) if a_[q] != b_[q])
            per.append({"seed": R["seed"], "cell": ln["cell"], "t_close": R["t_close"],
                        "newest_open_step": newest_open[1] if newest_open else None, "newest_open_tape": newest_open[2] if newest_open else None,
                        "confined_from_step": run[1] if run else None, "confined_from_tape": run[2] if run else None,
                        "n_between": len(between), "between_classes": ",".join(sorted(set(s[3] for s in between))),
                        "between_tapes": " | ".join(s[2] for s in between[:6]),
                        "classes_seen": ",".join(sorted(set(s[3] for s in seq))), "n_sampled": len(seq),
                        "stable_from_step": seq[tr][1] if tr is not None else None, "pre_open_step": pre_open[1] if pre_open else None,
                        "pre_open_tape": pre_open[2] if pre_open else None, "post_conf_step": post_conf[1] if post_conf else None,
                        "post_conf_tape": post_conf[2] if post_conf else None, "diff": diff})
        P = pd.DataFrame(per)
        rows.append(P)
        P["key"] = P.newest_open_step.fillna(-1).astype(int).astype(str) + "|" + P.confined_from_step.fillna(-1).astype(int).astype(str)
        g = P.groupby("key").size().reset_index(name="lines").sort_values("lines", ascending=False)
        lines_out += [f"## World {R['seed']} (closure step {R['t_close']}, end {R['t_end']})", ""]
        P["key2"] = P.pre_open_step.fillna(-1).astype(int).astype(str) + "|" + P.post_conf_step.fillna(-1).astype(int).astype(str)
        for key2, n2 in P.groupby("key2").size().sort_values(ascending=False).head(3).items():
            e = P[P.key2 == key2].iloc[0]
            lines_out.append(f"- robust transition, {n2} of {len(P)} lines: stable from step {e.stable_from_step}; last open copier at {e.pre_open_step} `{e.pre_open_tape}` → first confined copier at {e.post_conf_step} `{e.post_conf_tape}`; changed positions {e['diff'] or '—'}")
        for r in g.head(3).itertuples():
            e = P[P.key == r.key].iloc[0]
            lines_out.append(f"- {r.lines} of {len(P)} lines: newest open-copier ancestor at step {e.newest_open_step} `{e.newest_open_tape}`; "
                             f"confined copiers without break from step {e.confined_from_step} `{e.confined_from_tape}`; "
                             f"{e.n_between} sampled ancestors between ({e.between_classes or 'none'}): {e.between_tapes or '—'}")
        lines_out.append("")
    if rows:
        A = pd.concat(rows)
        A.to_csv(os.path.join(a.out, f"traj{a.tag}.csv"), index=False)
        w = A.groupby("seed").agg(lines=("cell", "size"), open_anc=("newest_open_step", lambda s: s.notna().mean()),
                                  t_close=("t_close", "first"), conf_from=("confined_from_step", "median"), open_last=("newest_open_step", "median"))
        lines_out += ["## Summary per world", "", "| seed | lines | share of lines with an open-copier ancestor | median step of newest open ancestor | median step from which all ancestors are confined copiers | closure step |", "|---|---|---|---|---|---|"]
        for s, r in w.iterrows():
            lines_out.append(f"| {s} | {r.lines} | {r.open_anc:.2f} | {r.open_last} | {r.conf_from} | {r.t_close} |")
    open(os.path.join(a.out, f"TRAJ{a.tag}.md"), "w").write("\n".join(lines_out) + "\n")
    print("\n".join(lines_out))


if __name__ == "__main__":
    main()
