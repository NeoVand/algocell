"""C4a, post hoc: what closes under random registers. For each world closed at 3,000,000 steps (most heritable cells
confined), 32 heritable cells: share whose offspring equals the parent exactly (whole-tape copy) in 16 encounters,
share of the tape never executed (traced), and whether the cell carries a jump (`c3` JP or `18` JR) before its block move.
Also the culture test, under random registers, of short self-initialising closers built by hand.
Output: results/r4/R4_CLOSERS.md"""
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import conv  # noqa: E402
from algocell_exp import exectrace as X  # noqa: E402

L = 16
import argparse
_ap = argparse.ArgumentParser()
_ap.add_argument("--runs", default=os.path.join(HERE, "runs", "conv_long", "conv_long"))
_ap.add_argument("--csv", default="r4_long.csv")
_ap.add_argument("--name", default="R4_CLOSERS")
_ap.add_argument("--no-hand", action="store_true")
_a = _ap.parse_args()
RUNS = _a.runs
D = pd.read_csv(os.path.join(HERE, "results", "r4", _a.csv))
fin = D[(D.step == 3000000) & (D.confined_given_heritable > 0.5)]
lines = ["# C4a post hoc — the closers that evolve under random registers (generated by `r4_closers.py`)", "",
         "| seed | first closed snapshot | heritable cells tested | whole-tape exact copy (median over cells) | never-executed bytes (median) | cells executing a JP or JR | cells with LDIR / LDDR |", "|---|---|---|---|---|---|---|"]
for r in fin.itertuples():
    seed = r.seed
    rng = np.random.default_rng([seed, 77])
    first = D[(D.seed == seed) & (D.confined_given_heritable > 0.5)].step.min()
    soup = np.load(os.path.join(RUNS, f"randreg_s{seed}_t3000000.npy"))
    cand = soup[rng.choice(len(soup), 256, replace=False)]
    res = conv.assay_many_conv(cand, "randreg", n=32, seed=int(rng.integers(1 << 31)))
    her = cand[np.array([x["is_replicator"] for x in res])][:32]
    exact, unexec, jump, blk = [], [], [], []
    for t in her:
        P = rng.integers(0, 256, (16, L), dtype=np.uint8)
        out, m = conv.execute(np.concatenate([np.repeat(t[None], 16, 0), P], 1), L, 128, "randreg", int(rng.integers(1 << 31)), traced=True)
        exact.append(float((out[:, L:] == t).all(1).mean()))
        ex = X.exec_positions(m, 2 * L)[:, :L].any(axis=0)
        unexec.append(int((~ex).sum()))
        h = " ".join(f"{b:02x}" for b in np.concatenate([t, t]))
        ex_any = X.exec_positions(m, 2 * L)[:, :L].any(axis=0)
        jump.append(bool(any(t[i] in (0xC3, 0x18) and ex_any[i] for i in range(L))))
        blk.append(("ed b0" in h) or ("ed b8" in h))
    lines.append(f"| {seed} | {first:,} | {len(her)} | {np.median(exact):.2f} | {np.median(unexec):.0f} | {np.mean(jump):.2f} | {np.mean(blk):.2f} |")
if not _a.no_hand:
  lines += ["", "Hand-built closers, culture test (64 partners) under random registers and under the standard convention:", "",
            "| tape | random registers: score / gen2 | standard: score / gen2 |", "|---|---|---|"]
  rng = np.random.default_rng(5)
  for core in ("2e 00 1e 10 ed b0", "1e 10 2e 00 ed b0", "2e 00 5e ed b0", "44 5e ed b0", "21 00 00 11 10 00 01 10 00 ed b0 18 fe"):
      c = np.array([int(b, 16) for b in core.split()], np.uint8)
      tapes = np.concatenate([np.repeat(c[None], 8, 0), rng.integers(0, 256, (8, L - len(c)), dtype=np.uint8)], 1)
      if core == "44 5e ed b0":
          tapes = np.repeat(np.array([0x44, 0x5e, 0xed, 0xb0] * 4, np.uint8)[None], 8, 0)
      a = conv.assay_many_conv(tapes, "randreg", n=64, seed=1)
      b = conv.assay_many_conv(tapes, None, n=64, seed=1)
      f = lambda rs: f"{np.median([x.get('score', np.nan) for x in rs]):.2f} / {np.median([x.get('gen2_score', np.nan) for x in rs]):.2f}"
      lines.append(f"| `{core}` + random tail | {f(a)} | {f(b)} |")
open(os.path.join(HERE, "results", "r4", _a.name + ".md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
