"""Summary statistics of founding.csv by executor kind (generated table for the manuscript's genealogy numbers).

    .venv/bin/python lod_founding_summary.py      # results/lod/FOUNDING_SUMMARY.md
"""
from __future__ import annotations

import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "results", "lod")


def main():
    T = pd.read_csv(os.path.join(OUT, "founding.csv"))
    nc = T[T.executor_exec_copier < 0.5]                     # copies neither its tape nor the code it runs
    cc = T[T.executor_exec_copier >= 0.5]                    # copies the code it runs (confined producers)
    op = nc[nc.executor_soup_produces_F >= 0.5]              # open producer(s) among the non-copiers
    rare = nc[nc.executor_soup_produces_F < 0.5]
    md = ["# N3: founding executors by kind (generated by `lod_founding_summary.py` from `founding.csv`)", "",
          f"- non-copiers by both criteria: {len(nc)}; share of 512 soup partners with which they make the founder: median {nc.executor_soup_produces_F.median():.4f}; "
          f"with none of the 512: {int((nc.executor_soup_produces_F == 0).sum())}; excluding producers (≥ 0.5): median {rare.executor_soup_produces_F.median():.4f}, max {rare.executor_soup_produces_F.max():.4f}; producers: {len(op)} (worlds {', '.join(map(str, op.seed))})",
          f"- copiers of their executed code: {len(cc)}; confined (enter random partners in < half): {int((cc.executor_enters < 0.5).sum())}; make the founder with soup partners: min {cc.executor_soup_produces_F.min():.2f}",
          f"- pointer entered the partner in the founding encounter: non-copiers {int(nc.executor_entered_in_founding.sum())} of {len(nc)}, executed-code copiers {int(cc.executor_entered_in_founding.sum())} of {len(cc)}"]
    open(os.path.join(OUT, "FOUNDING_SUMMARY.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
