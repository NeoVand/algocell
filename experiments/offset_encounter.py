"""E, post hoc: encounter-level components of the matched pair (R, T) of the copy-offset switch, L = 16, benign and
lethal tar. Partners and executors are 4,096 cells drawn from the final soups of the ten mix50 mutation-on worlds of
each tar. Output: results/offset/OFFSET_ENCOUNTER.md"""
import glob
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import assay as A  # noqa: E402

L, N = 16, 4096
rng = np.random.default_rng(0)
R = np.array([0x44, 0x5e, 0xed, 0xb0] * 4, np.uint8)
lines = ["# Encounter components of the matched regenerator R and transmitter T (generated by `offset_encounter.py`)", "",
         f"L = 16; {N} encounters per entry; soup cells from the final mix50 mutation-on soups of each tar; T with a fresh random 12-byte tail per encounter.", "",
         "| tar | type | copies exactly into a soup partner | survives exactly as partner of a soup executor | core bytes 1–3 intact as partner | random single mutant still copies exactly |",
         "|---|---|---|---|---|---|"]
for tar in ("benign", "lethal"):
    zh = tar == "lethal"
    soups = [np.load(f) for f in sorted(glob.glob(os.path.join(HERE, "runs", "offset", "offset", f"L16_{tar}_muton_mix50_s*_final.npy")))]
    pool = np.concatenate(soups)
    pool = pool[rng.choice(len(pool), N, replace=False)]
    for name in ("R", "T"):
        if name == "R":
            X = np.repeat(R[None], N, 0)
        else:
            X = np.concatenate([np.tile(np.array([0xb0, 0x5e, 0xed, 0xb0], np.uint8), (N, 1)), rng.integers(0, 256, (N, 12), dtype=np.uint8)], 1)
        copy = (A.execute_pairs(np.concatenate([X, pool], 1), L, 128, zero_halts=zh)[:, L:] == X).all(1).mean()
        B = A.execute_pairs(np.concatenate([pool, X], 1), L, 128, zero_halts=zh)[:, L:]
        same = (B == X).all(1).mean()
        core = ((B[:, 1] == 0x5e) & (B[:, 2] == 0xed) & (B[:, 3] == 0xb0)).mean()
        M = X.copy()
        pos = rng.integers(0, L, N)
        M[np.arange(N), pos] = rng.integers(0, 256, N)
        P = rng.integers(0, 256, (N, L), dtype=np.uint8)
        off = A.execute_pairs(np.concatenate([M, P], 1), L, 128, zero_halts=zh)[:, L:]
        viable = ((off == M).all(1) | (off == X).all(1)).mean()
        lines.append(f"| {tar} | {name} | {copy:.3f} | {same:.3f} | {core:.3f} | {viable:.3f} |")
open(os.path.join(HERE, "results", "offset", "OFFSET_ENCOUNTER.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
