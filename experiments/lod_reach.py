"""N3 nulls for the founding events (third critic report).

1. Mutational reach: every single-byte mutant (16 × 255) of every distinct tape on the 17 first-founder chains (chain
   start to the record before the founder) is classed against 64 random partners (lod_traj.classify_tapes); per tape, the
   share of its mutants that are confined copiers. The expected number of founders made by the 54 recorded point mutations
   is the sum, over those mutations, of that share for the mutated tape.
2. Distance: the Hamming distance (best cyclic shift) from each founder to the tape its line held just before.
3. Abundance: the probability that all 17 founding executors are whole-tape non-copiers if executors were drawn by the
   soup's composition (the product of the non-copier shares at the snapshot before each founder, founders2.csv).

    .venv/bin/python lod_reach.py      # results/lod/REACH.md
"""
from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lod_traj import classify_tapes  # noqa: E402

L = 16
IND = os.environ.get("LOD_IND", os.path.join(HERE, "runs", "lod_v6_modal", "lod_v6"))   # paths only (N6 replication)
OUT = os.environ.get("LOD_OUT", os.path.join(HERE, "results", "lod"))
K = {0: "init", 1: "copy", 2: "damage", 3: "novel", 4: "mut", 5: "copyA"}


def h(a):
    return " ".join(f"{int(x):02x}" for x in a)


def hx(t):
    return np.array([int(x, 16) for x in t.split()], np.uint8)


def chain_of(z, tapes, F_step, F_tape, C):
    cand = {i for i in range(len(tapes)) if z["step"][i] == F_step and tapes[i] == F_tape}
    off = 0
    for n in z["line_lengths"]:
        ids = z["line_ids"][off:off + n]
        hit = [q for q in range(n) if ids[q] in cand]
        if hit:
            fq = hit[0]
            lo = next(q for q in range(fq + 1, n) if C[tapes[ids[q]]]["class"] == "open copier")
            return [int(ids[q]) for q in range(lo, fq - 1, -1)]
        off += n
    raise ValueError("founder not on any line")


def main():
    D = pd.read_csv(os.path.join(OUT, "founders2.csv"))
    D = D[D["first"] == True]  # noqa: E712
    chains, all_tapes = {}, set()
    for r in D.itertuples():
        z = np.load(os.path.join(IND, f"L16_benign_s{r.seed}", "line_records.npz"))
        tapes = [h(t) for t in z["tape"]]
        C = classify_tapes(sorted(set(tapes)))
        ch = chain_of(z, tapes, r.F_step, r.F_tape, C)
        chains[r.seed] = (z, tapes, ch)
        all_tapes |= {tapes[i] for i in ch[:-1]}
    # mutational reach of every distinct chain tape
    reach = {}
    for t in sorted(all_tapes):
        T = hx(t)
        muts = []
        for p in range(L):
            for v in range(256):
                if v != T[p]:
                    m = T.copy(); m[p] = v
                    muts.append(h(m))
        Cm = classify_tapes(muts)
        reach[t] = float(np.mean([Cm[m]["class"] == "confined copier" for m in muts]))
    rows, expected, n_mut = [], 0.0, 0
    for seed, (z, tapes, ch) in chains.items():
        F = ch[-1]
        prev = ch[-2]
        Fb, Pb = z["tape"][F], z["tape"][prev]
        dist = min(int((Fb != np.roll(Pb, s)).sum()) for s in range(L))
        for i in ch[1:-1]:
            if K[int(z["kind"][i])] == "mut":
                parent = int(z["p1"][i])
                expected += reach.get(tapes[parent], 0.0)
                n_mut += 1
        rows.append({"seed": seed, "dist_to_line_parent": dist,
                     "chain_tapes_with_confined_neighbour": int(sum(reach[tapes[i]] > 0 for i in ch[:-1])),
                     "max_neighbour_share": max(reach[tapes[i]] for i in ch[:-1])})
    T = pd.DataFrame(rows)
    p_abund = float(np.prod(D.soup_noncopier.values))
    md = ["# N3 nulls for the founding events (generated by `lod_reach.py`)", "",
          f"- distinct tapes on the 17 chains (before the founder): {len(reach)}; with any single-byte mutant that is a confined copier: {sum(v > 0 for v in reach.values())}; "
          f"largest share of such mutants: {max(reach.values()):.4f}",
          f"- recorded point mutations on the chains: {n_mut}; expected number that make a confined copier (sum of the mutated tapes' shares): {expected:.4f}",
          f"- founder's Hamming distance (best cyclic shift) to the tape its line held just before: median {T.dist_to_line_parent.median():.0f} (range {T.dist_to_line_parent.min()}–{T.dist_to_line_parent.max()})",
          f"- probability that all 17 founding executors are whole-tape non-copiers if drawn by soup composition: {p_abund:.3f}"]
    T.to_csv(os.path.join(OUT, "reach.csv"), index=False)
    open(os.path.join(OUT, "REACH.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
