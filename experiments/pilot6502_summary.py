"""Summary of the 6502 pilot (sizing only; PREREG_6502_DRAFT.md, predictions locked 2026-10-11).

    cd experiments && python pilot6502_summary.py   # -> results/pilot6502/PILOT.md

Reports only what the locked plan allows: speed and population-concentration trajectories (share of the most common
tape, quasispecies share), with run.py's thresholds t_02 (top share >= 0.02) and tq_10 (quasispecies share >= 0.10) at
the pilot's 500-step resolution. No tape is shown or classified.
"""
import json
from pathlib import Path

OUT = Path(__file__).resolve().parent / "results" / "pilot6502"
rows = []
for p in sorted(OUT.glob("pilot6502_*.jsonl")):
    recs = [json.loads(x) for x in p.read_text().splitlines() if x.strip()]
    cond = next(r for r in recs if r["kind"] == "condition")
    samp = [r for r in recs if r["kind"] == "sample"]
    summ = next(r for r in recs if r["kind"] == "summary")
    first = lambda key, thr: next((s["step"] for s in samp if s[key] >= thr), None)  # noqa: E731
    rows.append((cond["L"], cond["seed"], summ["steps_run"], summ["steps_per_s"], max(s["top_share"] for s in samp),
                 max(s["q_share"] for s in samp), first("top_share", 0.02), first("q_share", 0.10), samp[-1]["top_share"], samp[-1]["q_share"]))
fmt = lambda v: "none" if v is None else (f"{v:,}" if isinstance(v, int) else f"{v:.4f}")  # noqa: E731
lines = ["# 6502 pilot: sizing summary (generated by `pilot6502_summary.py`; do not edit)", "",
         "Eight worlds, 160 × 125, 128 instructions per encounter, BRK faithful, run on Modal (NVIDIA L40S) with `modal_pilot6502.py`. "
         "Only speed and concentration are reported (the locked plan forbids classifying pilot soups). t_02 and tq_10 are the first "
         "500-step samples with top-tape share ≥ 0.02 and quasispecies share ≥ 0.10 (run.py's thresholds); \"none\" = not within the run.", "",
         "| L | seed | steps | steps/s | max top share | max q share | t_02 | tq_10 | final top share | final q share |",
         "|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    lines.append("| " + " | ".join(fmt(v) if i >= 3 or v is None else f"{v:,}" for i, v in enumerate(r)) + " |")
(OUT / "PILOT.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines[-len(rows) - 2:]))
