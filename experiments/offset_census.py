"""The copy-offset census: what the first byte of the block-copy core `XX 5e ed b0` does (REVISION_PREREG E).

    .venv/bin/python offset_census.py      # -> results/offset/offset_census.csv, OFFSET_CENSUS.md

For L = 16, 20, 32 and every XX in 0..255: four tapes `XX 5e ed b0` + random tail, each against 32 random partners
(128 instructions). Classes: T (transmits: the partner ends as an exact copy of the tape in > 95% of encounters);
Rd (regenerates: the partner ends as the tiling of the tape's first d bytes, d < L); broken (neither). Also the share of
encounters with the pointer confined and the parent's own bytes after the encounter (exact, or regenerated).
"""
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import exectrace as X  # noqa: E402

rows = []
for L in (16, 20, 32):
    rng = np.random.default_rng([20261016, L])
    for xx in range(256):
        T = np.array([np.concatenate([[xx, 0x5E, 0xED, 0xB0], rng.integers(0, 256, L - 4)]) for _ in range(4)], np.uint8)
        P = rng.integers(0, 256, size=(128, L), dtype=np.uint8)
        TT = np.repeat(T, 32, 0)
        res, m = X.execute_pairs_traced(np.concatenate([TT, P], 1), L, 128)
        off, par = res[:, L:], res[:, :L]
        cls = "broken"
        if (off == TT).all(1).mean() > 0.95:
            cls = "T"
        else:
            for d in range(4, L):
                tile = np.tile(TT[:, :d], (1, L // d + 1))[:, :L]
                if (off == tile).all(1).mean() > 0.95:
                    cls = f"R{d}"
                    break
        rows.append({"L": L, "xx": f"{xx:02x}", "offset": xx % (2 * L), "class": cls, "confined": float((~X.exec_positions(m, 2 * L)[:, L:].any(1)).mean()),
                     "parent_unchanged": float((par == TT).all(1).mean())})
D = pd.DataFrame(rows)
D.to_csv(os.path.join(HERE, "results", "offset", "offset_census.csv"), index=False)
lines = ["# Copy-offset census of the block-copy core `XX 5e ed b0` (generated by `offset_census.py`)", ""]
for L, d in D.groupby("L"):
    lines.append(f"**L = {L}**")
    for c, e in d[d["class"] != "broken"].groupby("class"):
        lines.append(f"- {c}: {len(e)} values ({', '.join(e.xx)}); offsets {sorted(set(e.offset))}; confined {e.confined.min():.2f}–{e.confined.max():.2f}; parent unchanged {e.parent_unchanged.min():.2f}–{e.parent_unchanged.max():.2f}")
    nR = int(d["class"].str.startswith("R").sum())
    nT = int((d["class"] == "T").sum())
    lines.append(f"- working values: {nR} regenerating, {nT} transmitting; neutral mutation-bias equilibrium share of transmitters ≈ {nT / (nR + nT):.2f}")
    lines.append("")
open(os.path.join(HERE, "results", "offset", "OFFSET_CENSUS.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
