"""Audit item: how common is the four-byte block-copy core among confined heritable cells of the population scans?
Output: results/offset/CORE_FAMILIES.md"""
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
c = pd.read_csv(os.path.join(HERE, "results", "population", "classes_cells.csv"))
c = c[c.confined]


def fam(t):
    b = t.split()
    if b[1:4] == ["5e", "ed", "b0"]:
        return "XX 5e ed b0"
    if b[0] == "1e" and b[2:4] == ["ed", "b0"]:
        return "1e NN ed b0"
    s = " ".join(b + b)
    if "ed b0" in s or "ed b8" in s:
        return "other block copy"
    if any(x in b for x in ("c0", "c8", "c9", "d0", "d8")):
        return "carries a return"
    return "other"


c["family"] = c.tape.map(fam)
T = c.groupby(["stage", "L", "family"]).size().unstack(fill_value=0)
core = c.family.isin(["XX 5e ed b0", "1e NN ed b0"])
block = core | (c.family == "other block copy")
lines = ["# Families of confined heritable cells in the population scans (generated by `core_families.py`)", "",
         f"- confined heritable cells scanned: {len(c)}; four-byte core (`XX 5e ed b0` or `1e NN ed b0`): {int(core.sum())}; all block copiers: {int(block.sum())}; carrying a return: {int((c.family == 'carries a return').sum())}",
         f"- share of block-copy cells with the four-byte core, by stage and L: " + "; ".join(f"{s} L = {L}: {int(core[(c.stage == s) & (c.L == L)].sum())} of {int(block[(c.stage == s) & (c.L == L)].sum())}" for (s, L) in sorted(set(zip(c.stage, c.L))) if block[(c.stage == s) & (c.L == L)].sum()),
         "", T.to_markdown()]
open(os.path.join(HERE, "results", "offset", "CORE_FAMILIES.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines[:4]))
