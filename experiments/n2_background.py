"""N2 follow-up: per-capita background terms for R and T (direct R<->T copying excluded: it is neutral in counts)."""
import glob
import os

import numpy as np
import pandas as pd

O, M, R, T = 0, 1, 2, 3
rows = []
for f in sorted(glob.glob("runs/n2/*.npz")):
    comp, _, rule, _, sd = os.path.basename(f)[:-4].split("_")
    z = np.load(f)
    enc, exe, mut, occ = z["enc"], z["exe"], z["mut"], z["occ"].astype(float)
    for c, d in ((R, T), (T, R)):
        n = occ[c]
        rows.append({"comp": comp, "rule": rule, "seed": int(sd[1:]), "class": "RT"[c - 2],
                     "recolonise_O": enc[c, O, c] / n, "recolonise_M": enc[c, M, c] / n,
                     "destroyed_by_O": (enc[O, c, :].sum() - enc[O, c, c]) / n,
                     "destroyed_by_M": (enc[M, c, :].sum() - enc[M, c, c]) / n,
                     "made_by_O_or_M": (enc[O, :, c].sum() - enc[O, c, c] + enc[M, :, c].sum() - enc[M, c, c]) / n,
                     "self_change": (exe[c, :].sum() - exe[c, c]) / n,
                     "converts_intruder": (exe[:, c].sum() - exe[c, c]) / n,
                     "mutation_loss": (mut[c, :].sum() - mut[c, c]) / n, "mutation_gain": (mut[:, c].sum() - mut[c, c]) / n})
D = pd.DataFrame(rows)
sign = {"recolonise_O": 1, "recolonise_M": 1, "destroyed_by_O": -1, "destroyed_by_M": -1, "made_by_O_or_M": 1, "converts_intruder": 1, "self_change": -1, "mutation_loss": -1, "mutation_gain": 1}
lines = ["# N2 background terms (generated by `n2_background.py`)", "", "Per-capita rates per cell-step, mean over ten soups. Direct R↔T copying is excluded (neutral in counts).", "",
         "| soup | rule | class | " + " | ".join(sign) + " |", "|---|---|---|" + "---|" * len(sign)]
for (comp, rule, c), e in D.groupby(["comp", "rule", "class"]):
    lines.append(f"| {comp} | {rule} | {c} | " + " | ".join(f"{e[k].mean():.5f}" for k in sign) + " |")
lines += ["", "## T − R per component (signed: positive favours T), mean over soups, and the change from the benign to the lethal rule", "",
          "| soup | rule | " + " | ".join(sign) + " | total |", "|---|---|" + "---|" * (len(sign) + 1)]
tot = {}
for (comp, rule), e in D.groupby(["comp", "rule"]):
    Rr, Tt = e[e["class"] == "R"].set_index("seed"), e[e["class"] == "T"].set_index("seed")
    vals = {k: sign[k] * (Tt[k] - Rr[k]).mean() for k in sign}
    tot[(comp, rule)] = vals
    lines.append(f"| {comp} | {rule} | " + " | ".join(f"{v:+.5f}" for v in vals.values()) + f" | {sum(vals.values()):+.5f} |")
for comp in ("benign", "lethal"):
    dv = {k: tot[(comp, "lethal")][k] - tot[(comp, "benign")][k] for k in sign}
    lines.append(f"| {comp} | lethal − benign | " + " | ".join(f"{v:+.5f}" for v in dv.values()) + f" | {sum(dv.values()):+.5f} |")
lines += ["", "## Observed change of the transmitter share over the 2,000 steps (mean over soups)", ""]
for f_comp in ("benign", "lethal"):
    for f_rule in ("benign", "lethal"):
        sh = []
        for f in sorted(glob.glob(f"runs/n2/{f_comp}_soup_{f_rule}_rule_s*.npz")):
            c = np.load(f)["counts"]
            sh.append((c[-1][3] / (c[-1][2] + c[-1][3])) - (c[0][3] / (c[0][2] + c[0][3])))
        lines.append(f"- {f_comp} soup, {f_rule} rule: {np.mean(sh):+.4f} (range {np.min(sh):+.4f} to {np.max(sh):+.4f})")
os.makedirs("results/n2", exist_ok=True)
open("results/n2/BACKGROUND.md", "w").write("\n".join(lines) + "\n")
D.to_csv("results/n2/background.csv", index=False)
print("\n".join(lines))
