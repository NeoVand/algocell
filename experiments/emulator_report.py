"""Ring-size differential test of the soup's Z80 executor against an independent reference (summary table).

The test (src/lib/dev/z80difftest_ring.node.ts with experiments/z80_ring_gpu.py) runs random and targeted programs on the
GPU executor and on z80-emulator 2.3.0 (L. Kesteloot), both mapping every 16-bit address modulo the pair size P, and
classifies every mismatch by instruction-level re-comparison. This script summarises its JSON reports.

    .venv/bin/python emulator_report.py      # results/emulator/RING_DIFFTEST.md
"""
from __future__ import annotations

import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.join(HERE, "results", "emulator")


def main():
    md = ["# Z80 executor against an independent reference at six pair sizes (generated by `emulator_report.py`)", ""]
    for f in sorted(glob.glob(os.path.join(D, "ring_difftest_seed*.json"))):
        r = json.load(open(f))
        md += [f"## seed {r['seed']} ({os.path.basename(f)})", "", f"- reference: {r['reference']}", f"- executor: {r['core']}; {r['steps']} instructions per program", "",
               "| P | L | start SP | random | targeted | exact | match after documented reference bugs | zilion deviations | unexplained | HALT-terminated targeted checked (oracle / GPU failures) |",
               "|---|---|---|---|---|---|---|---|---|---|"]
        for P, s in sorted(r["sizes"].items(), key=lambda kv: int(kv[0])):
            o = s["outcomes"]
            quirk = sum(v for k, v in o.get("match-modulo-oracle-quirks", {}).items())
            zil = sum(v for k, v in o.get("zilion-deviation", {}).items())
            une = sum(v for k, v in o.get("unexplained", {}).items()) if "unexplained" in o else 0
            n = s["random"] + s["targeted"]
            exact = n - quirk - zil - une
            e = s["expectations"]
            md.append(f"| {P} | {s['L']} | {s['spInit']} | {s['random']:,} | {s['targeted']:,} | {exact:,} | {quirk:,} | {zil:,} | {une:,} | {e['checked']:,} ({e['oracleFails']} / {e['gpuFails']}) |")
        ev = {}
        for s in r["sizes"].values():
            for k, v in s["events"].items():
                ev[k] = ev.get(k, 0) + v["n"]
        md += ["", "Mismatch events by cause, all sizes (each verified at the instruction where it occurs): " +
               "; ".join(f"{k} {v:,}" for k, v in sorted(ev.items(), key=lambda kv: -kv[1])), ""]
    open(os.path.join(D, "RING_DIFFTEST.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
