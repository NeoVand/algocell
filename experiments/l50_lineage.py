"""Post hoc (round-2 review): the L = 50 closer's serial lineage, generation by generation. Starting from the Stage G modal
final (the pusher tiling with three inserted jumps), each generation's offspring (against random partners; the closer's
offspring does not depend on the partner while it is confined) becomes the next parent. Per generation, against 256
random partners: share of encounters with the pointer confined, share of >= 75% copies of the parent, share of offspring
identical to the modal offspring, number of jump words `20 f0`. Output: results/review_r2/l50_lineage.txt.
"""
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import assay as A  # noqa: E402
from algocell_exp import exectrace as X  # noqa: E402

L = 50
g = pd.read_csv(os.path.join(HERE, "results", "stageG", "stageG", "stage_g_runs.csv"))
t = np.array([int(b, 16) for b in g[g.L == 50].final_tape.value_counts().index[0].split()], np.uint8)
rng = np.random.default_rng(20261013)
out = ["# L = 50 closer, serial lineage (generated by l50_lineage.py; post hoc)", ""]
for gen in range(0, 7):
    P = rng.integers(0, 256, size=(256, L), dtype=np.uint8)
    res, masks = X.execute_pairs_traced(np.concatenate([np.repeat(t[None], 256, 0), P], 1), L, 128)
    off = res[:, L:]
    conf = float((~X.exec_positions(masks, 2 * L)[:, L:].any(axis=1)).mean())
    cp = float((A._best_shift_match_rows(off, np.repeat(t[None], 256, 0)) >= 0.75).mean())
    u, n = np.unique(off, axis=0, return_counts=True)
    modal = u[int(np.argmax(n))]
    nj = int(((t == 0x20) & (np.roll(t, -1) == 0xF0)).sum())
    gen2 = A.assay_many(t[None], n=64, seed=gen)[0]
    out.append(f"generation {gen}: jump words {nj}; confined in {conf:.3f} of 256 encounters; >= 75% copies {cp:.3f}; most common offspring in {n.max() / 256:.3f}; "
               f"culture test gen2 {gen2['gen2_score']:.2f} ({'heritable' if gen2['is_replicator'] else 'not heritable'}); tape {' '.join(f'{b:02x}' for b in t)}")
    t = modal
txt = "\n".join(out)
open(os.path.join(HERE, "results", "review_r2", "l50_lineage.txt"), "w").write(txt + "\n")
print(txt)
