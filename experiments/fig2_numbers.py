"""Numbers quoted in the Fig. 2 legend (world 2002, L = 16), from the video run's samples and snapshots.

    .venv/bin/python fig2_numbers.py        # results/video/FIG2_NUMBERS.md

From the sample log: zero-byte fraction, quasispecies occupancy q_share (cells within Hamming distance L/4 = 4 of the most
common tape, algocell_exp.metrics) and distinct tapes at the frame steps and at the end. From the snapshots nearest each
frame step: the four most common tapes (>= 20 copies, < half zeros), their counts, and whether each carries a conditional
return `c0` (RET NZ) or `e0` (RET PO); the exact share of the most common tape at the last snapshot.
"""
from __future__ import annotations

import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "manuscript", "figures"))
import soup_stills as ss  # noqa: E402

STEM = os.path.join(HERE, "runs", "video", "video_L16_st128_k4_s2002")
FRAMES = [5, 320, 600, 1200, 10000, 41000, 100000]
OUT = os.path.join(HERE, "results", "video")


def h(t):
    return " ".join(f"{int(b):02x}" for b in t)


def main():
    os.makedirs(OUT, exist_ok=True)
    rows = sorted((json.loads(l) for l in open(STEM + ".jsonl") if '"kind": "sample"' in l), key=lambda r: r["step"])
    by = {r["step"]: r for r in rows}
    steps = np.array(sorted(by))
    md = ["# Fig. 2 numbers (world 2002, L = 16; generated by `fig2_numbers.py`)", "",
          "q_share = share of cells within Hamming distance 4 (L/4) of the most common tape.", "",
          "| frame | step (sample) | zero bytes | q_share | distinct tapes |", "|---|---|---|---|---|"]
    for i, st in enumerate(FRAMES):
        s = int(steps[np.abs(steps - st).argmin()])
        r = by[s]
        md.append(f"| {i + 1} | {s:,} | {r['zero_frac']:.3f} | {r.get('q_share', float('nan')):.3f} | {r.get('unique', 0):,} |")
    z = np.array([by[s]["zero_frac"] for s in steps])
    md += ["", f"- zero-byte fraction peaks at {z.max():.3f} at step {int(steps[z.argmax()]):,}", ""]
    snaps = ss.snapshot_files(STEM)
    md += ["## Most common tapes at the snapshots nearest the frame steps", ""]
    for st in FRAMES:
        name, sp, f = min(snaps, key=lambda t: abs((t[1] if t[1] is not None else -1) - st))
        soup = ss.load(f, 16)
        uniq, counts = np.unique(soup, axis=0, return_counts=True)
        order = np.argsort(-counts, kind="stable")
        md.append(f"- step {sp:,} (frame step {st:,}): " + "; ".join(
            f"`{h(uniq[i])}` × {int(counts[i]):,}" + (" [c0]" if 0xC0 in uniq[i] else "") + (" [e0]" if 0xE0 in uniq[i] else "")
            for i in order[:4]))
        if st == FRAMES[-1]:
            top = uniq[order[0]]
            md.append(f"- last snapshot: most common tape `{h(top)}` holds {counts[order[0]] / len(soup):.3f} of the soup exactly; "
                      f"cells carrying `c0`: {np.mean([(0xC0 in t) for t in soup]):.3f}; carrying `e0`: {np.mean([(0xE0 in t) for t in soup]):.3f}; "
                      f"zero bytes {np.mean(soup == 0):.4f}; distinct tapes {len(uniq):,}")
    # when do the c0 and e0 classes first pass 10% of cells (snapshots)
    md += ["", "## Share of cells carrying the return-closer motif `.. e3 21 e3 21 c0` or `.. e3 21 e3 21 e0` (every 5,000 steps)", "",
           "| step | motif with c0 (RET NZ) | motif with e0 (RET PO) |", "|---|---|---|"]
    for name, sp, f in snaps:
        if sp is None or sp % 5000:
            continue
        soup = ss.load(f, 16)
        txt = [h(t) for t in soup]
        md.append(f"| {sp:,} | {np.mean(['e3 21 e3 21 c0' in t for t in txt]):.3f} | {np.mean(['e3 21 e3 21 e0' in t for t in txt]):.3f} |")
    open(os.path.join(OUT, "FIG2_NUMBERS.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
