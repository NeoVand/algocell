"""C4a (REVISION_PREREG R4): 20 random-register worlds at L = 16 (seeds 8101-8120), 3,000,000 steps (Modal).
For every snapshot: classes of 64 random cells under the world's convention (heritable by the culture test with 32
partners; confined if the pointer fetches no partner byte in 16 traced encounters), the share of cells carrying an LDIR
(`ed b0`) anywhere, and the modal tape. Prediction C4a: closure (most heritable cells confined) in <= 5 of 20 by
3,000,000 steps. Output: results/r4/R4_LONG.md, r4_long.csv
    .venv/bin/python r4_long.py
"""
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from conv_soups import classify_cells  # noqa: E402

import argparse
_ap = argparse.ArgumentParser()
_ap.add_argument("--runs", default=os.path.join(HERE, "runs", "conv_long", "conv_long"))
_ap.add_argument("--seeds", default="8101-8120")
_ap.add_argument("--name", default="R4_LONG")
_a = _ap.parse_args()
RUNS = _a.runs
_s0, _s1 = (int(x) for x in _a.seeds.split("-"))
SNAPS = (20000, 100000, 300000, 1000000, 2000000, 3000000)
OUT = os.path.join(HERE, "results", "r4")


def has_ldir(s):
    m = np.zeros(len(s), bool)
    for i in range(s.shape[1] - 1):
        m |= (s[:, i] == 0xED) & (s[:, i + 1] == 0xB0)
    return m


rows = []
for seed in range(_s0, _s1 + 1):
    rng = np.random.default_rng([seed, 41])
    for st in SNAPS:
        f = os.path.join(RUNS, f"randreg_s{seed}_t{st}.npy")
        if not os.path.exists(f):
            continue
        soup = np.load(f)
        cells = soup[rng.choice(len(soup), size=64, replace=False)]
        herit, conf = classify_cells(cells, "randreg", rng)
        u, n = np.unique(soup, axis=0, return_counts=True)
        rows.append({"seed": seed, "step": st, "heritable": float(herit.mean()),
                     "confined_given_heritable": float(conf[herit].mean()) if herit.any() else np.nan,
                     "ldir_share": float(has_ldir(soup).mean()), "zero_frac": float((soup == 0).mean()),
                     "modal": " ".join(f"{b:02x}" for b in u[int(np.argmax(n))]), "modal_share": float(n.max() / len(soup))})
        print(rows[-1], flush=True)
D = pd.DataFrame(rows)
os.makedirs(OUT, exist_ok=True)
D.to_csv(os.path.join(OUT, _a.name.lower() + ".csv"), index=False)
lines = [f"# {_a.name}: random-register worlds, seeds {_a.seeds}, to 3,000,000 steps (generated by `r4_long.py`)", "",
         "| step | worlds | heritable share (median, range) | confined among heritable (median, range) | worlds closed (most heritable cells confined) | cells carrying an LDIR (median, range) |",
         "|---|---|---|---|---|---|"]
for st, d in D.groupby("step"):
    c = d.confined_given_heritable
    lines.append(f"| {st:,} | {len(d)} | {d.heritable.median():.2f} ({d.heritable.min():.2f}–{d.heritable.max():.2f}) | {c.median():.2f} ({c.min():.2f}–{c.max():.2f}) | {int((c > 0.5).sum())} | {d.ldir_share.median():.3f} ({d.ldir_share.min():.3f}–{d.ldir_share.max():.3f}) |")
fin = D[D.step == D.step.max()]
nclosed = int((fin.confined_given_heritable > 0.5).sum())
par = [int(x) % 2 for x in fin[fin.confined_given_heritable > 0.5].seed]
pred = (f"- C4a (closure in <= 5 of 20 by 3,000,000 steps): {'met' if nclosed <= 5 else 'NOT met'} ({nclosed} of {len(fin)} closed)" if _a.name == "R4_LONG" else
        f"- C4a-rep (closure in 2-12 of 20; both seed parities if >= 4 close): {'met' if (2 <= nclosed <= 12 and (nclosed < 4 or len(set(par)) == 2)) else 'NOT met'} ({nclosed} of {len(fin)} closed; odd seeds {sum(par)}, even {len(par) - sum(par)})")
lines += ["", pred,
          "", "Modal tapes at 3,000,000 steps:", ""]
for r in fin.itertuples():
    lines.append(f"- seed {r.seed}: `{r.modal}` ({r.modal_share:.3f}); heritable {r.heritable:.2f}, confined {r.confined_given_heritable:.2f}")
open(os.path.join(OUT, _a.name + ".md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
