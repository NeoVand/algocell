"""N4 (REVISION_PREREG): do inherited payload zeros carry the lethal rule's protection of transmitters?
    .venv/bin/python n4_scars.py      # results/n2/SCARS.md, scars.csv
"""
import glob
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import exectrace as X  # noqa: E402
from offset_switch import classify  # noqa: E402
from payload_toxin import _redraw  # noqa: E402

L, N = 32, 65536
OFF = os.path.join(HERE, "runs", "offset", "offset")
rng = np.random.default_rng(20261010)
rows = []
for tar in ("benign", "lethal"):
    soup = np.concatenate([np.load(f) for f in sorted(glob.glob(os.path.join(OFF, f"L32_{tar}_muton_mix50_s*_final.npy")))])
    core, isR, isT = classify(soup, L)
    O = soup[~core]
    E = O[rng.integers(0, len(O), N)]
    Tn = soup[isT][rng.integers(0, isT.sum(), N)]
    Rn = soup[isR][rng.integers(0, isR.sum(), N)]
    Td, Ts = Tn.copy(), Tn.copy()
    for i in range(N):
        z = np.where(Tn[i, 4:] == 0)[0]
        Td[i, 4 + z] = _redraw(rng, len(z))
        other = np.where(Tn[i, 4:] != 0)[0]
        k = min(len(z), len(other))
        if k:
            pick = rng.choice(other, size=k, replace=False)
            Ts[i, 4 + pick] = _redraw(rng, k)
    for host, H, want in (("T native", Tn, 3), ("T detox", Td, 3), ("T sham", Ts, 3), ("R", Rn, 2)):
        for rule in ("benign", "lethal"):
            res, m = X.execute_pairs_traced(np.concatenate([E, H], 1), L, 128, zero_halts=(rule == "lethal"))
            B = res[:, L:]
            c, r_, t_ = classify(B, L)
            keep = t_ if want == 3 else r_
            ent = X.exec_positions(m, 2 * L)[:, L:].any(1)
            rows.append({"soup": tar, "host": host, "rule": rule, "destroyed": 1 - keep.mean(), "entered": ent.mean(),
                         "destroyed_if_entered": 1 - keep[ent].mean(), "zeros_per_host": float((H[:, 4:] == 0).sum(1).mean())})
D = pd.DataFrame(rows)
os.makedirs(os.path.join(HERE, "results", "n2"), exist_ok=True)
D.to_csv(os.path.join(HERE, "results", "n2", "scars.csv"), index=False)
lines = ["# N4: payload zeros and the lethal rule's protection (generated by `n4_scars.py`)", "",
         f"{N} encounters per row; executors = core-free cells of the soup; hosts as partner B. Destroyed = host loses its class.", "",
         "| soup | host | zeros per host | rule | destroyed | executor entered | destroyed if entered |", "|---|---|---|---|---|---|---|"]
for r in D.itertuples():
    lines.append(f"| {r.soup} | {r.host} | {r.zeros_per_host:.2f} | {r.rule} | {r.destroyed:.4f} | {r.entered:.4f} | {r.destroyed_if_entered:.4f} |")
lines += ["", "## Reduction in destruction from the benign to the lethal rule", ""]
for tar in ("benign", "lethal"):
    red = {}
    for host in ("T native", "T detox", "T sham", "R"):
        e = D[(D.soup == tar) & (D.host == host)].set_index("rule")
        red[host] = e.loc["benign", "destroyed"] - e.loc["lethal", "destroyed"]
    lines.append(f"- {tar} soup: " + "; ".join(f"{h} {v:+.4f}" for h, v in red.items()) +
                 f". N4-1 (native ≥ 2 × detox): {'met' if red['T native'] >= 2 * red['T detox'] else 'not met'}; kill (detox ≥ 0.75 × native): {'yes' if red['T detox'] >= 0.75 * red['T native'] else 'no'}; N4-2 (sham within 25% of native): {'met' if abs(red['T sham'] - red['T native']) <= 0.25 * abs(red['T native']) else 'not met'}")
open(os.path.join(HERE, "results", "n2", "SCARS.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
