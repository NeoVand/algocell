"""Exact-copy fraction of every Stage G first replicator and final dominant, and the executed/unexecuted split of the
closers' transmissible sites (post hoc, 2026-10-09; no new runs).

.venv/bin/python exact_copy.py  ->  results/stageG/EXACT_COPY.md, results/stageG/exact_copy.csv

Each tape runs as organism A against 256 seeded random partners on the culture-test executor (traced copy, byte-identical);
an encounter yields an exact copy if the partner region afterwards equals the tape at some cyclic shift (the culture test's
alignment), and an aligned copy if it equals the tape at shift 0.
"""
from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import exectrace as X  # noqa: E402

R = os.path.join(HERE, "results")


def main() -> None:
    G = pd.read_csv(os.path.join(R, "stageG", "stageG", "stage_g_runs.csv"))
    rows = []
    for _, w in G.iterrows():
        L, seed = int(w.L), int(w.seed)
        rng = np.random.default_rng([20261009, L, seed])
        P = rng.integers(0, 256, size=(256, L), dtype=np.uint8)
        for which in ("first", "final"):
            t = np.array([int(b, 16) for b in str(w[f"{which}_tape"]).split()], np.uint8)
            res, _ = X.execute_pairs_traced(np.concatenate([np.repeat(t[None], 256, 0), P], 1), L, 128)
            off = res[:, L:]
            shifts = np.stack([np.roll(t, k) for k in range(L)])
            exact = (off[:, None, :] == shifts[None, :, :]).all(axis=2).any(axis=1)
            rows.append({"L": L, "seed": seed, "which": which, "exact_frac": float(exact.mean()), "aligned_frac": float((off == t).all(axis=1).mean())})
    T = pd.DataFrame(rows)
    T.to_csv(os.path.join(R, "stageG", "exact_copy.csv"), index=False)
    out = ["# Exact copies of Stage G first replicators and final dominants (generated by exact_copy.py; do not edit)", "",
           "Fraction of 256 seeded random partners left holding an exact copy of the tape (any cyclic shift), median over 20 worlds:", ""]
    for which in ("first", "final"):
        m = T[T.which == which].groupby("L").exact_frac.median()
        out.append(f"- {which}: " + ", ".join(f"L = {L}: {v:.3f}" for L, v in m.items()))
    X_ = pd.read_csv(os.path.join(R, "exectrace", "per_replicator.csv"))
    c = X_[(X_.stage == "G") & (X_.which == "final") & (X_.has_loop.astype(bool))]
    o = X_[(X_.stage == "G") & (X_.which == "final") & (~X_.has_loop.astype(bool))]
    out.append("")
    out.append(f"- transmissible sites of Stage G final dominants: {int(X_[(X_.stage == 'G') & (X_.which == 'final')].n_sites.sum())} in all; "
               f"loop-bearing closers {int(c.n_sites.sum())} ({int(c.n_sites_unexecuted.sum())} never executed, {int(c.n_sites.sum() - c.n_sites_unexecuted.sum())} executed) "
               f"in {len(c)} tapes, {int((c.n_sites > 0).sum())} of which carry any; open finals {int(o.n_sites.sum())} in {len(o)} tapes")
    open(os.path.join(R, "stageG", "EXACT_COPY.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
