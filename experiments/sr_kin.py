"""Post hoc (not registered): serial allele retention with partners drawn from the organism's own world (kin context)
instead of uniform random bytes. Pushers at L = 16 and 50 against cells of a Stage G world in its open phase (seed 2001,
steps 10,000 and 3,000), the L = 50 closer against the same world at 300,000 steps, the RET closer against the L = 16 world
at 300,000. The copy criterion is uninformative here (a kin partner already resembles the parent), so the quantity to read
is `retained`: the share of all lineages whose tape carries the mutant window at generation g.
Output: results/serial_retention/kin_summary.csv, KIN.md.
"""
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "manuscript", "figures"))
import soup_stills as ss  # noqa: E402
from serial_retention import run_genotype, sites, panel, GENS  # noqa: E402

P = {p["key"]: p for p in panel()}
stem = lambda L: os.path.join(HERE, "runs", "stageG", f"none@closure_L{L}_st128_k4_s2001")  # noqa: E731
cases = [("pusher16", 16, "t10000"), ("pusher50", 50, "t3000"), ("jr50", 50, "final"), ("ret16", 16, "final"), ("pusher16", 16, "final"), ("pusher50", 50, "final")]
rows = []
for key, L, snap in cases:
    files = {n: f for n, st, f in ss.snapshot_files(stem(L))}
    pool = ss.load(files[snap], L)
    df, meta = run_genotype(P[key], seed=20261009, pool=pool)
    s = sites(df, meta)
    r = {"genotype": key, "L": L, "partners_from": f"Stage G L{L} seed 2001 {snap}"}
    for g in GENS:
        dg = df[(df.gen == g) & df.identifiable]
        r[f"retained_g{g}"] = float(dg.retained.mean())
        r[f"bg_g{g}"] = float(dg.bg.mean())
        r[f"sites_g{g}"] = int(s[s.gen == g].transmissible.sum())
    rows.append(r)
    print(r, flush=True)
D = pd.DataFrame(rows)
D.to_csv(os.path.join(HERE, "results", "serial_retention", "kin_summary.csv"), index=False)
lines = ["# Post hoc: serial retention with kin partners (generated by `sr_kin.py`; not registered)", "",
         "| genotype | partners drawn from | retained, g = 1 / 2 / 4 / 8 (all lineages) | sites g = 1 / 4 / 8 |", "|---|---|---|---|"]
lines += [f"| {r.genotype} | {r.partners_from} | {r.retained_g1:.2f} / {r.retained_g2:.2f} / {r.retained_g4:.2f} / {r.retained_g8:.2f} | {r.sites_g1} / {r.sites_g4} / {r.sites_g8} |" for r in D.itertuples()]
open(os.path.join(HERE, "results", "serial_retention", "KIN.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
