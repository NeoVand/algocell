"""F — ref. 22's robustness test on the Stage K tapes (registered: REVISION_PREREG.md R3/F, 2026-10-09).

    .venv/bin/python robust_ref22.py --yes      # -> results/review_r2/robust_ref22.csv, ROBUST_REF22.md

Every Stage K first replicator and final dominant (L = 32): 1,000 trials each of k = 1, 4 and 8 successive random
single-byte mutations (random position, random different value); a trial is robust if the mutant, run for 512
instructions against the all-zero partner, leaves the partner equal to the mutant (shift 0; any cyclic shift also
reported). Beside it, the share of single mutants heritable in our own scan (results/mutscan_K).
"""
import argparse
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import assay as A  # noqa: E402

L = 32


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--yes", action="store_true")
    ap.add_argument("--designed", action="store_true")
    a = ap.parse_args()
    if not a.yes:
        sys.exit("refusing to run: pass --yes after pausing the browser simulation (local GPU)")
    g = pd.read_csv(os.path.join(HERE, "results", "stageK", "stageK", "stage_g_runs.csv"))
    ms = pd.read_csv(os.path.join(HERE, "results", "mutscan_K", "mutscan_tapes.csv"))
    rows = []
    for _, w in g.iterrows():
        for which in ("first", "final"):
            t = np.array([int(b, 16) for b in w[f"{which}_tape"].split()], np.uint8)
            rng = np.random.default_rng([int(w.seed), 1 if which == "first" else 2])
            rec = {"seed": int(w.seed), "which": which, "tape": w[f"{which}_tape"], "loop": bool(w[f"{which}_has_cf"]) or bool(w[f"{which}_has_block"])}
            base = A.execute_pairs(np.concatenate([t[None], np.zeros((1, L), np.uint8)], 1), L, 512)[0, L:]
            rec["unmutated_exact"] = bool((base == t).all())
            for k in (1, 4, 8):
                M = np.repeat(t[None], 1000, 0)
                for _ in range(k):
                    pos = rng.integers(0, L, 1000)
                    delta = rng.integers(1, 256, 1000).astype(np.uint8)
                    M[np.arange(1000), pos] = (M[np.arange(1000), pos] + delta).astype(np.uint8)
                off = A.execute_pairs(np.concatenate([M, np.zeros_like(M)], 1), L, 512)[:, L:]
                rec[f"robust_k{k}"] = float((off == M).all(1).mean())
                anys = np.zeros(1000, bool)
                for s in range(L):
                    anys |= (off == np.roll(M, s, axis=1)).all(1)
                rec[f"robust_any_shift_k{k}"] = float(anys.mean())
            m = ms[(ms.seed == w.seed) & (ms.which == which)]
            rec["single_mutant_heritable_ours"] = float(m.robustness_h.iloc[0]) if len(m) else np.nan
            rows.append(rec)
            print(rec["seed"], which, rec["tape"][:11], rec["unmutated_exact"], rec["robust_k1"], rec["robust_k4"], rec["robust_k8"], rec["single_mutant_heritable_ours"], flush=True)
    D = pd.DataFrame(rows)
    out = os.path.join(HERE, "results", "review_r2")
    D.to_csv(os.path.join(out, "robust_ref22.csv"), index=False)
    lines = ["# Ref. 22's robustness test on the Stage K tapes (generated by `robust_ref22.py`)", "",
             "Share of 1,000 trials in which the mutant (k successive random single-byte mutations), run for 512 instructions against the all-zero partner, leaves an exact copy of itself in the partner (shift 0). Medians over tapes.", "",
             "| tapes | n | unmutated tape copies itself exactly | k = 1 | k = 4 | k = 8 | any shift, k = 1 | our single-mutant heritable share |", "|---|---|---|---|---|---|---|---|"]
    for lab, d in (("first replicators (pushers)", D[D.which == "first"]), ("final dominants with a loop (block copiers)", D[(D.which == "final") & D.loop]),
                   ("final dominants without a loop", D[(D.which == "final") & ~D.loop])):
        if len(d):
            lines.append(f"| {lab} | {len(d)} | {int(d.unmutated_exact.sum())} | {d.robust_k1.median():.3f} | {d.robust_k4.median():.3f} | {d.robust_k8.median():.3f} | {d.robust_any_shift_k1.median():.3f} | {d.single_mutant_heritable_ours.median():.3f} |")
    fi, fl = D[D.which == "first"], D[(D.which == "final") & D.loop]
    ok = all(fl[f"robust_k{k}"].median() > fi[f"robust_k{k}"].median() for k in (1, 4, 8))
    lines += ["", f"- F1 (block-copy finals more robust than the pushers at every k, by ref. 22's criterion): {'met' if ok else 'NOT met'}"]
    txt = "\n".join(lines)
    open(os.path.join(out, "ROBUST_REF22.md"), "w").write(txt + "\n")
    print(txt)


if __name__ == "__main__" and "--designed" not in sys.argv:
    main()


def designed():
    """Post hoc (added after F1 failed): the same test on the matched regenerator / transmitter pair of the offset switch
    at L = 32 (R = `04 5e ed b0`x8; T = `a0 5e ed b0` + 28 random bytes, 20 tails), as in ref. 22's LDIR seed."""
    rows = []
    rng = np.random.default_rng(20261019)
    tapes = [("regenerator R", np.array([0x04, 0x5e, 0xed, 0xb0] * 8, np.uint8))] + \
            [("transmitter T", np.concatenate([[0xa0, 0x5e, 0xed, 0xb0], rng.integers(0, 256, 28)]).astype(np.uint8)) for _ in range(20)]
    for lab, t in tapes:
        rec = {"design": lab}
        for k in (1, 4, 8):
            M = np.repeat(t[None], 1000, 0)
            for _ in range(k):
                pos = rng.integers(0, L, 1000)
                M[np.arange(1000), pos] = (M[np.arange(1000), pos] + rng.integers(1, 256, 1000)).astype(np.uint8)
            off = A.execute_pairs(np.concatenate([M, np.zeros_like(M)], 1), L, 512)[:, L:]
            rec[f"robust_k{k}"] = float((off == M).all(1).mean())
        rows.append(rec)
    D = pd.DataFrame(rows).groupby("design").median()
    lines = ["", "Post hoc: the matched pair of the copy-offset switch (medians; 20 transmitter tails)", "", "| design | k = 1 | k = 4 | k = 8 |", "|---|---|---|---|"]
    lines += [f"| {i} | {r.robust_k1:.3f} | {r.robust_k4:.3f} | {r.robust_k8:.3f} |" for i, r in D.iterrows()]
    open(os.path.join(HERE, "results", "review_r2", "ROBUST_REF22.md"), "a").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__" and "--designed" in sys.argv:
    designed()
