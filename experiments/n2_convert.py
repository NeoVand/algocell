"""N2 follow-up (descriptive): does an intruder that runs into a regenerator's tiled body become a regenerator?
Executors: core-free cells of the L = 32 mix50 final soups; hosts R and T from the same soups as partner B.
Output: results/n2/CONVERT.md"""
import glob
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import exectrace as X  # noqa: E402
from offset_switch import classify  # noqa: E402

L, N = 32, 65536
rng = np.random.default_rng(77)
lines = ["# Intruder conversion (generated by `n2_convert.py`; descriptive)", "", f"{N} encounters per row; executors = core-free cells; host = partner B.", "",
         "| soup | host | rule | executor entered | executor becomes R | executor becomes T | ... if entered: R | ... T | host destroyed |", "|---|---|---|---|---|---|---|---|---|"]
for tar in ("benign", "lethal"):
    soup = np.concatenate([np.load(f) for f in sorted(glob.glob(os.path.join(HERE, "runs", "offset", "offset", f"L32_{tar}_muton_mix50_s*_final.npy")))])
    core, isR, isT = classify(soup, L)
    E = soup[~core][rng.integers(0, (~core).sum(), N)]
    for host, mask, k in (("R", isR, 2), ("T", isT, 3)):
        H = soup[mask][rng.integers(0, mask.sum(), N)]
        for rule in ("benign", "lethal"):
            res, m = X.execute_pairs_traced(np.concatenate([E, H], 1), L, 128, zero_halts=(rule == "lethal"))
            ent = X.exec_positions(m, 2 * L)[:, L:].any(1)
            _, aR, aT = classify(res[:, :L], L)
            _, bR, bT = classify(res[:, L:], L)
            keep = bR if k == 2 else bT
            lines.append(f"| {tar} | {host} | {rule} | {ent.mean():.4f} | {aR.mean():.4f} | {aT.mean():.4f} | {aR[ent].mean():.4f} | {aT[ent].mean():.4f} | {1 - keep.mean():.4f} |")
os.makedirs(os.path.join(HERE, "results", "n2"), exist_ok=True)
open(os.path.join(HERE, "results", "n2", "CONVERT.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
