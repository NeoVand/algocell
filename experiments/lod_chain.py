"""N3 (addition): how the founder F of each confined lineage was assembled (uses lod_v6's full line record tables).

On each line (functional parents) the chain runs from the last open copier before the stable confined stretch to F (the
first confined copier after it; as lod_found). For every byte of F: the event on the chain at which it last took F's
value, and the source of that event (a mutation; or the tape that wrote it: the executor of a copy, the writer of a
damage record, the minor parent of a recombinant, or the overwritten tape kept by a copy), with that source's class.
Reported per founder: the number of events and of distinct contributing events (the mosaic size), the classes of the
contributing sources, the steps elapsed, and whether every tape on the chain between the last open copier and F was a
non-copier.

    .venv/bin/python lod_chain.py --indir runs/lod_v6_modal/lod_v6     # results/lod/CHAIN.md, chain.csv
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys
from collections import Counter

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lod_traj import classify_tapes  # noqa: E402

L = 16
K = {0: "init", 1: "copy", 2: "damage", 3: "novel", 4: "mut", 5: "copyA"}


def h(a):
    return " ".join(f"{int(x):02x}" for x in a)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--indir", default=os.path.join(HERE, "runs", "lod_v6_modal", "lod_v6"))
    ap.add_argument("--out", default=os.path.join(HERE, "results", "lod"))
    ap.add_argument("--tag", default="")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    rows = []
    md = ["# N3 addition: how each founder of a confined lineage was assembled (generated by `lod_chain.py`)", ""]
    for f in sorted(glob.glob(os.path.join(a.indir, "L16_benign_s*", "line_records.npz"))):
        z = np.load(f)
        res = json.load(open(os.path.join(os.path.dirname(f), "lod.json")))["result"]
        tapes = [h(t) for t in z["tape"]]
        oth = [h(t) if ho else (h(p) if hp else None) for t, ho, p, hp in zip(z["other"], z["has_other"], z["p2_tape"], z["has_p2"])]
        C = classify_tapes(sorted(set(tapes) | {t for t in oth if t}))
        cls = np.array([C[t]["class"] for t in tapes])
        done = set()
        off = 0
        for li, (cell, n) in enumerate(zip(z["line_cells"], z["line_lengths"])):
            ids = z["line_ids"][off:off + n]
            off += n
            conf = cls[ids] == "confined copier"
            frac = np.cumsum(conf) / np.arange(1, n + 1)
            ok = np.where(frac >= 0.9)[0]
            if not len(ok):
                continue
            tr = int(ok.max())
            lo = next((q for q in range(tr, n) if cls[ids[q]] == "open copier"), None)
            if lo is None:
                continue
            fq = next((q for q in range(lo - 1, -1, -1) if cls[ids[q]] == "confined copier"), None)
            F = int(ids[fq])
            if F in done:
                continue
            done.add(F)
            chain = [int(ids[q]) for q in range(lo, fq - 1, -1)]        # oldest (last open copier) ... F
            Fb = z["tape"][F]
            contrib = {}
            for qpos in range(L):
                src = None
                for i in range(len(chain) - 1, 0, -1):                     # walk back from F
                    cur, prv = chain[i], chain[i - 1]
                    if z["tape"][cur][qpos] == Fb[qpos] and z["tape"][prv][qpos] != Fb[qpos]:
                        src = cur
                        break
                contrib[qpos] = src
            srcs = Counter()
            classes = Counter()
            for qpos, rid in contrib.items():
                if rid is None:
                    srcs["inherited from the last open copier"] += 1
                    continue
                k = K[int(z["kind"][rid])]
                if k == "mut":
                    srcs["mutation"] += 1
                    continue
                if k in ("copy", "copyA"):
                    p1 = int(z["p1"][rid])
                    tsrc = tapes[p1] if p1 >= 0 else None
                    role = "copier"
                else:
                    tsrc = oth[rid]
                    role = {"damage": "writer", "novel": "minor parent"}.get(k, k)
                srcs[f"{role}"] += 1
                classes[C[tsrc]["class"] if tsrc else "?"] += 1
            events = len({rid for rid in contrib.values() if rid is not None})
            between = [cls[r] for r in chain[1:-1]]
            row = {"seed": res["seed"], "t_close": res["t_close"], "F_step": int(z["step"][F]), "F_tape": tapes[F], "F_kind": K[int(z["kind"][F])],
                   "last_open_step": int(z["step"][chain[0]]), "last_open_tape": tapes[chain[0]], "chain_records": len(chain) - 1,
                   "steps_elapsed": int(z["step"][F] - z["step"][chain[0]]), "contributing_events": events,
                   "all_between_noncopiers": all(c == "non-copier" for c in between) if between else None,
                   "sources": dict(srcs), "source_classes": dict(classes),
                   "kinds_on_chain": dict(Counter(K[int(z["kind"][r])] for r in chain[1:]))}
            rows.append(row)
            md.append(f"- world {res['seed']}: F `{tapes[F]}` at step {row['F_step']} ({row['F_kind']}); last open copier `{tapes[chain[0]]}` at {row['last_open_step']}; "
                      f"{row['chain_records']} records over {row['steps_elapsed']} steps ({row['kinds_on_chain']}); F's 16 bytes from {events} distinct events: {dict(srcs)}; "
                      f"classes of the tapes that wrote them: {dict(classes)}; every tape between was a non-copier: {row['all_between_noncopiers']}")
    D = pd.DataFrame(rows)
    D.to_csv(os.path.join(a.out, f"chain{a.tag}.csv"), index=False)
    if len(D):
        md += ["", "## Summary over founders", "",
               f"- founders: {len(D)} in {D.seed.nunique()} worlds",
               f"- F made by: " + ", ".join(f"{k} {v}" for k, v in D.F_kind.value_counts().items()),
               f"- distinct events contributing F's bytes: median {D.contributing_events.median():.0f} (range {D.contributing_events.min()}–{D.contributing_events.max()})",
               f"- records on the chain: median {D.chain_records.median():.0f}; steps elapsed: median {D.steps_elapsed.median():.0f}",
               f"- every tape between the last open copier and F a non-copier: {int((D.all_between_noncopiers == True).sum())} of {len(D)}"]  # noqa: E712
    open(os.path.join(a.out, f"CHAIN{a.tag}.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
