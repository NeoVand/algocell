def log(*a):
    print(*a, file=sys.stderr, flush=True)


def write_csv(name: str, rows: list[dict]) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    keys = list(dict.fromkeys(k for r in rows for k in r))
    with open(OUT / name, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys)
        w.writeheader()
        w.writerows(rows)


def md_table(rows: list[dict], cols: list[str], heads: list[str] | None = None) -> str:
    heads = heads or cols
    s = io.StringIO()
    s.write("| " + " | ".join(heads) + " |\n|" + "---|" * len(cols) + "\n")
    for r in rows:
        s.write("| " + " | ".join(_fmt(r[c]) for c in cols) + " |\n")
    return s.getvalue()


def _fmt(v) -> str:
    if isinstance(v, bool) or v is None:
        return str(v)
    if isinstance(v, (int, np.integer)):
        return f"{int(v):,}"
    if isinstance(v, (float, np.floating)):
        return f"{float(v):.4g}"
    return str(v)


def header(title: str, cmd: str) -> str:
    return (f"# {title}\n\nGenerated by `python zsoup_validate.py {cmd}` on {time.strftime('%Y-%m-%d %H:%M %Z')}, "
            f"adapter {adapter_summary()}. Do not edit by hand.\n\n")


# ── extraction ──────────────────────────────────────────────────────────────────────────────────────────────────────
def cmd_extraction(a) -> None:
    rows, notes = [], []
    texts = {}
    for name in ("sim_square_L16.wgsl", "sim_lethal_L16.wgsl", "sim_square_L32.wgsl", "sim_lethal_L32.wgsl"):
        src_path = SHADER_DIR / name
        composed, kept, src = extract_soup_kernels(src_path)
        items = parse_wgsl_items(src)
        # the parser accounts for all code: what lies between consecutive items is whitespace and comments only
        gaps_ok = all(C_gap.strip() == "" for C_gap in _gaps(src, items))
        texts[name] = [it.text for it in kept]
        for it in kept:
            rows.append({
                "source": name, "item": it.name, "kind": it.kind, "bytes": len(it.text), "offset": f"{it.start}-{it.end}",
                "sha256_16": hashlib.sha256(it.text.encode()).hexdigest()[:16],
                "identical_to_source_slice": src[it.start: it.end] == it.text,
                "occurrences_in_source": src.count(it.text),
                "in_zsoup_shader": it.text in composed,
            })
        dropped = [it.name for it in items if it not in kept]
        notes.append(f"- `{name}` (sha256 `{hashlib.sha256(src.encode()).hexdigest()[:16]}…`): {len(items)} top-level items, "
                     f"{len(kept)} kept; inter-item text is whitespace and comments only: {gaps_ok}; dropped {len(dropped)} "
                     f"(Z80 and helpers), including `z80_execute_batch`: {'z80_execute_batch' in dropped}")
    same = texts["sim_square_L16.wgsl"] == texts["sim_lethal_L16.wgsl"] == texts["sim_square_L32.wgsl"] == texts["sim_lethal_L32.wgsl"]
    write_csv("extraction.csv", rows)
    bad = [r for r in rows if not (r["identical_to_source_slice"] and r["occurrences_in_source"] == 1 and r["in_zsoup_shader"])]
    body = header("ZSoup: soup kernels kept verbatim", "extraction")
    body += "\n".join(notes) + "\n\n"
    body += f"Kernels kept: {', '.join('`' + k + '`' for k in SOUP_KERNELS)}; bridge kernels added: {', '.join('`' + k + '`' for k in BRIDGE_KERNELS)}.\n\n"
    body += f"- Kept items checked: {len(rows)}; byte-identical to the source slice, unique in the source and present in the ZSoup shader: {len(rows) - len(bad)} of {len(rows)}.\n"
    body += f"- The kept texts are the same in all four sources (square and lethal, L = 16 and 32): {same}.\n\n"
    body += md_table([r for r in rows if r["source"] == "sim_square_L16.wgsl"], ["item", "kind", "bytes", "offset", "sha256_16", "identical_to_source_slice", "occurrences_in_source", "in_zsoup_shader"])
    (OUT / "extraction.md").write_text(body)
    log(body)


def _gaps(src: str, items) -> list[str]:
    import re
    out, pos = [], 0
    for it in items:
        out.append(re.sub(r"//[^\n]*", "", src[pos: it.start]))
        pos = it.end
    out.append(re.sub(r"//[^\n]*", "", src[pos:]))
    return out


# ── pair executors on archived tapes ────────────────────────────────────────────────────────────────────────────────
CONDITIONS = [
    # label, (L, P, lethal), machine, pairs per soup
    ("L=16 plain", (16, 32, False), "z80c02_pair_L16", 1000),
    ("L=32 plain", (32, 64, False), "z80c02_pair_L32", 10000),
    ("L=16 lethal", (16, 32, True), "z80c02_lethal_L16", 20000),
]


def cmd_pairs(a) -> None:
    soups = C.archived_soups()
    log(f"{len(soups)} archived final soups")
    rows, summary, controls = [], [], []
    for label, (L, P, lethal), mname, per_soup in CONDITIONS:
        sel = [s for s in soups if (s["L"], s["P"], s["zero_halts"]) == (L, P, lethal)]
        machine = load_machine(mname)
        groups: dict = defaultdict(list)
        stages: dict = defaultdict(Counter)
        for s in sel:
            soup = C.load_soup(s)
            rng = np.random.default_rng([1, C.path_seed(s["path"])])
            key = (s["z80_steps"], tuple(s["suppress"]))
            groups[key].append(C.neighbour_pairs(soup, per_soup, rng, s["width"], s["height"]))
            stages[key][s["stage"]] += 1
        tot = Counter()
        distinct = []
        for (steps, sup), parts in sorted(groups.items()):
            pairs = np.concatenate(parts)
            r = C.compare_pairs(pairs, L, steps, sup, lethal, machine)
            row = {"condition": label, "machine": mname, "executor": A.executor_file(L, None, lethal), "z80_steps": steps,
                   "suppress": ";".join(sup) or "-", "stages": " ".join(f"{k}:{v}" for k, v in sorted(stages[(steps, sup)].items())),
                   "soups": len(parts), **r}
            rows.append(row)
            for k in ("soups", "pairs", "mem_changed", "b_written", "zil_halted", "mem_mismatch", "wc_mismatch", "reg_mismatch"):
                tot[k] += row[k]
            distinct.append(pairs)
            log(f"  {label} st{steps} {';'.join(sup) or '-'}: {r['pairs']} pairs, changed {r['mem_changed']}, mismatches mem {r['mem_mismatch']} wc {r['wc_mismatch']} reg {r['reg_mismatch']}")
        all_stages = Counter()
        for c in stages.values():
            all_stages.update(c)
        summary.append({"condition": label, "machine": mname, "executor": A.executor_file(L, None, lethal),
                        "stages (soups)": " ".join(f"{k}:{v}" for k, v in sorted(all_stages.items())), "groups": len(groups),
                        **{k: int(tot[k]) for k in ("soups", "pairs")},
                        "distinct_pairs": int(np.unique(np.concatenate(distinct), axis=0).shape[0]),
                        "a_equals_b": int(sum((d[:, :L] == d[:, L:]).all(axis=1).sum() for d in distinct)),
                        **{k: int(tot[k]) for k in ("mem_changed", "b_written", "zil_halted", "mem_mismatch", "wc_mismatch", "reg_mismatch")}})
        del distinct
        if label == "L=16 plain":
            # the op-traced executor (fetch and start maps) against the maps machine, on the 128-step unsuppressed group
            pairs = np.concatenate(groups[(128, ())])
            r = C.compare_pairs(pairs, L, 128, (), False, load_machine("z80c02_pair_maps_L16"), traced=True)
            maps_row = {"condition": "L=16 plain, 128 steps, no suppression", "machine": "z80c02_pair_maps_L16",
                        "executor": "op-traced " + A.executor_file(L, None, False) + " (gen_trace_shader + optrace hunks)", **r}
            log(f"  maps: {maps_row}")
            # negative controls: the comparison must see a one-instruction budget difference and the lethal rule
            sub = pairs[:20000]
            for what, mach, delta in (("Zilion budget 127 instead of 128", machine, -1),
                                      ("Zilion lethal machine against the plain executor", load_machine("z80c02_lethal_L16"), 0)):
                r = C.compare_pairs(sub, L, 128, (), False, mach, zil_budget_delta=delta)
                controls.append({"control": what, "pairs": r["pairs"], "mem_mismatch": r["mem_mismatch"], "wc_mismatch": r["wc_mismatch"], "reg_mismatch": r["reg_mismatch"]})
    used = {(L, P, lethal) for _, (L, P, lethal), _, _ in CONDITIONS}
    excluded = Counter((s["stage"], s["L"], s["P"], s["zero_halts"]) for s in soups if (s["L"], s["P"], s["zero_halts"]) not in used)
    write_csv("pairs_equivalence.csv", rows)
    body = header("Pair executors on archived evolved tapes: Algocell vs Zilion", "pairs")
    body += ("Lattice-neighbour pairs (A = a cell, B = one of its four neighbours, reflected at the edges, as `prepare_batch` draws "
             "them) sampled with seed 1 from every archived final soup of the condition (Stages A–I `*.soup_final.u8.br`, line-of-descent "
             "runs `final.npy`), run through Algocell's single-pair executor and through the vendored Zilion machine with the "
             "soup's own step budget and suppression masks. Compared per pair: final memory (2L bytes), writes into A and into B, "
             "and the registers a f b c d e h l sp pc. A mismatch count is the number of pairs that differ in that output.\n\n")
    body += (f"Archived final soups found: {len(soups):,}. Not used (no vendored machine for their L, ring P and rule): "
             + ", ".join(f"{st} L={L} P={P}{' lethal' if zh else ''}: {n}" for (st, L, P, zh), n in sorted(excluded.items())) + ".\n\n")
    body += "## Per condition\n\n" + md_table(summary, ["condition", "machine", "executor", "stages (soups)", "groups", "soups", "pairs", "distinct_pairs", "a_equals_b", "mem_changed", "b_written", "zil_halted", "mem_mismatch", "wc_mismatch", "reg_mismatch"]) + "\n"
    body += ("Pairs are drawn uniformly with replacement (`pairs` counts draws; `distinct_pairs` the distinct (A, B) byte strings among "
             "them; `a_equals_b` the draws whose two tapes are identical, common in soups full of one replicator). `mem_changed`: pairs "
             "whose memory execution changed; `b_written`: pairs with at least one write into B (both from Algocell's executor; they "
             "show the comparison is not of idle pairs). `zil_halted`: lanes the machine halted (HALT or lethal tar). Stage H soups "
             "are well mixed; their pairs are drawn as lattice neighbours all the same (executor equivalence does not depend on it).\n\n")
    body += "## Fetch and start maps\n\n" + md_table([maps_row], list(maps_row)) + "\n"
    body += "## Negative controls (must show mismatches)\n\n" + md_table(controls, list(controls[0])) + "\n"
    body += "## Per budget and suppression set\n\n" + md_table(rows, ["condition", "z80_steps", "suppress", "stages", "soups", "pairs", "distinct_pairs", "mem_changed", "mem_mismatch", "wc_mismatch", "reg_mismatch"]) + "\n"
    (OUT / "pairs_equivalence.md").write_text(body)
    log(body[:3000])


# ── step-locked differential test ───────────────────────────────────────────────────────────────────────────────────
def cmd_lockstep(a) -> None:
    runs = []
    for L in (16, 32):
        for lethal in (False, True):
            for seed in (1, 2):
                runs.append(dict(L=L, zero_halts=lethal, seed=seed, steps=a.steps))
    runs.append(dict(L=16, zero_halts=False, seed=3, steps=a.steps // 4, suppress="family:block-copy"))
    controls = [dict(L=16, zero_halts=False, seed=1, steps=200, zil_budget_delta=-1),
                dict(L=16, zero_halts=False, seed=1, steps=200, machine="z80c02_lethal_L16")]
    if a.only:
        runs = runs[: a.only]
    out, traj, wins = [], [], []
    for r in runs + controls:
        steps = r.pop("steps")
        t0 = time.perf_counter()
        ls = C.Lockstep(steps_capacity=steps, **r)
        s = ls.run(steps, dense_until=min(a.dense, steps), every=a.every, checkpoint_every=500, log=log)
        traj.extend({"machine": ls.name, "seed": ls.seed, "suppress": s["suppress"], "control": bool(r.get("zil_budget_delta") or r.get("machine")), **c} for c in ls.trajectory)
        wins.extend(ls.windows())
        s["control"] = bool(r.get("zil_budget_delta") or r.get("machine"))
        s["wall_s"] = round(time.perf_counter() - t0, 1)
        out.append(s)
        log(s)
        del ls
    write_csv("lockstep.csv", out)
    write_csv("lockstep_trajectory.csv", traj)
    write_csv("lockstep_windows.csv", wins)
    main = [s for s in out if not s["control"]]
    ctl = [s for s in out if s["control"]]
    body = header("Step-locked differential test in the original soup", "lockstep")
    body += (f"The original `Soup` runs (160 × 125, 8,192 drawn pairs per step, 128 steps per encounter, k = 4). At every step, after "
             f"`prepare_batch`, `pair_data` and `write_counts` are copied; the original `z80_execute_batch` runs in place and the Zilion "
             f"machine runs on the copies through ZSoup's own bridge (`ZBridge.encode_execute`); a comparator kernel counts, for every "
             f"step, the pair slots (all {main[0]['pairs_compared'] // main[0]['steps']:,} drawn per step, active or not) whose `pair_data` or write counts differ. The soup "
             f"continues from the original executor's output. The raw buffers are re-checked on the CPU after every step up to step "
             f"{a.dense:,}, then every {a.every}th, and the CPU counts must equal the comparator's.\n\n")
    cols = ["machine", "L", "lethal", "seed", "suppress", "steps", "steps_with_mismatch", "pair_mem_mismatches", "pair_wc_mismatches", "pairs_compared",
            "active_pairs", "active_changed", "min_window_active_changed", "last_window_active_changed", "inactive_changed", "b_written", "zil_steps", "zil_inactive_steps", "cpu_checks", "cpu_gpu_disagree", "cpu_mismatches", "first_checkpoint_t02", "top_share_max", "top_tape_at_max", "q_share_max", "first_checkpoint_q10", "wall_s"]
    body += "## Runs\n\n" + md_table(main, cols) + "\n"
    body += ("`active_changed`: active pairs whose memory the execution changed, over the run and in its 1,000-step windows (smallest "
             "window and last window; every window is in `lockstep_windows.csv`); `inactive_changed`: inactive slots whose memory the "
             "original executor changed (0; the machine's inactive slots are covered by the mismatch counts, which compare every slot, "
             "and by `zil_inactive_steps`); `zil_steps`: instructions executed by the machine's lanes, `zil_inactive_steps`: lanes of "
             "inactive pairs that executed any (0: budget 0 runs nothing). Population state at checkpoints every 500 steps "
             "(`lockstep_trajectory.csv`), as run.py measures it: `top_share` is the share of the most common tape (exact hash), "
             "`q_share` the quasispecies occupancy (cells within Hamming distance L/4 of the dominant tape); `first_checkpoint_t02` and "
             "`first_checkpoint_q10` are the first checkpoints with top_share >= 0.02 and q_share >= 0.10 (run.py's t_02 and tq_10 at "
             "500-step resolution; -1 = none); `top_tape_at_max` is the first 8 bytes of the dominant tape when top_share peaked "
             "(`01 c5 01 c5 …` is the pusher LD BC,$01C5; PUSH BC, the first replicator of Stage G at L = 16).\n\n")
    body += "## Negative controls (must show mismatches)\n\n" + md_table(ctl, ["machine", "L", "lethal", "seed", "zil_budget_delta", "steps", "steps_with_mismatch", "first_mismatch_step", "pair_mem_mismatches", "pair_wc_mismatches", "cpu_checks", "cpu_gpu_disagree", "cpu_mismatches"]) + "\n"
    (OUT / "lockstep.md").write_text(body)
    log(body)


# ── nondeterminism of the original pipeline ─────────────────────────────────────────────────────────────────────────
def cmd_nondet(a) -> None:
    rows = []
    for L, lethal, seeds in ((16, False, range(1, 6)), (16, True, range(1, 4)), (32, False, range(1, 4))):
        for seed in seeds:
            r = C.nondeterminism(L, lethal, seed, max_steps=a.max_steps)
            rows.append(r)
            log(r)
    write_csv("nondeterminism.csv", rows)
    fs = [r["first_step_soup_differ"] for r in rows]
    body = header("Run-to-run nondeterminism of the original pipeline", "nondet")
    body += ("Two runs of the original `Soup` with the same seed, one after the other in one process on one GPU, each recording the "
             "soup, the drawn pairs and the `pair_active` flags after every step. The initial soups and the drawn pairs agree (they "
             "are seeded); which drawn pairs win the collision claim (`atomicCompareExchangeWeak`, in scheduling order) need not, "
             "and the mutation write is an unsynchronised read-modify-write.\n\n")
    body += f"- Trials: {len(rows)}; first step at which the two soups differ: min {min(fs)}, median {statistics.median(fs)}, max {max(fs)} (-1 = never within {a.max_steps} steps).\n\n"
    body += md_table(rows, list(rows[0])) + "\n"
    (OUT / "nondeterminism.md").write_text(body)
    log(body)


# ── throughput ──────────────────────────────────────────────────────────────────────────────────────────────────────
def _rate(soup, steps: int, warm: int) -> float:
    soup.step(warm)
    soup.sync()
    t0 = time.perf_counter()
    soup.step(steps)
    soup.sync()
    return steps / (time.perf_counter() - t0)


def cmd_bench(a) -> None:
    rows = []
    for L, lethal in ((16, False), (16, True), (32, False)):
        mname = f"z80c02_{'lethal' if lethal else 'pair'}_L{L}"
        s_rates, z_rates = [], []
        for rep in range(a.reps):
            s = Soup(tape_length=L, seed=100 + rep, zero_halts=lethal)
            s_rates.append(_rate(s, a.steps, a.warm))
            del s
            z = ZSoup(mname, seed=100 + rep)
            z_rates.append(_rate(z, a.steps, a.warm))
            del z
        row = {"L": L, "lethal": lethal, "machine": mname, "steps_timed": a.steps, "warmup": a.warm, "reps": a.reps,
               "soup_steps_per_s": round(statistics.median(s_rates), 1), "zsoup_steps_per_s": round(statistics.median(z_rates), 1),
               "zsoup_over_soup": round(statistics.median(z_rates) / statistics.median(s_rates), 3),
               "soup_all": " ".join(f"{x:.0f}" for x in s_rates), "zsoup_all": " ".join(f"{x:.0f}" for x in z_rates)}
        rows.append(row)
        log(row)
    write_csv("throughput.csv", rows)
    body = header("Throughput: ZSoup vs Soup", "bench")
    body += (f"Steps per second (160 × 125, 8,192 drawn pairs, 128 steps per encounter, k = 4; 32 steps per submit for both), "
             f"median of {a.reps} alternating repetitions of {a.steps:,} steps after {a.warm} warm-up steps, each from a fresh soup "
             f"(seeds 100…). The GPU is shared with other jobs, so single repetitions vary; all are listed.\n\n")
    body += md_table(rows, list(rows[0])) + "\n"
    (OUT / "throughput.md").write_text(body)
    log(body)


# ── a second ISA through ZSoup (plumbing only) ──────────────────────────────────────────────────────────────────────
def cmd_plumbing(a) -> None:
    from algocell_exp.zsoup_check import plumbing_check

    lines = []
    for mname in ("m6502_pair_L16", "z80c02_pair_L16"):
        r = plumbing_check(mname, steps=a.steps)
        lines.append(r)
        log(r)
    write_csv("plumbing.csv", lines)
    body = header("ZSoup on a second ISA: plumbing only", "plumbing")
    body += ("`m6502_pair_L16` is zilion's full NMOS 6502 core (all 256 opcodes; status experimental, every one of the 2,560,000 "
             "SingleStepTests `6502/v1` vectors passes), in the same pair world with the stack given by meaning (`firstPushAt: "
             "'lastByte'`). This shows that ZSoup runs a non-Z80 machine with no Z80 assumption: after each checked step the soup's "
             "own pair memory, write counts and lane records equal a direct `ZMachine.run` of the same machine on the pairs the step "
             "drew (read from the soup before the step). It checks the plumbing, not the 6502 (the core's validation is zilion's).\n\n"
             "`pairs_changed`: active pairs whose memory the execution changed; `soup_bytes_changed`: soup bytes that differ from "
             "the initial soup after the run, mutations included (512 per step); `halted_lanes`: active lanes by halt reason / trap "
             "cause (on the 6502, trap/illegal is a JAM opcode; on the Z80, halt-insn is HALT).\n\n")
    body += md_table(lines, list(lines[0])) + "\n"
    (OUT / "plumbing.md").write_text(body)
    log(body)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("extraction")
    sub.add_parser("pairs")
    p = sub.add_parser("lockstep")
    p.add_argument("--steps", type=int, default=20000)
    p.add_argument("--dense", type=int, default=3000)
    p.add_argument("--every", type=int, default=100)
    p.add_argument("--only", type=int, default=0, help="run only the first n configurations (smoke)")
    p = sub.add_parser("nondet")
    p.add_argument("--max-steps", type=int, default=50)
    p = sub.add_parser("bench")
    p.add_argument("--steps", type=int, default=3000)
    p.add_argument("--warm", type=int, default=300)
    p.add_argument("--reps", type=int, default=3)
    p = sub.add_parser("plumbing")
    p.add_argument("--steps", type=int, default=200)
    a = ap.parse_args()
    {"extraction": cmd_extraction, "pairs": cmd_pairs, "lockstep": cmd_lockstep, "nondet": cmd_nondet, "bench": cmd_bench, "plumbing": cmd_plumbing}[a.cmd](a)


if __name__ == "__main__":
    main()
