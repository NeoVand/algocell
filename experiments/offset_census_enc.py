"""E-census (exploratory): encounter outcomes in the L = 32 equilibrium soups, composition x rule.
Output: results/offset/ENCOUNTER_CENSUS.md"""
import glob
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import assay as A  # noqa: E402
from offset_switch import classify  # noqa: E402

L, W, H = 32, 160, 125
N = 200000
rng = np.random.default_rng(20261009)


def cls(X):
    core, isR, isT = classify(X, L)
    return np.where(isR, "R", np.where(isT, "T", np.where(core, "X", "N")))


def pairs(soups):
    out_a, out_b = [], []
    per = N // len(soups)
    for s in soups:
        i = rng.integers(0, W * H, per)
        x, y = i % W, i // W
        k = rng.integers(0, 4, per)
        dx = np.array([1, -1, 0, 0])[k]
        dy = np.array([0, 0, 1, -1])[k]
        j = ((y + dy) % H) * W + (x + dx) % W
        out_a.append(s[i])
        out_b.append(s[j])
    return np.concatenate(out_a), np.concatenate(out_b)


rows = []
for comp in ("benign", "lethal"):
    soups = [np.load(f) for f in sorted(glob.glob(os.path.join(HERE, "runs", "offset", "offset", f"L32_{comp}_muton_mix50_s*_final.npy")))]
    a, b = pairs(soups)
    ca, cb = cls(a), cls(b)
    for rule in ("benign", "lethal"):
        res = A.execute_pairs(np.concatenate([a, b], 1), L, 128, zero_halts=(rule == "lethal"))
        ca2, cb2 = cls(res[:, :L]), cls(res[:, L:])
        D = pd.DataFrame({"ea": ca, "pb": cb, "pb2": cb2, "ea2": ca2})
        nR0 = (np.concatenate([ca, cb]) == "R").sum()
        nT0 = (np.concatenate([ca, cb]) == "T").sum()
        nR1 = (np.concatenate([ca2, cb2]) == "R").sum()
        nT1 = (np.concatenate([ca2, cb2]) == "T").sum()
        sh0, sh1 = nT0 / (nR0 + nT0), nT1 / (nR1 + nT1)
        for ex in ("R", "T", "X", "N", "all"):
            d = D if ex == "all" else D[D.ea == ex]
            for pc in ("R", "T"):
                e = d[d.pb == pc]
                if len(e) == 0:
                    continue
                vc = e.pb2.value_counts(normalize=True)
                rows.append({"composition": comp, "rule": rule, "executor": ex, "partner": pc, "n": len(e),
                             "stays": vc.get(pc, 0.0), "to_other": vc.get("T" if pc == "R" else "R", 0.0), "to_X": vc.get("X", 0.0), "to_N": vc.get("N", 0.0),
                             "share_exec": len(d) / len(D), "T_share_before": sh0, "T_share_after": sh1})
        print(comp, rule, "T share before", round(sh0, 4), "after one encounter round", round(sh1, 4), flush=True)
R = pd.DataFrame(rows)
R.to_csv(os.path.join(HERE, "results", "offset", "encounter_census.csv"), index=False)
lines = ["# E-census — encounter outcomes in the L = 32 equilibrium soups (generated by `offset_census_enc.py`; exploratory)", "",
         "Partner fate per encounter (stays its class / becomes the other class / core with another offset / loses the core), by executor class; composition = soups the pairs come from, rule = execution rule.", "",
         "| composition | rule | executor (share of encounters) | partner | n | stays | to other | to X | to N |", "|---|---|---|---|---|---|---|---|---|"]
for r in R.itertuples():
    lines.append(f"| {r.composition} | {r.rule} | {r.executor} ({r.share_exec:.2f}) | {r.partner} | {r.n} | {r.stays:.3f} | {r.to_other:.3f} | {r.to_X:.3f} | {r.to_N:.3f} |")
lines += ["", "Transmitter share among R + T cells before and after one round of these encounters:", ""]
for (c, ru), d in R.groupby(["composition", "rule"]):
    lines.append(f"- composition {c}, rule {ru}: {d.T_share_before.iloc[0]:.4f} → {d.T_share_after.iloc[0]:.4f} (change {d.T_share_after.iloc[0] - d.T_share_before.iloc[0]:+.4f})")
open(os.path.join(HERE, "results", "offset", "ENCOUNTER_CENSUS.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines[-6:]))
