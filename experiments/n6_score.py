"""Score the registered N6 predictions (REVISION_PREREG.md: N6 and its three amendments), written before any N6 data.

Run after the frozen analysis on the N6 worlds (LOD_IND=runs/lod_n6_modal/lod_n6, LOD_OUT=results/lod_n6):
    .venv/bin/python n6_score.py      # results/lod_n6/N6_SCORE.md
"""
from __future__ import annotations

import os
import re

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.environ.get("LOD_OUT", os.path.join(HERE, "results", "lod_n6"))
BASE = 0.00024


def main():
    F = pd.read_csv(os.path.join(OUT, "founders2.csv"))
    F1 = F[F["first"] == True]  # noqa: E712
    n = len(F1)
    T = pd.read_csv(os.path.join(OUT, "founding.csv"))
    parts = open(os.path.join(OUT, "PARTS_FIRST.md")).read()
    reach = open(os.path.join(OUT, "REACH.md")).read()
    med_share = float(re.search(r"median share of cells carrying an executed word[^:]*: ([0-9.]+)", parts).group(1))
    expected = float(re.search(r"expected number that make a confined copier[^:]*: ([0-9.]+)", reach).group(1))
    p_abund = float(re.search(r"drawn by soup composition: ([0-9.]+)", reach).group(1))
    k_ok = int(F1.F_kind.isin(["novel", "copyA"]).sum())
    k_mut = int((F1.F_kind == "mut").sum())
    between = int((F1.all_between_noncopiers == True).sum())  # noqa: E712
    nc_whole = int((T.executor_class == "non-copier").sum())
    nc_exec = int((T.executor_exec_copier < 0.5).sum())
    verdict = lambda ok: "met" if ok else "not met"  # noqa: E731
    lines = ["# N6: registered predictions scored (generated by `n6_score.py`)", "",
             f"Closed worlds with a first founder: n = {n} (of 20 recorded).", ""]
    if n < 10:
        lines.append("**Uninformative by registration (fewer than 10 closed worlds); the founder result stays exploratory.**")
    lines += ["| prediction | registered criterion | observed | verdict |", "|---|---|---|---|",
              f"| N6-1 | rewrite or copy of the partner ≥ 0.8 n and point mutation ≤ 0.1 n | {k_ok} and {k_mut} of {n} | {verdict(k_ok >= 0.8 * n and k_mut <= 0.1 * n)} |",
              f"| N6-2 | only non-copiers between chain start and founder ≥ 0.75 n | {between} of {n} | {verdict(between >= 0.75 * n)} |",
              f"| N6-3 | median share of executed words ≥ 5 × {BASE} | {med_share:.5f} ({med_share / BASE:.1f}×) | {verdict(med_share >= 5 * BASE)} |",
              f"| N6-4 | executor whole-tape non-copier ≥ 0.8 n; executed-bytes non-copier ≥ 0.6 n (with the abundance null) | {nc_whole} and {nc_exec} of {n}; abundance P = {p_abund:.3f} | {verdict(nc_whole >= 0.8 * n and nc_exec >= 0.6 * n)} |",
              f"| N6-5′ | expected founders from recorded point mutations < 0.05 | {expected:.4f} | {verdict(expected < 0.05)} |",
              "", f"Kill (point mutations complete ≥ 0.25 n first founders): {'triggered' if k_mut >= 0.25 * n else 'not triggered'} ({k_mut} of {n})."]
    open(os.path.join(OUT, "N6_SCORE.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
