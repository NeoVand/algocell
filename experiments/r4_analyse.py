"""R4 analysis: classes of 64 random cells (culture test and tracing under the world's convention) in the final soups of
the C4b/C4c invasions, plus the most common tapes. Output: results/r4/R4_INVASIONS.md, r4_inv.csv."""
import glob
import json
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import conv  # noqa: E402
from algocell_exp import exectrace as X  # noqa: E402

L = 16
rows = []
for f in sorted(glob.glob(os.path.join(HERE, "runs", "r4_inv", "r4_inv", "*.jsonl"))):
    c = json.loads(open(f).readline())
    soup = np.load(f.replace(".jsonl", "_final.npy"))
    v = c["variant"]
    rng = np.random.default_rng([c["seed"], len(f)])
    cells = soup[rng.choice(len(soup), size=64, replace=False)]
    res = conv.assay_many_conv(cells, v, n=32, seed=int(rng.integers(1 << 31)))
    herit = np.array([r["is_replicator"] for r in res])
    P = rng.integers(0, 256, size=(64 * 16, L), dtype=np.uint8)
    _, m = conv.execute(np.concatenate([np.repeat(cells, 16, 0), P], 1), L, 128, v, int(rng.integers(1 << 31)), traced=True)
    conf = ~X.exec_positions(m, 2 * L)[:, L:].any(axis=1).reshape(64, 16).any(axis=1)
    u, n = np.unique(soup, axis=0, return_counts=True)
    o = np.argsort(-n)[:2]
    rows.append({"variant": v or "std", "resident": c["resident"], "invader": c["invader"], "seed": c["seed"], "heritable": float(herit.mean()),
                 "confined_given_heritable": float(conf[herit].mean()) if herit.any() else np.nan,
                 "top1": " ".join(f"{b:02x}" for b in u[o[0]]), "top1_share": float(n[o[0]] / len(soup))})
D = pd.DataFrame(rows)
os.makedirs(os.path.join(HERE, "results", "r4"), exist_ok=True)
D.to_csv(os.path.join(HERE, "results", "r4", "r4_inv.csv"), index=False)
lines = ["# R4 invasions: classes of random cells at the end (generated by `r4_analyse.py`)", "",
         "| convention | resident | invader | soups | heritable (range) | confined among heritable (range) | most common tape (share) in seed 1 |", "|---|---|---|---|---|---|---|"]
for (v, res, inv), d in D.groupby(["variant", "resident", "invader"]):
    s1 = d.sort_values("seed").iloc[0]
    lines.append(f"| {v} | {res} | {inv} | {len(d)} | {d.heritable.min():.2f}–{d.heritable.max():.2f} | {d.confined_given_heritable.min():.2f}–{d.confined_given_heritable.max():.2f} | `{s1.top1}` ({s1.top1_share:.3f}) |")
open(os.path.join(HERE, "results", "r4", "R4_INVASIONS.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
