"""What the final dominants of Stage G are, as a population and as copiers (post hoc, 2026-10-09; no new runs).

.venv/bin/python closer_census.py   ->  results/stageG/CLOSER_CENSUS.md, results/stageG/closer_census.csv

Per world: the rank of the reported final dominant among the three most common exact tapes (assay rule: the most heritable
of the three); the share of the most common exact tape and whether it is the plain pusher tiling; at L = 50, the share of
cells carrying the jump word `20 f0`; and, for loop-bearing finals, whether the offspring in every encounter is the parent
itself or a constant variant (from results/biology/individuality/per_replicator.csv: p_modal, sim_mean).
"""
from __future__ import annotations

import glob
import os

import brotli
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results")


def main() -> None:
    G = pd.read_csv(os.path.join(R, "stageG", "stageG", "stage_g_runs.csv"))
    A = pd.read_csv(os.path.join(R, "stageG", "assays.csv"))
    P = pd.read_csv(os.path.join(R, "biology", "individuality", "per_replicator.csv"))
    P = P[(P.machine == "z80") & (P.which == "final")].assign(L=lambda d: d.group.astype(int), seed=lambda d: d.world.str.extract(r"_s(\d+)")[0].astype(int))
    rows = []
    for _, w in G.iterrows():
        L, seed = int(w.L), int(w.seed)
        a = A[(A.tape_len == L) & (A.seed == seed)]
        rank = int(a.final_rank.iloc[0]) if len(a) else -1
        snaps = glob.glob(os.path.join(HERE, "runs", "stageG", "**", f"*_L{L}_st128_k4_s{seed}.soup_final.u8.br"), recursive=True)
        top_share = jump_share = np.nan
        top_tape = ""
        if snaps:
            T = np.frombuffer(brotli.decompress(open(snaps[0], "rb").read()), np.uint8).reshape(-1, L)
            vals, cnt = np.unique(T, axis=0, return_counts=True)
            k = int(cnt.argmax())
            top_share, top_tape = cnt[k] / len(T), bytes(vals[k]).hex(" ")
            if L == 50:
                jump_share = float(np.mean([b"\x20\xf0" in bytes(t) for t in T]))
        p = P[(P.L == L) & (P.seed == seed)]
        rows.append({"L": L, "seed": seed, "final_rank": rank, "final_share": w.final_share, "loop": bool(w.final_has_cf or w.final_has_block),
                     "modal_share": top_share, "modal_is_plain_pusher": len(set(top_tape.split()[0::2])) == 1 and len(set(top_tape.split()[1::2])) == 1 if top_tape else False,
                     "jump_word_share": jump_share, "one_string": bool(len(p) and int(p.n_unique_offspring.iloc[0]) == 1),
                     "exact_self": bool(len(p) and p.p_modal.iloc[0] >= 0.999 and p.sim_mean.iloc[0] >= 0.999), "offspring_sim": float(p.sim_mean.iloc[0]) if len(p) else np.nan})
    T = pd.DataFrame(rows).sort_values(["L", "seed"])
    T.to_csv(os.path.join(R, "stageG", "closer_census.csv"), index=False)
    out = ["# Stage G final dominants as a population and as copiers (generated by closer_census.py; do not edit)", ""]
    for L, d in T.groupby("L"):
        out.append(f"- L = {L}: reported final is the most common exact tape in {int((d.final_rank == 0).sum())}/{len(d)} worlds "
                   f"(second in {int((d.final_rank == 1).sum())}, third in {int((d.final_rank == 2).sum())}); most common exact tape is a plain load–push tiling in "
                   f"{int(d.modal_is_plain_pusher.sum())}/{len(d)} (share {d.modal_share.min():.3f}–{d.modal_share.max():.3f})"
                   + (f"; cells carrying `20 f0`: {d.jump_word_share.min():.3f}–{d.jump_word_share.max():.3f} (median {d.jump_word_share.median():.3f})" if L == 50 else ""))
    c = T[T.loop]
    out.append(f"- loop-bearing finals: {len(c)}; one offspring string in all 256 encounters: {int(c.one_string.sum())}; that string is the parent itself: "
               f"{int(c.exact_self.sum())}; a constant variant of the parent: {int((c.one_string & ~c.exact_self).sum())} "
               f"(by L: {c[c.one_string & ~c.exact_self].groupby('L').size().to_dict()}; offspring similarity {c[c.one_string & ~c.exact_self].offspring_sim.min():.2f}–{c[c.one_string & ~c.exact_self].offspring_sim.max():.2f})")
    open(os.path.join(R, "stageG", "CLOSER_CENSUS.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
