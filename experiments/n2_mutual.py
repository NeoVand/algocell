"""N2 (addition): direct copying between regenerators (R) and transmitters (T) in the demography runs.

From the recorded encounter tensors (enc[executor class, partner class before, partner class after]): R executors that turn
a T partner into R, and T executors that turn an R partner into T, summed over the ten soups of each composition × rule.

    .venv/bin/python n2_mutual.py      # results/n2/MUTUAL.md
"""
from __future__ import annotations

import glob
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
RUNS = os.path.join(HERE, "runs", "n2")
OUT = os.path.join(HERE, "results", "n2")
R, T = 2, 3


def main():
    md = ["# N2: direct R ↔ T copying (generated by `n2_mutual.py`)", "",
          "| soup | rule | soups | R turns T into R | T turns R into T | difference / sum | difference / R–T encounters |",
          "|---|---|---|---|---|---|---|"]
    rel = []
    for comp in ("benign", "lethal"):
        for rule in ("benign", "lethal"):
            fs = sorted(glob.glob(os.path.join(RUNS, f"{comp}_soup_{rule}_rule_s*.npz")))
            enc = sum(np.load(f)["enc"].astype(np.int64) for f in fs)
            rt, tr = int(enc[R, T, R]), int(enc[T, R, T])
            meet = int(enc[R, T, :].sum() + enc[T, R, :].sum())
            d1 = (rt - tr) / max(rt + tr, 1)
            d2 = (rt - tr) / max(meet, 1)
            rel.append(abs(d2))
            md.append(f"| {comp} | {rule} | {len(fs)} | {rt:,} | {tr:,} | {d1:+.4f} | {d2:+.4f} |")
    md += ["", f"- largest |difference| as a share of all R–T encounters: {max(rel):.4f}"]
    open(os.path.join(OUT, "MUTUAL.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
