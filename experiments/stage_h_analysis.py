"""Stage H analysis: does space sustain the open phase? Pre-registered in PLAN.md (2026-10-08 night) before any run.

    python stage_h_analysis.py [--h-c4 results/stageH/c4/functional.csv] [--h-runs results/stageH/stageH/stage_h_runs.csv]
                               [--g-c4 results/stageG/c4/functional.csv] [--g-runs results/stageG/stageG/stage_g_runs.csv]
                               [--out results/stageH]

Measures per world (identical for the lattice control, Stage G L = 16, and the well-mixed worlds, Stage H):
  h_open     median heritable fraction of 16 random cells over sampled steps 2,000–20,000 (c4 functional census)
  t_close70  first sampled step at which the heritable fraction is ≥ 0.7 (censored at the horizon if never)
  t_rep      first heritable top-3 exemplar (assay pipeline); pusher = period-2 tape `LD rr,nn ; PUSH rr`
Predictions (fixed before the data): H0 pusher first in ≥ 7/10 mixed worlds with t_rep in 100–5,000; H1 h_open lower under
mixing (mixed median < lattice median 0.125; one-sided Mann–Whitney P < 0.05; kill: median ≥ 0.125 with P ≥ 0.2);
H2 closure sooner under mixing (t_close70 mixed median < 30,000; one-sided P < 0.05; kill: median ≥ 30,000 with P ≥ 0.2);
strong form: ≥ 4/10 mixed worlds without a heritable replicator by 300,000 steps.
The one-sided P values are the normal approximation with tie correction and a seeded Monte-Carlo permutation P (100,000
draws); both are reported. The script runs on the control alone (baselines) when the Stage H files are absent.
"""

from __future__ import annotations

import argparse
import math
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results")
PUSH = {("01", "c5"), ("11", "d5"), ("21", "e5")}


def world_measures(c4: pd.DataFrame, L: int, horizon: int) -> pd.DataFrame:
    rows = []
    for seed, d in c4[c4["tape_len"] == L].groupby("seed"):
        d = d.sort_values("step")
        win = d[(d["step"] >= 2000) & (d["step"] <= 20000)]["frac_heritable"]
        hi = d[d["frac_heritable"] >= 0.7]
        rows.append({"seed": int(seed), "h_open": float(win.median()) if len(win) else np.nan,
                     "t_close70": float(hi["step"].min()) if len(hi) else np.nan, "closed": bool(len(hi)),
                     "h_final": float(d["frac_heritable"].iloc[-1]), "horizon": horizon})
    return pd.DataFrame(rows)


def is_pusher(tape_hex: str) -> bool:
    b = tape_hex.strip().split()
    if len(b) < 4:
        return False
    a, c = b[0].lower(), b[1].lower()
    return (a, c) in PUSH and all(b[i].lower() == (a if i % 2 == 0 else c) for i in range(len(b) - 1))


def mann_whitney_less(x: np.ndarray, y: np.ndarray, n_perm: int = 100_000, seed: int = 0) -> dict:
    """One-sided test that x (mixed) tends to be SMALLER than y (lattice). Returns U, normal-approximation P and a
    permutation P (fraction of label shuffles with U_x ≤ observed)."""
    x, y = np.asarray(x, float), np.asarray(y, float)
    allv = np.concatenate([x, y])
    ranks = pd.Series(allv).rank(method="average").values
    nx, ny = len(x), len(y)
    u = ranks[:nx].sum() - nx * (nx + 1) / 2          # U for x: number of (x, y) pairs with x > y (+ ties/2)
    mu = nx * ny / 2
    _, counts = np.unique(allv, return_counts=True)
    tie = (counts**3 - counts).sum()
    n = nx + ny
    sigma = math.sqrt(nx * ny / 12 * ((n + 1) - tie / (n * (n - 1)))) if n > 1 else float("nan")
    z = (u + 0.5 - mu) / sigma if sigma > 0 else float("nan")
    p_norm = 0.5 * (1 + math.erf(z / math.sqrt(2))) if sigma > 0 else float("nan")   # P(U ≤ u): small U = x small
    rng = np.random.default_rng(seed)
    hits = 0
    for _ in range(n_perm):
        perm = rng.permutation(n)
        up = ranks[perm[:nx]].sum() - nx * (nx + 1) / 2
        hits += up <= u
    return {"U": float(u), "z": float(z), "p_normal": float(p_norm), "p_perm": (hits + 1) / (n_perm + 1), "n_x": nx, "n_y": ny}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--h-c4", default=os.path.join(R, "stageH", "c4", "functional.csv"))
    ap.add_argument("--h-runs", default=os.path.join(R, "stageH", "stageH", "stage_h_runs.csv"))
    ap.add_argument("--g-c4", default=os.path.join(R, "stageG", "c4", "functional.csv"))
    ap.add_argument("--g-runs", default=os.path.join(R, "stageG", "stageG", "stage_g_runs.csv"))
    ap.add_argument("--out", default=os.path.join(R, "stageH"))
    ap.add_argument("--horizon", type=int, default=300000)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    lines = ["# Stage H numbers (generated by stage_h_analysis.py)", ""]

    G = world_measures(pd.read_csv(a.g_c4), 16, a.horizon)
    gr = pd.read_csv(a.g_runs)
    gr = gr[gr["L"] == 16]
    G = G.merge(gr[["seed", "t_rep", "first_tape"]], on="seed", how="left")
    G["pusher_first"] = G["first_tape"].fillna("").map(is_pusher)
    G["group"] = "lattice"
    lines += ["## Lattice control (Stage G, L = 16)", "",
              f"- worlds {len(G)}; t_rep median {G['t_rep'].median():.0f} (IQR {G['t_rep'].quantile(.25):.0f}–{G['t_rep'].quantile(.75):.0f}); pusher first in {int(G['pusher_first'].sum())}/{len(G)}",
              f"- h_open median {G['h_open'].median():.3f} (IQR {G['h_open'].quantile(.25):.3f}–{G['h_open'].quantile(.75):.3f})",
              f"- t_close70 median {G['t_close70'].median():.0f} (IQR {G['t_close70'].quantile(.25):.0f}–{G['t_close70'].quantile(.75):.0f}); reached in {int(G['closed'].sum())}/{len(G)}", ""]

    have_h = os.path.exists(a.h_c4)
    if have_h:
        H = world_measures(pd.read_csv(a.h_c4), 16, a.horizon)
        if os.path.exists(a.h_runs):
            hr = pd.read_csv(a.h_runs)
            hr = hr[hr["L"] == 16] if "L" in hr else hr
            H = H.merge(hr[["seed", "t_rep", "first_tape"]], on="seed", how="left")
        else:
            H["t_rep"], H["first_tape"] = np.nan, ""
        H["pusher_first"] = H["first_tape"].fillna("").map(is_pusher)
        H["group"] = "mixed"
        no_life = int(H["t_rep"].isna().sum())
        strong = no_life >= 4
        h0_ok = int((H["pusher_first"] & H["t_rep"].between(100, 5000)).sum())
        # censored closure times rank worst
        tc_h = H["t_close70"].fillna(a.horizon + 1).values
        tc_g = G["t_close70"].fillna(a.horizon + 1).values
        t1 = mann_whitney_less(H["h_open"].dropna().values, G["h_open"].dropna().values)
        t2 = mann_whitney_less(tc_h, tc_g)
        med_h1, med_h2 = float(H["h_open"].median()), float(np.median(tc_h))
        def verdict(med, base, t, lower_is_pred=True):
            p = t["p_perm"]
            if med < base and p < 0.05:
                return "met"
            if med >= base and p >= 0.2:
                return "killed"
            return "between"
        v1, v2 = verdict(med_h1, 0.125, t1), verdict(med_h2, 30000, t2)
        pred = pd.DataFrame([
            {"prediction": "H0", "statement": "pusher first, t_rep in 100–5,000, ≥ 7/10", "value": f"{h0_ok}/{len(H)}", "outcome": "met" if h0_ok >= 7 else "not met"},
            {"prediction": "strong form", "statement": "≥ 4/10 mixed worlds with no heritable replicator by horizon", "value": f"{no_life}/{len(H)}", "outcome": "triggered" if strong else "not triggered"},
            {"prediction": "H1", "statement": "h_open mixed median < 0.125, one-sided P < 0.05 (kill: ≥ 0.125 and P ≥ 0.2)", "value": f"median {med_h1:.3f}; P_perm {t1['p_perm']:.4f}; P_norm {t1['p_normal']:.4f}", "outcome": v1},
            {"prediction": "H2", "statement": "t_close70 mixed median < 30,000, one-sided P < 0.05 (kill: ≥ 30,000 and P ≥ 0.2)", "value": f"median {med_h2:.0f}; P_perm {t2['p_perm']:.4f}; P_norm {t2['p_normal']:.4f}", "outcome": v2},
        ])
        pred.to_csv(os.path.join(a.out, "predictions.csv"), index=False)
        lines += ["## Well-mixed worlds (Stage H)", "",
                  f"- worlds {len(H)}; no heritable replicator by horizon: {no_life}; pusher first with t_rep in 100–5,000: {h0_ok}/{len(H)}",
                  f"- t_rep median {H['t_rep'].median():.0f}; h_open median {med_h1:.3f} (IQR {H['h_open'].quantile(.25):.3f}–{H['h_open'].quantile(.75):.3f}); t_close70 median {med_h2:.0f}, reached in {int(H['closed'].sum())}/{len(H)}",
                  "", "## Verdicts", "", pred.to_markdown(index=False), ""]
        both = pd.concat([G, H], ignore_index=True)
    else:
        lines += ["## Well-mixed worlds (Stage H)", "", "- not yet available", ""]
        both = G
    both.to_csv(os.path.join(a.out, "per_world.csv"), index=False)
    open(os.path.join(a.out, "NUMBERS_H.md"), "w").write("\n".join(lines))
    print("\n".join(lines))

    if have_h:
        import sys
        sys.path.insert(0, HERE)
        import figstyle as fs
        import matplotlib.pyplot as plt
        sys.path.insert(0, os.path.join(HERE, "manuscript", "figures"))
        import figcheck
        fs.setup()
        fig, axes = plt.subplots(1, 2, figsize=(fs.DOUBLE * 0.6, 45 * fs.MM))
        rng = np.random.default_rng(0)
        for ax, col, ylab, log in ((axes[0], "h_open", "heritable fraction, steps 2,000–20,000", False), (axes[1], "t_close70", "step at which heritability reaches 0.7", True)):
            for k, (name, d) in enumerate((("lattice", G), ("mixed", H))):
                v = d[col].fillna(a.horizon * 1.5 if log else np.nan).values
                ax.scatter(k + rng.uniform(-0.15, 0.15, len(v)), v, s=9, facecolors="none", edgecolors="#1C2733" if k == 0 else "#E8431F", lw=0.6)
                ax.hlines(np.nanmedian(d[col].values), k - 0.25, k + 0.25, color="#1C2733" if k == 0 else "#E8431F", lw=1.0)
            ax.set_xticks([0, 1], ["lattice", "mixed"])
            ax.set_xlim(-0.6, 1.6)
            if log:
                ax.set_yscale("log")
            fs.tidy(ax, None, ylab)
        figcheck.print_report(figcheck.check(fig), "stageH_measures")
        fs.save(fig, os.path.join(a.out, "stageH_measures"))


if __name__ == "__main__":
    main()
