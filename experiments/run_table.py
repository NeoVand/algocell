"""Extended Data Table 4: every soup run of the Z80 stages, from the run summaries (second report, item 10).
Output: results/review_r2/RUN_TABLE.md"""
import glob
import json
import os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
STAGES = ["stageA", "stageB", "stageC", "stageD", "stageE", "stageF", "stageG", "stageH", "stageI", "stageK", "stageL", "stageM"]


def rng(v):
    v = sorted(set(v))
    return f"{v[0]}–{v[-1]}" if len(v) > 1 and v == list(range(v[0], v[-1] + 1)) else ", ".join(str(x) for x in v) if len(v) <= 8 else f"{v[0]}–{v[-1]} ({len(v)})"


lines = ["# Extended Data Table 4 — every Z80 soup run (generated by `run_table.py` from the run summaries)", "",
         "| stage | runs | arms (instruction sets) | tape lengths L | budgets (instructions per encounter) | mutations per step | seeds | horizon (steps) | stopped early |",
         "|---|---|---|---|---|---|---|---|---|"]
total = 0
for st in STAGES:
    files = glob.glob(os.path.join(HERE, "runs", st, "**", "*.summary.json"), recursive=True)
    if not files:
        continue
    S = [json.load(open(f)) for f in files]
    arms = sorted({(s.get("label") or "").split("@")[0] or "none" for s in S})
    Ls = [int(s["tape_length"]) for s in S]
    bud = [int(s["z80_steps"]) for s in S]
    mut = sorted({s.get("mutations_per_step") for s in S if s.get("mutations_per_step") is not None})
    seeds = [int(s["seed"]) for s in S]
    hz = sorted({int(s["horizon"]) for s in S})
    early = sum(1 for s in S if s.get("steps_run") is not None and int(s["steps_run"]) < int(s["horizon"]) and not s.get("censored", False))
    total += len(S)
    lines.append(f"| {st[5:]} | {len(S)} | {len(arms)}: {', '.join(arms[:6])}{' …' if len(arms) > 6 else ''} | {rng(Ls)} | {rng(bud)} | {', '.join(str(m) for m in mut[:6])}{' …' if len(mut) > 6 else ''} | {rng(seeds)} | {', '.join(f'{h:,}' for h in hz)} | {early} |")
lines += ["", f"- total Z80 soup runs in these stages: {total:,}"]
open(os.path.join(HERE, "results", "review_r2", "RUN_TABLE.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
