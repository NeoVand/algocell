"""N3 (addition): were the parts of each founder already circulating in the soup before it was assembled?

For each founder F (lod_chain): the two-byte words F executes (each instruction start p and byte p+1, from the
instruction-start trace against random partners), and, in the last soup snapshot before F's birth (lod_v6 saves the soup
every 2,000 steps), the share of cells carrying each word anywhere (cyclically), split by the class of the carrying cell
(open copier, confined copier, non-copier; classified against random partners). Also: whether any cell already carried F's
whole executed segment (every executed position, at any cyclic shift). Baseline for a random 16-byte tape: about 16/65,536
= 0.00024 per word.

    .venv/bin/python lod_parts.py --indir runs/lod_v6_modal/lod_v6      # results/lod/PARTS.md, parts.csv
"""
from __future__ import annotations

import argparse
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lod_origin import roles  # noqa: E402
from lod_traj import classify_tapes  # noqa: E402

L = 16


def hx(t):
    return np.array([int(x, 16) for x in t.split()], np.uint8)


def has_word(S: np.ndarray, w0: int, w1: int) -> np.ndarray:
    return ((S == w0) & (np.roll(S, -1, axis=1) == w1)).any(1)


def has_segment(S: np.ndarray, F: np.ndarray, ex: np.ndarray) -> np.ndarray:
    """Any cyclic shift s at which S matches F on every executed position of F."""
    out = np.zeros(len(S), bool)
    pos = np.where(ex)[0]
    for s in range(L):
        Fr = np.roll(F, s)
        pr = (pos + s) % L
        out |= (S[:, pr] == Fr[pr]).all(1)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--indir", default=os.path.join(HERE, "runs", "lod_v6_modal", "lod_v6"))
    ap.add_argument("--chain", default=os.path.join(HERE, "results", "lod", "chain_v6.csv"))
    ap.add_argument("--out", default=os.path.join(HERE, "results", "lod"))
    ap.add_argument("--tag", default="_v6")
    a = ap.parse_args()
    D = pd.read_csv(a.chain).drop_duplicates(["seed", "F_step", "F_tape"])
    rows, md = [], ["# N3 addition: were the founder's parts already in the soup? (generated by `lod_parts.py`)", ""]
    for r in D.itertuples():
        z = np.load(os.path.join(a.indir, f"L16_benign_s{r.seed}", "soups.npz"))
        steps = z["steps"]
        k = np.where(steps < r.F_step)[0]
        if not len(k):
            continue
        S = z["soups"][k.max()]
        t_snap = int(steps[k.max()])
        F = hx(r.F_tape)
        R = roles([r.F_tape])[r.F_tape]
        starts = np.where(R["start"] >= 0.5)[0]
        ex = R["fetch"] >= 0.5
        words = sorted({(int(F[p]), int(F[(p + 1) % L])) for p in starts})
        # classify the cells that carry any of F's words (all distinct tapes among them)
        carry_any = np.zeros(len(S), bool)
        per = {}
        for w in words:
            hw = has_word(S, *w)
            per[w] = hw
            carry_any |= hw
        tapes = [" ".join(f"{x:02x}" for x in row) for row in S[carry_any]]
        C = classify_tapes(tapes) if tapes else {}
        cls_all = np.array(["-"] * len(S), dtype=object)
        cls_all[np.where(carry_any)[0]] = [C[t]["class"] for t in tapes]
        seg = has_segment(S, F, ex)
        for w, hw in per.items():
            rows.append({"seed": r.seed, "F_step": r.F_step, "F_tape": r.F_tape, "snapshot": t_snap, "word": f"{w[0]:02x} {w[1]:02x}",
                         "share": float(hw.mean()), "share_noncopier": float((hw & (cls_all == "non-copier")).mean()),
                         "share_open": float((hw & (cls_all == "open copier")).mean()), "share_confined": float((hw & (cls_all == "confined copier")).mean()),
                         "segment_share": float(seg.mean()), "segment_cells": int(seg.sum())})
        e = pd.DataFrame([x for x in rows if x["seed"] == r.seed and x["F_step"] == r.F_step])
        md.append(f"- world {r.seed}, F `{r.F_tape}` at step {r.F_step} (snapshot {t_snap}): executed words " +
                  "; ".join(f"`{x.word}` in {x.share:.4f} of cells (non-copiers {x.share_noncopier:.4f}, open {x.share_open:.4f}, confined {x.share_confined:.4f})" for x in e.itertuples()) +
                  f"; cells already carrying F's whole executed segment: {int(e.segment_cells.iloc[0])} ({e.segment_share.iloc[0]:.5f})")
    P = pd.DataFrame(rows)
    P.to_csv(os.path.join(a.out, f"parts{a.tag}.csv"), index=False)
    if len(P):
        md += ["", "## Summary", "", f"- founders: {P.groupby(['seed', 'F_step']).ngroups}; executed words: {len(P)}",
               f"- median share of cells carrying an executed word before the founder: {P.share.median():.4f} (random-tape baseline ≈ 0.00024)",
               f"- of carriers, share in non-copiers (median over words): {(P.share_noncopier / P.share.replace(0, np.nan)).median():.2f}",
               f"- founders whose whole executed segment was already carried by some cell: {int((P.groupby(['seed', 'F_step']).segment_cells.first() > 0).sum())} of {P.groupby(['seed', 'F_step']).ngroups}"]
    open(os.path.join(a.out, f"PARTS{a.tag}.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
