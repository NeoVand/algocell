"""Generate the two Extended Data tables of the v4 manuscript as Markdown (printed to stdout and written to
manuscript/ed_tables.md). Table 1 from results/stageG/stageG/stage_g_runs.csv; Table 2 from make_conds.ABLATIONS via isa.

    .venv/bin/python manuscript/ed_tables.py
"""
from __future__ import annotations

import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, EXP)
from algocell_exp import isa  # noqa: E402
import make_conds  # noqa: E402


def mechanism(cf: str, block: str) -> str:
    cf, block = str(cf), str(block)
    if block not in ("-", "nan", ""):
        return "block copy (" + block + ")"
    if "RET" in cf:
        return "conditional return (RET NZ)" if "RET NZ" in cf else "return"
    if "JR" in cf or "DJNZ" in cf:
        return "relative jump (" + ("DJNZ" if "DJNZ" in cf else "JR") + ")"
    if "JP" in cf or "CALL" in cf:
        return "absolute jump (" + cf.split("+")[0] + ")"
    return "none: the open pusher"


def table1() -> str:
    d = pd.read_csv(os.path.join(EXP, "results", "stageG", "stageG", "stage_g_runs.csv"))
    d["mech"] = [mechanism(c, b) for c, b in zip(d.final_cf, d.final_block)]
    rows = ["| L | instruction that closes the cycle | worlds | most common final tape in the class (worlds) | partners copied | self-damage |",
            "|---:|:---|---:|:---|---:|---:|"]
    for L in (16, 20, 50, 64):
        g = d[d.L == L]
        for mech, h in sorted(g.groupby("mech"), key=lambda kv: -len(kv[1])):
            vc = h.final_tape.value_counts()
            tape = vc.index[0].split()
            shown = " ".join(tape[:8]) + (" …" if len(tape) > 8 else "")
            rows.append(f"| {L} | {mech} | {len(h)} | `{shown}` ({vc.iloc[0]}) | {h.final_copied.median():.2f} | {h.final_damaged.median():.2f} |")
    return "\n".join(rows)


def table2() -> str:
    order = ["none", "block-copy", "stack-writes", "stack-write-only", "stack-read-only", "push-only", "push", "ex-sp-only", "call-rst",
             "call-rst-write", "ld-mem", "ld-imm", "ld-reg", "all-ld", "ed-loads", "cb-page", "no-copy", "rmw-only", "i8080"]
    rows = ["| ablation | opcodes made no-ops | patterns (instruction families or mnemonics) |", "|:---|---:|:---|"]
    for name in order:
        pats = make_conds.ABLATIONS[name]
        n = isa.count(isa.resolve(pats)) if pats else 0
        shown = ", ".join(p.strip().replace("family:", "") for p in pats if not p.startswith("ed:"))
        ed = [p for p in pats if p.startswith("ed:")]
        if ed:
            shown = (shown + ", " if shown else "") + f"{len(ed)} ED-page opcodes"
        rows.append(f"| `{name}` | {n} | {shown or '(none)'} |")
    return "\n".join(rows)


if __name__ == "__main__":
    t1, t2 = table1(), table2()
    out = "<!-- generated by manuscript/ed_tables.py; do not edit by hand -->\n\n" + t1 + "\n\n" + t2 + "\n"
    open(os.path.join(HERE, "ed_tables.md"), "w").write(out)
    print(out)
