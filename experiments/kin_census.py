"""Descriptive (pre-registered as descriptive in the Stage H entry of PLAN.md): how often does the first replicator meet
kin? From the interaction census recorded at every snapshot step (128 sampled encounters: cell indices and the four tapes
before/after), for every encounter in which one side is the world's first heritable tape (exact), classify the partner as
kin (Hamming distance ≤ 2 to the first tape) or stranger, and record whether the first-tape side was damaged (its own bytes
changed) and whether the partner became a ≥ 75% copy. Summarised per world over the open phase (snapshot steps 2,000–20,000),
lattice (Stage G L = 16) against mixed (Stage H).

    python kin_census.py [--out results/stageH]
"""
from __future__ import annotations

import argparse
import glob
import json
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))


def hexs(s: str) -> np.ndarray:
    return np.frombuffer(bytes.fromhex(s), np.uint8)


def hamming(a: np.ndarray, b: np.ndarray) -> int:
    return int((a != b).sum())


def world_rows(jsonl: str, first_tape_hex: str, lo: int, hi: int) -> dict:
    first = hexs(first_tape_hex)
    L = len(first)
    n_enc = kin = damaged_kin = damaged_str = copy_kin = copy_str = 0
    for line in open(jsonl):
        if '"census"' not in line:
            continue
        r = json.loads(line)
        if not (lo <= r["step"] <= hi):
            continue
        for p in r["census"].get("pairs", []):
            _, _, a0, b0, a1, b1 = p
            A0, B0, A1, B1 = hexs(a0), hexs(b0), hexs(a1), hexs(b1)
            for me0, me1, other0, other1 in ((A0, A1, B0, B1), (B0, B1, A0, A1)):
                if hamming(me0, first) != 0:
                    continue
                n_enc += 1
                is_kin = hamming(other0, first) <= 2
                dmg = hamming(me0, me1) >= max(1, L // 4)        # ≥ 25% of own bytes changed, as the partner test's damage
                cp = (L - hamming(other1, first)) / L >= 0.75    # partner became a ≥ 75% copy (no shift tolerance here)
                kin += is_kin
                if is_kin:
                    damaged_kin += dmg; copy_kin += cp
                else:
                    damaged_str += dmg; copy_str += cp
    return {"encounters": n_enc, "kin_frac": kin / n_enc if n_enc else np.nan,
            "damage_kin": damaged_kin / kin if kin else np.nan, "damage_stranger": damaged_str / (n_enc - kin) if n_enc - kin else np.nan,
            "copy_kin": copy_kin / kin if kin else np.nan, "copy_stranger": copy_str / (n_enc - kin) if n_enc - kin else np.nan}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(HERE, "results", "stageH"))
    ap.add_argument("--lo", type=int, default=2000)
    ap.add_argument("--hi", type=int, default=20000)
    a = ap.parse_args()
    rows = []
    for group, rundir, table in (("lattice", "runs/stageG", "results/stageG/stageG/stage_g_runs.csv"), ("mixed", "runs/stageH", "results/stageH/stageH/stage_g_runs.csv")):
        T = pd.read_csv(os.path.join(HERE, table))
        T = T[T["L"] == 16] if "L" in T else T
        for _, t in T.iterrows():
            seed = int(t["seed"])
            files = [f for f in glob.glob(os.path.join(HERE, rundir, f"*_L16_st128_k4_s{seed}.jsonl"))]
            if not files or not isinstance(t["first_tape"], str):
                continue
            tape_hex = t["first_tape"].replace(" ", "")
            row = world_rows(files[0], tape_hex, a.lo, a.hi)
            row.update({"group": group, "seed": seed, "first_tape": t["first_tape"][:23]})
            rows.append(row)
    D = pd.DataFrame(rows)
    D.to_csv(os.path.join(a.out, "kin_census.csv"), index=False)
    S = D.groupby("group")[["encounters", "kin_frac", "damage_kin", "damage_stranger", "copy_kin", "copy_stranger"]].median().round(3)
    lines = ["# Kin census (descriptive; generated by kin_census.py)", "", f"Open-phase snapshot steps {a.lo}–{a.hi}; encounters in which one side is the world's first heritable tape (exact).", "",
             "## Medians over worlds", "", S.to_markdown(), "", "## Per world", "", D.round(3).to_markdown(index=False)]
    open(os.path.join(a.out, "KIN_CENSUS.md"), "w").write("\n".join(lines))
    print("\n".join(lines[:9]))


if __name__ == "__main__":
    main()
