"""E, post hoc (figure critic): transmitter share among core-carrying cells at fixed times, only where at least 1,000
cells carry the core, and the worlds that lost the core (fewer than 1,000 core cells at some sample after 20,000 steps).
Output: results/offset/SWITCH_TIMES.md"""
import glob
import json
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
rows = []
for f in sorted(glob.glob(os.path.join(HERE, "runs", "offset", "offset", "*.jsonl"))):
    r = [json.loads(x) for x in open(f)]
    c, t = r[0], pd.DataFrame(r[1:])
    t["n"] = t["R"] + t["T"]
    t["sh"] = t["T"] / t["n"].where(t["n"] >= 1000)
    row = {"L": c["L"], "tar": c["tar"], "mut": c["mut"], "start": c["start"], "seed": c["seed"],
           "lost_after_20k": bool(((t.step > 20000) & (t["n"] < 1000)).any())}
    for s in (20000, 100000, 300000):
        x = t[t.step == s]
        row[f"T_{s}"] = float(x.sh.iloc[0]) if len(x) and pd.notna(x.sh.iloc[0]) else float("nan")
    rows.append(row)
D = pd.DataFrame(rows)
lines = ["# E — transmitter share at fixed times (generated by `offset_switch_times.py`; post hoc)", "",
         "Share of transmitters among core-carrying cells, worlds with at least 1,000 core cells at that time; range over worlds (number of worlds).", "",
         "| L | tar | mutation | start | worlds | T at 20,000 | T at 100,000 | T at 300,000 | worlds that lost the core after 20,000 |", "|---|---|---|---|---|---|---|---|---|"]
for k, d in D.groupby(["L", "tar", "mut", "start"]):
    cells = []
    for s in (20000, 100000, 300000):
        v = d[f"T_{s}"].dropna()
        cells.append(f"{v.min():.2f}–{v.max():.2f} ({len(v)})" if len(v) else "– (0)")
    lines.append(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {len(d)} | " + " | ".join(cells) + f" | {int(d.lost_after_20k.sum())} |")
open(os.path.join(HERE, "results", "offset", "SWITCH_TIMES.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
