"""The copy period in natural populations (post hoc, motivated by REVISION_PREREG E): for every heritable cell scanned
in the population study (results/population/classes_cells.csv) whose first four bytes are a block-copy core of the
form `XX 5e ed b0` (copy offset XX) or `1e NN ed b0` (offset NN), the copy offset d = value mod 2L against the number of
transmissible sites. Also, in every final snapshot, the share of cells of each core family by offset class.
Output: results/offset/OFFSET_POPULATION.md, offset_cells.csv, offset_snapshots.csv.
"""
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "manuscript", "figures"))
import soup_stills as ss  # noqa: E402
from population_sample import STAGES  # noqa: E402


def offset_of(t, L):
    if t[1] == 0x5E and t[2] == 0xED and t[3] == 0xB0:
        return "XX 5e ed b0", int(t[0]) % (2 * L)
    if t[0] == 0x1E and t[2] == 0xED and t[3] == 0xB0:
        return "1e NN ed b0", int(t[1]) % (2 * L)
    return None, None


C = pd.read_csv(os.path.join(HERE, "results", "population", "classes_cells.csv"))
rows = []
for r in C.itertuples():
    t = np.array([int(b, 16) for b in r.tape.split()], np.uint8)
    fam, d = offset_of(t, r.L)
    if fam and r.confined:
        rows.append({"stage": r.stage, "L": r.L, "seed": r.seed, "snapshot": r.snapshot, "family": fam, "offset": d, "n_sites": r.n_sites, "n_unexec": r.n_sites_unexecuted, "tape": r.tape})
D = pd.DataFrame(rows)
D.to_csv(os.path.join(HERE, "results", "offset", "offset_cells.csv"), index=False)
lines = ["# The copy period in natural populations (generated by `offset_population.py`; post hoc)", "",
         "Confined heritable cells from the population scans whose first four bytes are a block-copy core; copy offset d = byte mod 2L; transmissible sites from the single-mutant scan.", "",
         "| L | copy offset d | cells | transmissible sites (median, IQR) | never executed (median) | prediction d − 4 (capped at L − 4) |", "|---|---|---|---|---|---|"]
for (L, d), e in D.groupby(["L", "offset"]):
    if len(e) < 3:
        continue
    q1, q3 = e.n_sites.quantile(0.25), e.n_sites.quantile(0.75)
    lines.append(f"| {L} | {d} | {len(e)} | {e.n_sites.median():.0f} ({q1:.0f}–{q3:.0f}) | {e.n_unexec.median():.0f} | {min(d, L) - 4} |")
if len(D):
    D["pred"] = np.minimum(D.offset, D.L) - 4
    ok = D[D.offset <= D.L]
    r = np.corrcoef(ok.pred, ok.n_sites)[0, 1] if len(ok) > 2 else np.nan
    lines += ["", f"- cells with d ≤ L: {len(ok)}; Pearson r between d − 4 and transmissible sites {r:.2f}"]
# snapshots: shares by offset class
srows = []
for st in ("G", "I", "K", "L"):
    runs_dir, csv, zh, abl = STAGES[st]
    g = pd.read_csv(csv)
    for _, w in g.iterrows():
        L, seed, label = int(w["L"]), int(w["seed"]), str(w["label"])
        snaps = [x for x in ss.snapshot_files(os.path.join(runs_dir, f"{label}_L{L}_st128_k4_s{seed}")) if x[0] == "final"]
        if not snaps:
            continue
        s = ss.load(snaps[0][2], L)
        core1 = (s[:, 1] == 0x5E) & (s[:, 2] == 0xED) & (s[:, 3] == 0xB0)
        core2 = (s[:, 0] == 0x1E) & (s[:, 2] == 0xED) & (s[:, 3] == 0xB0)
        d = np.where(core1, s[:, 0].astype(int) % (2 * L), np.where(core2, s[:, 1].astype(int) % (2 * L), -1))
        rec = {"stage": st, "L": L, "seed": seed, "core_share": float((d >= 0).mean()), "offset_L_share": float((d == L).mean())}
        for dd in (4, 8, 5, 10, 16):
            rec[f"offset_{dd}_share"] = float((d == dd).mean())
        srows.append(rec)
S = pd.DataFrame(srows)
S.to_csv(os.path.join(HERE, "results", "offset", "offset_snapshots.csv"), index=False)
lines += ["", "Final snapshots: share of all cells carrying a block-copy core, and among those the share with copy offset L (whole-tape copy).", "",
          "| stage | L | worlds | core-carrying cells (median) | of which offset L (median) | worlds where offset L is the majority of core cells |", "|---|---|---|---|---|---|"]
for (st, L), e in S.groupby(["stage", "L"]):
    frac = (e.offset_L_share / e.core_share.replace(0, np.nan))
    lines.append(f"| {st} | {L} | {len(e)} | {e.core_share.median():.2f} | {frac.median():.2f} | {int((frac > 0.5).sum())} |")
txt = "\n".join(lines)
open(os.path.join(HERE, "results", "offset", "OFFSET_POPULATION.md"), "w").write(txt + "\n")
print(txt)
