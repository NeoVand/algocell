"""N3 (descriptive, post hoc): how often each first founder's pointer enters its partner, and its writer's production
without the always-producer (supports two wording details of the text).

    .venv/bin/python lod_founder_entry.py      # results/lod/FOUNDER_ENTRY.md
"""
from __future__ import annotations

import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from lod_traj import classify_tapes  # noqa: E402

OUT = os.environ.get("LOD_OUT", os.path.join(HERE, "results", "lod"))


def main():
    F = pd.read_csv(os.path.join(OUT, "founders2.csv"))
    F1 = F[F["first"] == True].sort_values("seed")  # noqa: E712
    C = classify_tapes(sorted(set(F1.F_tape)))
    F1 = F1.assign(enter=[C[t]["enter"] for t in F1.F_tape], copy_share=[C[t]["copy"] for t in F1.F_tape], cls=[C[t]["class"] for t in F1.F_tape])
    md = ["# First founders: pointer entry and copying against 64 random partners (generated by `lod_founder_entry.py`)", "",
          f"- first founders: {len(F1)}; classed confined copier: {int((F1.cls == 'confined copier').sum())}",
          f"- share of encounters in which the founder's pointer enters the partner: max {F1.enter.max():.3f}; founders entering in none: {int((F1.enter == 0).sum())} of {len(F1)}",
          f"- copy share: median {F1.copy_share.median():.3f} (range {F1.copy_share.min():.3f}–{F1.copy_share.max():.3f})", ""]
    S = os.path.join(OUT, "founding.csv")
    if os.path.exists(S):
        D = pd.read_csv(S)
    for r in F1.itertuples():
        md.append(f"  - world {r.seed}: `{r.F_tape}` enter {r.enter:.3f}, copy {r.copy_share:.3f}, {r.cls}")
    open(os.path.join(OUT, "FOUNDER_ENTRY.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
