"""N3 (correction after the figure critic): first founders per world vs later founders, byte sources by role and class,
and a null from the soup's composition (share of non-copiers among cells at the last snapshot before each founder,
2,000 random cells classified as in lod_traj).   Output: results/lod/FOUNDERS2.md, founders2.csv"""
import ast
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
IND = os.environ.get("LOD_IND", os.path.join(HERE, "runs", "lod_v6_modal", "lod_v6"))   # paths only (N6 replication); definitions unchanged
OUTD = os.environ.get("LOD_OUT", os.path.join(HERE, "results", "lod"))
from lod_traj import classify_tapes  # noqa: E402

D = pd.read_csv(os.path.join(OUTD, "chain_v6b.csv")).drop_duplicates(["seed", "F_step", "F_tape"]).copy()
D["first"] = D.groupby("seed").F_step.transform("min") == D.F_step
rng = np.random.default_rng(3)
comp = {}
for r in D.itertuples():
    z = np.load(os.path.join(IND, f"L16_benign_s{r.seed}", "soups.npz"))
    k = np.where(z["steps"] < r.F_step)[0].max()
    key = (r.seed, int(z["steps"][k]))
    if key not in comp:
        S = z["soups"][k][rng.choice(len(z["soups"][k]), 2000, replace=False)]
        t = [" ".join(f"{x:02x}" for x in row) for row in S]
        C = classify_tapes(t)
        cl = pd.Series([C[x]["class"] for x in t]).value_counts(normalize=True)
        comp[key] = cl.to_dict()
    D.loc[r.Index, "soup_noncopier"] = comp[key].get("non-copier", 0)
    D.loc[r.Index, "soup_open"] = comp[key].get("open copier", 0)
    D.loc[r.Index, "soup_confined"] = comp[key].get("confined copier", 0)
    D.loc[r.Index, "snapshot"] = key[1]


def agg(E):
    tot = {}
    for r in E.itertuples():
        for k, v in ast.literal_eval(r.source_classes).items():
            tot[k] = tot.get(k, 0) + v
        for k, v in ast.literal_eval(r.sources).items():
            if k in ("mutation", "inherited from the last open copier"):
                tot[k] = tot.get(k, 0) + v
    n = sum(tot.values())
    return {k: round(v / n, 3) for k, v in sorted(tot.items())}, n


lines = ["# N3 correction: first founders and later founders (generated by `lod_founders2.py`)", "",
         "Chain start = the newest open copier older than the founder (corrected). First founder = the earliest founder in its world.", ""]
for name, E in (("first founders", D[D["first"]]), ("later founders", D[~D["first"]])):
    a, n = agg(E)
    nc = E.source_classes.apply(lambda s: ast.literal_eval(s).get("non-copier", 0)) / 16
    lines += [f"## {name}: {len(E)} in {E.seed.nunique()} worlds", "",
              f"- completed by: " + ", ".join(f"{k} {v}" for k, v in E.F_kind.value_counts().items()),
              f"- chain from the newest open copier: median {E.chain_records.median():.1f} records, {E.steps_elapsed.median():.1f} steps; only non-copiers between: {int((E.all_between_noncopiers == True).sum())} of {len(E)}",  # noqa: E712
              f"- distinct contributing events: median {E.contributing_events.median():.1f} (range {E.contributing_events.min()}–{E.contributing_events.max()})",
              f"- byte sources (share of {n} bytes): {a}",
              f"- per founder, share of bytes from non-copiers: median {nc.median():.2f}; soup share of non-copiers at the snapshot before: median {E.soup_noncopier.median():.2f}",
              f"- founders with a byte source in a confined copier: {int(E.source_classes.apply(lambda s: ast.literal_eval(s).get('confined copier', 0) > 0).sum())} of {len(E)}", ""]
open(os.path.join(OUTD, "FOUNDERS2.md"), "w").write("\n".join(lines) + "\n")
D.to_csv(os.path.join(OUTD, "founders2.csv"), index=False)
print("\n".join(lines))
