"""N3 (addition): was the copying instruction of the first confined copier inherited as data before it was executed?

For each line's robust transition (lod_traj): the first confined copier's copy instruction (a block move ED B0 / ED B8 /
ED A0 / ED A8 at an instruction start, or none) and its position; then, for every sampled ancestor on the line older
than the transition (within `window` steps), whether the same two bytes are present anywhere in the tape and whether
they are ever executed as an instruction start (against 64 random partners), as an operand only, or never fetched.

    .venv/bin/python lod_origin.py --indir runs/lod_v3_modal/lod_v3     # results/lod/ORIGIN.md, origin.csv
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp.optrace import execute_pairs_optrace  # noqa: E402
from lod_traj import classify_tapes  # noqa: E402

L = 16
MOVES = {(0xED, 0xB0): "LDIR", (0xED, 0xB8): "LDDR", (0xED, 0xA0): "LDI", (0xED, 0xA8): "LDD"}


def hx(t):
    return np.array([int(x, 16) for x in t.split()], np.uint8)


def roles(tapes: list[str], n: int = 64, seed: int = 5) -> dict:
    """Per tape: share of encounters (64 random partners) in which each own position is an instruction start, and in
    which it is fetched at all; plus how often the pointer enters the partner."""
    uniq = sorted(set(tapes))
    rng = np.random.default_rng(seed)
    P = rng.integers(0, 256, (n, L), dtype=np.uint8)
    out = {}
    for i in range(0, len(uniq), 256):
        chunk = uniq[i:i + 256]
        T = np.stack([hx(t) for t in chunk])
        res, fet, st = execute_pairs_optrace(np.concatenate([np.repeat(T, n, axis=0), np.tile(P, (len(chunk), 1))], 1), L)
        fet = fet.reshape(len(chunk), n, 2 * L)
        st = st.reshape(len(chunk), n, 2 * L)
        for j, t in enumerate(chunk):
            out[t] = {"start": st[j, :, :L].mean(0), "fetch": fet[j, :, :L].mean(0), "enter": float(fet[j, :, L:].any(1).mean())}
    return out


def copy_instruction(tape: np.ndarray, r: dict):
    """The block move executed as an instruction start in at least half of the encounters (first such), else None."""
    for p in range(L):
        key = (int(tape[p]), int(tape[(p + 1) % L]))
        if key in MOVES and r["start"][p] >= 0.5:
            return p, MOVES[key], key
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--indir", default=os.path.join(HERE, "runs", "lod_v3_modal", "lod_v3"))
    ap.add_argument("--out", default=os.path.join(HERE, "results", "lod"))
    ap.add_argument("--window", type=int, default=3000)
    ap.add_argument("--tag", default="")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    rows = []
    md = ["# N3 addition: was the copy instruction inherited as data before it was executed? (generated by `lod_origin.py`)", "",
          f"For each line: the first confined copier after the robust transition, its executed block move, and the sampled ancestors on the line in the {a.window:,} steps before it.", ""]
    for f in sorted(glob.glob(os.path.join(a.indir, "L16_benign_s*", "lod.json"))):
        D = json.load(open(f))
        R = D["result"]
        lines = D["lines"]["lines"]
        if not lines:
            continue
        alltapes = [t for ln in lines for t in ln.get("tapes", {}).values()]
        C = classify_tapes(alltapes)
        Rl = roles(alltapes)
        for ln in lines:
            steps = ln["steps"]
            seq = [(int(q), steps[int(q)], t, C[t]["class"]) for q, t in sorted(ln["tapes"].items(), key=lambda kv: int(kv[0]))]
            cls = np.array([s[3] == "confined copier" for s in seq])
            frac = np.cumsum(cls) / np.arange(1, len(cls) + 1)
            ok = np.where(frac >= 0.9)[0]
            if not len(ok):
                continue
            tr = int(ok.max())
            pre_open_i = next((i for i in range(tr + 1, len(seq)) if seq[i][3] == "open copier"), None)
            if pre_open_i is None:
                continue
            post_i = next((i for i in range(pre_open_i - 1, -1, -1) if seq[i][3] == "confined copier"), None)
            if post_i is None:
                continue
            post = seq[post_i]
            ci = copy_instruction(hx(post[2]), Rl[post[2]])
            row = {"seed": R["seed"], "cell": ln["cell"], "post_step": post[1], "post_tape": post[2], "copy_instr": ci[1] if ci else None,
                   "copy_pos": ci[0] if ci else None}
            if ci:
                key = ci[2]
                anc = [s for s in seq[pre_open_i:] if post[1] - s[1] <= a.window]
                has, as_start, as_fetch_only, never = 0, 0, 0, 0
                for s in anc:
                    t = hx(s[2])
                    pos = [p for p in range(L) if (int(t[p]), int(t[(p + 1) % L])) == key]
                    if not pos:
                        continue
                    has += 1
                    st = max(Rl[s[2]]["start"][p] for p in pos)
                    fe = max(Rl[s[2]]["fetch"][p] for p in pos)
                    if st >= 0.05:
                        as_start += 1
                    elif fe >= 0.05:
                        as_fetch_only += 1
                    else:
                        never += 1
                row.update({"ancestors": len(anc), "carry_bytes": has, "executed_as_instruction": as_start, "fetched_as_operand_only": as_fetch_only, "never_fetched": never,
                            "open_ancestors": sum(1 for s in anc if s[3] == "open copier")})
            rows.append(row)
    D = pd.DataFrame(rows)
    D.to_csv(os.path.join(a.out, f"origin{a.tag}.csv"), index=False)
    if len(D):
        D["key"] = D.post_step.astype(str) + "|" + D.post_tape
        for seed, e in D.groupby("seed"):
            md.append(f"## World {seed}")
            for key, g in e.groupby("key"):
                r = g.iloc[0]
                if r.copy_instr is None or (isinstance(r.copy_instr, float) and np.isnan(r.copy_instr)):
                    md.append(f"- {len(g)} lines: first confined copier at {r.post_step} `{r.post_tape}`: no block move at an instruction start")
                    continue
                md.append(f"- {len(g)} lines: first confined copier at {r.post_step} `{r.post_tape}`: {r.copy_instr} at position {int(r.copy_pos)}; "
                          f"of {int(r.ancestors)} sampled ancestors in the window ({int(r.open_ancestors)} open copiers), {int(r.carry_bytes)} carry its two bytes: "
                          f"executed as an instruction in {int(r.executed_as_instruction)}, fetched only as operand in {int(r.fetched_as_operand_only)}, never fetched in {int(r.never_fetched)}")
            md.append("")
    open(os.path.join(a.out, f"ORIGIN{a.tag}.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
