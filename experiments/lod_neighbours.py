"""N3 (exploratory, post hoc; a referee's control): are the founder's words `21 e3` and `21 e0` enriched among the one-byte
variants of the pusher's word `21 e5`, or typical of its mutational cloud?

For each first founder (founders2.csv, first == True), in the last soup snapshot before it (as lod_parts.py), the share of
cells carrying, anywhere and cyclically, each of the 510 one-byte variants of `21 e5` (first byte or second byte changed).
Reported: the shares of `21 e3` and `21 e0`, their rank among the 255 second-byte variants, and the median share of all
second-byte variants, per founder and summarised.

    .venv/bin/python lod_neighbours.py      # results/lod/NEIGHBOURS.md
"""
from __future__ import annotations

import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
IND = os.environ.get("LOD_IND", os.path.join(HERE, "runs", "lod_v6_modal", "lod_v6"))
OUT = os.environ.get("LOD_OUT", os.path.join(HERE, "results", "lod"))


def share_second(S: np.ndarray, w0: int) -> np.ndarray:
    """Share of cells carrying (w0, b) anywhere cyclically, for every b."""
    nxt = np.roll(S, -1, axis=1)
    out = np.zeros(256)
    hit = S == w0
    for b in range(256):
        out[b] = (hit & (nxt == b)).any(1).mean()
    return out


def share_first(S: np.ndarray, w1: int) -> np.ndarray:
    nxt = np.roll(S, -1, axis=1)
    out = np.zeros(256)
    hit = nxt == w1
    for a in range(256):
        out[a] = (hit & (S == a)).any(1).mean()
    return out


def main():
    F = pd.read_csv(os.path.join(OUT, "founders2.csv"))
    F1 = F[F["first"] == True].sort_values("seed")  # noqa: E712
    rows = []
    for r in F1.itertuples():
        z = np.load(os.path.join(IND, f"L16_benign_s{r.seed}", "soups.npz"))
        k = np.where(z["steps"] < r.F_step)[0]
        if not len(k):
            continue
        S = z["soups"][k.max()]
        sec = share_second(S, 0x21)
        fir = share_first(S, 0xE5)
        var2 = np.delete(sec, 0xE5)                      # the 255 second-byte variants
        var1 = np.delete(fir, 0x21)
        rank = lambda v: int((var2 > sec[v]).sum()) + 1  # 1 = commonest second-byte variant
        rows.append({"seed": r.seed, "snapshot": int(z["steps"][k.max()]), "e5": sec[0xE5], "e3": sec[0xE3], "e0": sec[0xE0],
                     "rank_e3": rank(0xE3), "rank_e0": rank(0xE0), "median_second": float(np.median(var2)),
                     "median_first": float(np.median(var1)), "top_second": f"21 {int(np.argsort(-np.where(np.arange(256) == 0xE5, -1, sec))[0]):02x}"})
    D = pd.DataFrame(rows)
    D.to_csv(os.path.join(OUT, "neighbours.csv"), index=False)
    md = ["# N3, exploratory: the founder's words among the one-byte variants of `21 e5` (generated by `lod_neighbours.py`)", "",
          f"- first founders: {len(D)}; last snapshot before each founder",
          f"- share of cells carrying `21 e5`: median {D.e5.median():.4f}",
          f"- `21 e3`: median {D.e3.median():.4f}; rank among the 255 second-byte variants: median {D.rank_e3.median():.0f} (range {D.rank_e3.min()}–{D.rank_e3.max()})",
          f"- `21 e0`: median {D.e0.median():.4f}; rank: median {D.rank_e0.median():.0f} (range {D.rank_e0.min()}–{D.rank_e0.max()})",
          f"- median share of a second-byte variant `21 XX`: {D.median_second.median():.4f}; of a first-byte variant `XX e5`: {D.median_first.median():.4f}",
          f"- ratio of `21 e3` to the median second-byte variant: median {(D.e3 / D.median_second).median():.1f}; of `21 e0`: {(D.e0 / D.median_second).median():.1f}",
          "", "| world | snapshot | 21 e5 | 21 e3 (rank) | 21 e0 (rank) | median 21 XX | commonest 21 XX |", "|---|---|---|---|---|---|---|"]
    for x in D.itertuples():
        md.append(f"| {x.seed} | {x.snapshot:,} | {x.e5:.4f} | {x.e3:.4f} ({x.rank_e3}) | {x.e0:.4f} ({x.rank_e0}) | {x.median_second:.4f} | `{x.top_second}` |")
    open(os.path.join(OUT, "NEIGHBOURS.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
