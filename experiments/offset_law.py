"""Proposition 8 against the population scans (post hoc): confined heritable block-copy cells by whether the copy offset
d divides L, and how many have exactly d - 4 transmissible sites. Output: results/offset/COPY_PERIOD_LAW.md"""
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
D = pd.read_csv(os.path.join(HERE, "results", "offset", "offset_cells.csv"))
gt = D[D.offset > D.L]
D = D[D.offset <= D.L].copy()
D["divides"] = (D.L % D.offset) == 0
ok = D[D.divides]
exact = int((ok.n_sites == ok.offset - 4).sum())
r = np.corrcoef(np.minimum(D.offset, D.L) - 4, D.n_sites)[0, 1]
lines = ["# The copy-period law against the population scans (generated by `offset_law.py`; post hoc)", "",
         f"- cells with d ≤ L: {len(D)}; with d dividing L: {len(ok)}; of these with exactly d − 4 transmissible sites: {exact} ({exact / len(ok):.3f}); Pearson r (all {len(D)}) between d − 4 and sites: {r:.2f}",
         f"- groups (L, d) with d | L: {ok.groupby(['L', 'offset']).ngroups}; median sites equal to d − 4 in {int((ok.groupby(['L', 'offset']).n_sites.median() == ok.groupby(['L', 'offset']).offset.first() - 4).sum())} of them",
         f"- cells with d not dividing L: {int((~D.divides).sum())}: " + "; ".join(f"L = {x.L}, d = {x.offset}, {x.n_sites} sites" for x in D[~D.divides].itertuples()),
         f"- cells with d > L (not covered): {len(gt)}"]
open(os.path.join(HERE, "results", "offset", "COPY_PERIOD_LAW.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
