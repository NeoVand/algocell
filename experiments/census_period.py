"""P — census of self-writers by period (registered: REVISION_PREREG.md R3/P, 2026-10-09).

    .venv/bin/python census_period.py --yes --period 3      # -> results/review_r2/census_p3.csv, CENSUS_P3.md

Every word of the given period (256^p words) tiled to 16 bytes is run for 128 instructions as organism against the
all-zero partner. A self-writer leaves the partner equal to the tape at some cyclic shift. Each self-writer is then
traced against the zero partner and 16 random partners: closed if no partner byte is fetched in any of the 17
encounters, open otherwise; also its culture-test heritability (32 partners).
"""
from __future__ import annotations

import argparse
import os
import sys
import time

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import assay as A  # noqa: E402
from algocell_exp import exectrace as X  # noqa: E402

L = 16


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--period", type=int, default=3)
    ap.add_argument("--chunk", type=int, default=1 << 20)
    ap.add_argument("--yes", action="store_true")
    a = ap.parse_args()
    if not a.yes:
        sys.exit("refusing to run: pass --yes after pausing the browser simulation (local GPU)")
    p = a.period
    total = 256 ** p
    reps = -(-L // p)
    hits = []
    t0 = time.time()
    for start in range(0, total, a.chunk):
        idx = np.arange(start, min(total, start + a.chunk), dtype=np.uint64)
        words = np.stack([((idx >> np.uint64(8 * (p - 1 - k))) & np.uint64(0xFF)).astype(np.uint8) for k in range(p)], 1)
        tapes = np.tile(words, (1, reps))[:, :L]
        pairs = np.concatenate([tapes, np.zeros_like(tapes)], 1)
        off = A.execute_pairs(pairs, L, 128)[:, L:]
        ok = np.zeros(len(tapes), bool)
        for s in range(L):
            ok |= (off == np.roll(tapes, s, axis=1)).all(axis=1)
        ok &= tapes.any(axis=1)
        hits += [tapes[i] for i in np.flatnonzero(ok)]
        if (start // a.chunk) % 4 == 0:
            print(f"{start + len(idx):,}/{total:,} words, {len(hits)} self-writers so far ({time.time() - t0:.0f} s)", flush=True)
    rows = []
    rng = np.random.default_rng([20261018, p])
    for t in hits:
        P = np.concatenate([np.zeros((1, L), np.uint8), rng.integers(0, 256, size=(16, L), dtype=np.uint8)])
        _, masks = X.execute_pairs_traced(np.concatenate([np.repeat(t[None], 17, 0), P], 1), L, 128)
        ent = X.exec_positions(masks, 2 * L)[:, L:].any(axis=1)
        r = A.assay_many(t[None], n=32, seed=1)[0]
        prim = min(q for q in range(1, p + 1) if p % q == 0 and np.array_equal(np.tile(t[:q], p // q), t[:p]))
        rows.append({"primitive_period": int(prim), "word": " ".join(f"{b:02x}" for b in t[:p]), "tape": " ".join(f"{b:02x}" for b in t), "closed": bool(~ent.any()), "entered_frac": float(ent.mean()),
                     "gen2": r["gen2_score"], "heritable": r["is_replicator"], "copies_q75": r["offspring_within_q"]})
    D = pd.DataFrame(rows)
    out = os.path.join(HERE, "results", "review_r2")
    D.to_csv(os.path.join(out, f"census_p{p}.csv"), index=False)
    lines = [f"# Census of period-{p} self-writers at L = 16 (generated by `census_period.py`)", "",
             (f"- by primitive period: " + "; ".join(f"period {q}: {int((D.primitive_period == q).sum())} ({int(D[D.primitive_period == q].closed.sum())} closed)" for q in sorted(D.primitive_period.unique())) if len(D) else "- none"),
             f"- words tested: {total:,}; self-writers against the zero partner (non-zero tapes): {len(D)}; closed: {int(D.closed.sum()) if len(D) else 0}; open: {int((~D.closed).sum()) if len(D) else 0}; "
             f"heritable by the culture test: {int(D.heritable.sum()) if len(D) else 0}"]
    if len(D):
        lines += ["", "| word | closed | partner entered (of 17) | gen2 | heritable |", "|---|---|---|---|---|"]
        lines += [f"| `{r.word}` | {r.closed} | {r.entered_frac:.2f} | {r.gen2:.2f} | {r.heritable} |" for r in D.sort_values(["closed", "gen2"], ascending=False).head(60).itertuples()]
    txt = "\n".join(lines)
    open(os.path.join(out, f"CENSUS_P{p}.md"), "w").write(txt + "\n")
    print(txt[:3000])


if __name__ == "__main__":
    main()
