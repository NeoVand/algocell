OUT = os.path.join(HERE, "results", "toxin")
OFF = os.path.join(HERE, "runs", "offset", "offset")
DIAL = os.path.join(HERE, "runs", "dial", "dial")
MIN_T = 100
P_OF = {"lp0": 0.0, "lp001": 0.01, "lp003": 0.03, "lp01": 0.1, "lp03": 0.3, "lp1": 1.0}


def spearman_perm(x, y, n=20000, seed=1):
    """Spearman rho and two-sided permutation P (no scipy in this environment)."""
    x, y = pd.Series(np.asarray(x, float)).rank().values, pd.Series(np.asarray(y, float)).rank().values
    r = float(np.corrcoef(x, y)[0, 1])
    rng = np.random.default_rng(seed)
    perm = np.array([np.corrcoef(x, rng.permutation(y))[0, 1] for _ in range(n)])
    return r, float((np.abs(perm) >= abs(r) - 1e-12).mean())


def payload_stats(P: np.ndarray) -> dict:
    """P: (n, m) payload bytes of n transmitter cells."""
    return {"n_T": len(P), "Z": float((P == 0x00).mean()), "H": float((P == 0x76).mean()),
            "n_distinct": int(len(np.unique(P, axis=0)))}


def e_worlds():
    rows, pos = [], []
    for f in sorted(glob.glob(os.path.join(OFF, "*_final.npy"))):
        m = re.match(r"L(\d+)_(benign|lethal)_mut(on|off)_(\w+?)_s(\d+)_final\.npy", os.path.basename(f))
        L, tar, mut, start, seed = int(m[1]), m[2], m[3], m[4], int(m[5])
        s = np.load(f)
        core, isR, isT = classify(s, L)
        P = s[isT][:, 4:L]
        r = {"L": L, "tar": tar, "mut": mut, "start": start, "seed": seed, "n_cells": len(s), "n_core": int(core.sum()),
             "n_R": int(isR.sum()), **payload_stats(P)}
        rows.append(r)
        if len(P) >= MIN_T:
            for j in range(P.shape[1]):
                pos.append({"L": L, "tar": tar, "mut": mut, "start": start, "seed": seed, "pos": j + 4,
                            "Z": float((P[:, j] == 0).mean()), "H": float((P[:, j] == 0x76).mean())})
    return pd.DataFrame(rows), pd.DataFrame(pos)


def dial_transmitters(s: np.ndarray, L: int = 16) -> np.ndarray:
    """Payloads of every cell carrying `XX 5e ed b0` with XX mod 2L = L at any cyclic shift (first match per cell)."""
    got = np.zeros(len(s), bool)
    sel = np.zeros_like(s)
    for k in range(L):
        r = np.roll(s, -k, axis=1)
        hit = (r[:, 1] == 0x5e) & (r[:, 2] == 0xed) & (r[:, 3] == 0xb0) & ((r[:, 0] % (2 * L)) == L) & ~got
        sel[hit] = r[hit]
        got |= hit
    return sel[got][:, 4:L]


def dial_worlds(t: int):
    rows = []
    for f in sorted(glob.glob(os.path.join(DIAL, f"*_t{t}.npy"))):
        m = re.match(r"(lp\d+)_s(\d+)_t\d+\.npy", os.path.basename(f))
        s = np.load(f)
        P = dial_transmitters(s)
        rows.append({"p": P_OF[m[1]], "seed": int(m[2]), "t": t, "n_cells": len(s), **payload_stats(P)})
    return pd.DataFrame(rows)


def composition():
    os.makedirs(OUT, exist_ok=True)
    W, POS = e_worlds()
    W.to_csv(os.path.join(OUT, "composition_worlds.csv"), index=False)
    POS.to_csv(os.path.join(OUT, "positions.csv"), index=False)
    D100 = dial_worlds(100000)
    D300 = dial_worlds(300000)
    pd.concat([D100, D300]).to_csv(os.path.join(OUT, "dial_worlds.csv"), index=False)
    null = 1 / 256
    lines = ["# N1 composition (generated by `payload_toxin.py --composition`)", "",
             f"Payload = positions 4 … L − 1 of transmitter cells; a world enters with ≥ {MIN_T} transmitters. Null (uniform bytes) = 1/256 = {null:.4f}.", "",
             "## Per world (E runs, final soups)", "",
             "| L | tar | mut | start | seed | transmitters | distinct payloads | Z (0x00) | H (0x76) |", "|---|---|---|---|---|---|---|---|---|"]
    for r in W.itertuples():
        lines.append(f"| {r.L} | {r.tar} | {r.mut} | {r.start} | {r.seed} | {r.n_T} | {r.n_distinct} | {r.Z:.4f} | {r.H:.4f} |")
    lines += ["", "## N1-1: H in benign mix50 mutation-on worlds (threshold 3/256 = 0.0117)", ""]
    for L in (32, 16):
        e = W[(W.L == L) & (W.tar == "benign") & (W.mut == "on") & (W.start == "mix50") & (W.n_T >= MIN_T)]
        lines.append(f"- L = {L}: {len(e)} worlds enter; H > 3/256 in {(e.H > 3 / 256).sum()}; median H = {e.H.median():.4f}" if len(e) else f"- L = {L}: no world enters")
    lines += ["", "## N1-2: median Z, lethal against benign (mix50, mutation on)", ""]
    for L in (32, 16):
        b = W[(W.L == L) & (W.tar == "benign") & (W.mut == "on") & (W.start == "mix50") & (W.n_T >= MIN_T)]
        le = W[(W.L == L) & (W.tar == "lethal") & (W.mut == "on") & (W.start == "mix50") & (W.n_T >= MIN_T)]
        if len(b) and len(le):
            lines.append(f"- L = {L}: lethal median Z = {le.Z.median():.4f} ({len(le)} worlds), benign median Z = {b.Z.median():.4f} ({len(b)} worlds); ratio = {le.Z.median() / max(b.Z.median(), 1e-9):.2f}")
        else:
            lines.append(f"- L = {L}: lethal worlds entering {len(le)}, benign {len(b)}")
    lines += ["", "## All starts, mutation on and off (medians over entering worlds)", "", "| L | tar | mut | start | worlds | median Z | median H |", "|---|---|---|---|---|---|---|"]
    for k, e in W[W.n_T >= MIN_T].groupby(["L", "tar", "mut", "start"]):
        lines.append(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | {len(e)} | {e.Z.median():.4f} | {e.H.median():.4f} |")
    lines += ["", "## N1-4: the lethality dial (L = 16), Z of transmitter payloads against p", ""]
    for t, D in ((100000, D100), (300000, D300)):
        e = D[D.n_T >= MIN_T]
        rho, pv = spearman_perm(e.p, e.Z) if len(e) > 3 else (np.nan, np.nan)
        lines.append(f"- t = {t:,}{' (registered)' if t == 100000 else ' (secondary)'}: {len(e)} worlds enter; Spearman ρ(p, Z) = {rho:.3f}, two-sided P = {pv:.3g} (one-sided P = {pv / 2 if rho > 0 else 1 - pv / 2:.3g})")
        lines += ["", "| p | worlds entering | median Z | median H | median transmitters |", "|---|---|---|---|---|"]
        for p, g in e.groupby("p"):
            lines.append(f"| {p:g} | {len(g)} | {g.Z.median():.4f} | {g.H.median():.4f} | {int(g.n_T.median())} |")
        lines.append("")
    lines += ["## Position profiles (mean over entering mutation-on mix50 worlds)", "", "| L | tar | position | Z | H |", "|---|---|---|---|---|"]
    if len(POS):
        for k, e in POS[(POS.mut == "on") & (POS.start == "mix50")].groupby(["L", "tar", "pos"]):
            lines.append(f"| {k[0]} | {k[1]} | {k[2]} | {e.Z.mean():.4f} | {e.H.mean():.4f} |")
    open(os.path.join(OUT, "COMPOSITION.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines[: 12 + len(W)]))
    print("\n".join(lines[12 + len(W):12 + len(W) + 40]))


TOXIC = np.array([0x00, 0x76], np.uint8)


def _redraw(rng, n):
    """n random bytes outside {0x00, 0x76}."""
    v = rng.integers(0, 254, n).astype(np.int64)
    v = v + (v >= 0x00) * 1          # skip 0x00
    v = v + (v >= 0x76) * 1          # skip 0x76
    return v.astype(np.uint8)


def variants(H, L, rng):
    """native, detox (payload 0x00/0x76 re-drawn outside the pair), sham (as many other payload positions re-drawn)."""
    nat = H.copy()
    det = H.copy()
    sha = H.copy()
    for i in range(len(H)):
        pay = H[i, 4:L]
        tox = np.where(np.isin(pay, TOXIC))[0]
        det[i, 4 + tox] = _redraw(rng, len(tox))
        other = np.where(~np.isin(pay, TOXIC))[0]
        k = min(len(tox), len(other))
        if k:
            pick = rng.choice(other, size=k, replace=False)
            sha[i, 4 + pick] = _redraw(rng, k)
    return {"native": nat, "detox": det, "sham": sha}


def causal(n_hosts=400, n_exec=64):
    from algocell_exp import exectrace as X
    os.makedirs(OUT, exist_ok=True)
    rng = np.random.default_rng(20261009)
    rows, haz = [], []
    for L in (32, 16):
        for tar in ("lethal", "benign"):
            files = sorted(glob.glob(os.path.join(OFF, f"L{L}_{tar}_muton_mix50_s*_final.npy")))
            soups = [np.load(f) for f in files]
            hosts, execs, wid = [], [], []
            per = -(-n_hosts // len(soups))
            for w, s in enumerate(soups):
                _, _, isT = classify(s, L)
                T = s[isT]
                if len(T) < MIN_T:
                    continue
                hosts.append(T[rng.integers(0, len(T), per)])
                execs.append(s[rng.integers(0, len(s), (per, n_exec))])
                wid += [w] * per
            Hn = np.concatenate(hosts)[:n_hosts]
            E = np.concatenate(execs)[:n_hosts]
            wid = np.array(wid[:n_hosts])
            V = variants(Hn, L, rng)
            zh = tar == "lethal"
            out = {}
            for name, Hv in V.items():
                B = np.repeat(Hv, n_exec, axis=0)
                A = E.reshape(-1, L)
                res, m = X.execute_pairs_traced(np.concatenate([A, B], 1), L, 128, zero_halts=zh)
                ex = X.exec_positions(m, 2 * L)
                Bp = res[:, L:]
                intact = (Bp == B).all(1).reshape(len(Hv), n_exec)
                core, isR, isT = classify(Bp, L)
                keep = isT.reshape(len(Hv), n_exec)
                entered = ex[:, L:].any(1).reshape(len(Hv), n_exec)
                out[name] = (intact, keep, entered, ex[:, L:].reshape(len(Hv), n_exec, L))
                # owner side: host as A against random partners of its soup
                P = E.reshape(-1, L)[np.random.default_rng(5).permutation(len(Hv) * n_exec)]
                resA, mA = X.execute_pairs_traced(np.concatenate([np.repeat(Hv, n_exec, axis=0), P], 1), L, 128, zero_halts=zh)
                exA = X.exec_positions(mA, 2 * L)
                copy_exact = (resA[:, L:] == np.repeat(Hv, n_exec, axis=0)).all(1).reshape(len(Hv), n_exec)
                own_payload_fetched = exA[:, 4:L].any(1).mean()
                rows.append({"L": L, "tar": tar, "variant": name, "hosts": len(Hv), "intact": intact.mean(), "keeps_T": keep.mean(),
                             "entered": entered.mean(), "intact_if_entered": intact[entered].mean() if entered.any() else np.nan,
                             "copy_exact_as_A": copy_exact.mean(), "own_payload_fetched_as_A": own_payload_fetched,
                             "toxic_per_host": float(np.isin(Hv[:, 4:L], TOXIC).sum(1).mean())})
            # paired host-level differences, bootstrap over hosts
            for a, b in (("native", "detox"), ("native", "sham")):
                for metric, k in (("intact", 0), ("keeps_T", 1)):
                    d = out[a][k].mean(1) - out[b][k].mean(1)
                    has = np.isin(Hn[:, 4:L], TOXIC).any(1)
                    bs = [d[rng.integers(0, len(d), len(d))].mean() for _ in range(4000)]
                    bsh = [d[has][rng.integers(0, has.sum(), has.sum())].mean() for _ in range(4000)] if has.sum() > 5 else [np.nan]
                    rows.append({"L": L, "tar": tar, "variant": f"{a}-{b}", "metric": metric, "diff": d.mean(), "lo": np.percentile(bs, 2.5), "hi": np.percentile(bs, 97.5),
                                 "diff_toxic_hosts": d[has].mean() if has.any() else np.nan, "lo_t": np.nanpercentile(bsh, 2.5), "hi_t": np.nanpercentile(bsh, 97.5), "n_toxic_hosts": int(has.sum())})
            # hazard: per payload position, share of entering executors (native hosts) that fetched it; halting bytes there
            intact, keep, entered, exB = out["native"]
            fetched = exB[entered]
            h = fetched.mean(0)
            tox_share = np.isin(Hn[:, :], TOXIC if tar == "lethal" else np.array([0x76], np.uint8)).mean(0)
            for j in range(4, L):
                haz.append({"L": L, "tar": tar, "pos": j, "hazard": h[j], "halting_share": tox_share[j], "zero_share": (Hn[:, j] == 0).mean()})
    C = pd.DataFrame(rows)
    Hz = pd.DataFrame(haz)
    C.to_csv(os.path.join(OUT, "causal.csv"), index=False)
    Hz.to_csv(os.path.join(OUT, "hazard.csv"), index=False)
    lines = ["# N1-3 and N1-6 (generated by `payload_toxin.py --causal`)", "",
             f"Hosts: {n_hosts} transmitter cells per condition from the mix50 mutation-on final soups (in proportion to abundance); each host is partner B of {n_exec} executors drawn from its own soup, under the soup's rule; owner side: host as A against {n_exec} partners.", "",
             "| L | tar | variant | toxic bytes per host | intact | keeps T | executor entered | intact if entered | copy exact as A | own payload fetched as A |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in C[C.metric.isna()].itertuples():
        lines.append(f"| {r.L} | {r.tar} | {r.variant} | {r.toxic_per_host:.2f} | {r.intact:.4f} | {r.keeps_T:.4f} | {r.entered:.4f} | {r.intact_if_entered:.4f} | {r.copy_exact_as_A:.4f} | {r.own_payload_fetched_as_A:.4f} |")
    lines += ["", "## Paired differences (mean over hosts; bootstrap 95% CI over hosts)", "", "| L | tar | contrast | metric | all hosts | 95% CI | hosts carrying a halting byte | 95% CI | n |", "|---|---|---|---|---|---|---|---|---|"]
    for r in C[C.metric.notna()].itertuples():
        lines.append(f"| {r.L} | {r.tar} | {r.variant} | {r.metric} | {r.diff:+.4f} | [{r.lo:+.4f}, {r.hi:+.4f}] | {r.diff_toxic_hosts:+.4f} | [{r.lo_t:+.4f}, {r.hi_t:+.4f}] | {r.n_toxic_hosts} |")
    lines += ["", "## N1-3: hazard against halting bytes by payload position (Spearman over positions)", ""]
    for (L, tar), e in Hz.groupby(["L", "tar"]):
        rho, pv = spearman_perm(e.hazard, e.halting_share, n=5000)
        rz, pz = spearman_perm(e.pos, e.zero_share, n=5000)
        lines.append(f"- L = {L}, {tar}: ρ(hazard, halting share) = {rho:+.3f} (P = {pv:.3g}); ρ(position, zero share) = {rz:+.3f} (P = {pz:.3g}); hazard by position: " + " ".join(f"{v:.2f}" for v in e.hazard.values))
    open(os.path.join(OUT, "CAUSAL.md"), "w").write("\n".join(lines) + "\n")
    print("\n".join(lines))


