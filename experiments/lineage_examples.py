"""Third report, heredity audit: parent -> offspring -> granddaughter byte sequences for each kind of replicator at L = 16,
against three random partners each (benign rule), with the culture-test verdict (gen2) and whether each copy is exact.
Output: results/review_r2/LINEAGES.md"""
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from algocell_exp import assay as A  # noqa: E402

L = 16
gi = pd.read_csv(os.path.join(HERE, "results", "stageI", "stageI", "stage_g_runs.csv"))
s4009 = gi[gi.seed == 4009].final_tape.iloc[0]
rng0 = np.random.default_rng(20261019)
tT = rng0.integers(0, 256, 12, dtype=np.uint8)
tS = rng0.integers(0, 256, 10, dtype=np.uint8)
hx = lambda t: " ".join(f"{b:02x}" for b in t)  # noqa: E731
P = [("pusher (open first replicator)", " ".join(["01 c5"] * 8), False),
     ("return closer (regenerator)", "ad e3 21 e3 21 c0 ad c0 ad e3 21 e3 21 c0 ad c0", False),
     ("block-copy R (regenerator, offset 4)", " ".join(["44 5e ed b0"] * 4), False),
     ("block-copy R with a mutation at byte 9", "44 5e ed b0 44 5e ed b0 44 77 ed b0 44 5e ed b0", False),
     ("block-copy T (transmitter, offset 16)", "b0 5e ed b0 " + hx(tT), False),
     ("lethal-tar closer of world 4009 (lethal rule)", s4009, True),
     ("self-initialising closer (transmitter)", "2e 00 1e 10 ed b0 " + hx(tS), False)]
rng = np.random.default_rng(7)
lines = ["# Parent, offspring and granddaughter sequences (generated by `lineage_examples.py`)", "",
         "Each parent runs as organism against a random partner; its offspring (the partner afterwards) runs against a fresh random partner, giving the granddaughter. Three independent lineages per parent; `=` marks a copy identical to the parent. gen2 and copies from the culture test (64 partners).", ""]
for name, t, zh in P:
    x = np.array([int(b, 16) for b in t.split()], np.uint8)
    r = A.assay_many(x[None], n=64, seed=11, zero_halts=zh)[0]
    lines += [f"**{name}** — parent `{hx(x)}`; gen2 {r['gen2_score']:.2f}, heritable {r['is_replicator']}", ""]
    for k in range(3):
        p1, p2 = rng.integers(0, 256, (2, L), dtype=np.uint8)
        o = A.execute_pairs(np.concatenate([x, p1])[None], L, 128, zero_halts=zh)[0, L:]
        g = A.execute_pairs(np.concatenate([o, p2])[None], L, 128, zero_halts=zh)[0, L:]
        fo = "=" if (o == x).all() else f"`{hx(o)}`"
        fg = "=" if (g == x).all() else f"`{hx(g)}`"
        lines.append(f"- lineage {k + 1}: offspring {fo}; granddaughter {fg}")
    lines.append("")
open(os.path.join(HERE, "results", "review_r2", "LINEAGES.md"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
