"""N2 (addition): class composition of the 20 L = 32 mix50 final soups the demography started from.

Classes by the first four bytes, as in n2_demography.cls: O (no core), M (core with another first byte), R, T.

    .venv/bin/python n2_composition.py      # results/n2/COMPOSITION_START.md
"""
from __future__ import annotations

import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from offset_switch import classify  # noqa: E402

OFF = os.path.join(HERE, "runs", "offset", "offset")
OUT = os.path.join(HERE, "results", "n2")
L = 32


def main():
    rows = []
    for comp in ("benign", "lethal"):
        for seed in range(1, 11):
            f = os.path.join(OFF, f"L32_{comp}_muton_mix50_s{seed}_final.npy")
            if not os.path.exists(f):
                continue
            s = np.load(f)
            core, isR, isT = classify(s, L)
            rows.append((comp, seed, 1 - core.mean(), (core & ~isR & ~isT).mean(), isR.mean(), isT.mean()))
    md = ["# N2: class composition of the starting soups (generated by `n2_composition.py`)", "",
          "| soup | seed | O (no core) | M | R | T |", "|---|---|---|---|---|---|"]
    md += [f"| {c} | {sd} | {o:.3f} | {m:.3f} | {r:.3f} | {t:.3f} |" for c, sd, o, m, r, t in rows]
    O = np.array([r[2] for r in rows])
    md += ["", f"- soups: {len(rows)}; core-free share: {O.min():.3f}–{O.max():.3f} (median {np.median(O):.3f})"]
    for comp in ("benign", "lethal"):
        o = np.array([r[2] for r in rows if r[0] == comp])
        md.append(f"- {comp}: core-free {o.min():.3f}–{o.max():.3f}")
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, "COMPOSITION_START.md"), "w").write("\n".join(md) + "\n")
    print("\n".join(md[-4:]))


if __name__ == "__main__":
    main()
